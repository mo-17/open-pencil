export function buildTaroConfig(projectName: string): string {
  return `import { defineConfig, type UserConfigExport } from '@tarojs/cli'

export default defineConfig<'webpack5'>(async (merge) => {
  const base: UserConfigExport<'webpack5'> = {
    projectName: ${JSON.stringify(projectName)},
    date: '2026-08-19',
    designWidth: 750,
    deviceRatio: { 375: 2, 640: 1.17, 750: 1, 828: 0.905 },
    sourceRoot: 'src',
    outputRoot: 'dist',
    framework: 'react',
    compiler: 'webpack5',
    cache: { enable: false },
    mini: {
      postcss: {
        pxtransform: { enable: true },
        url: { enable: true, config: { limit: 0 } },
        cssModules: { enable: false }
      }
    }
  }
  return merge({}, base)
})
`
}

