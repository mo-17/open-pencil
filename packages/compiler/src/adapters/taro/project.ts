      '@tarojs/plugin-platform-weapp': TARO_VERSION,
      '@tarojs/react': TARO_VERSION,
      '@tarojs/runtime': TARO_VERSION,
      '@tarojs/shared': TARO_VERSION,
      '@tarojs/taro': TARO_VERSION,
