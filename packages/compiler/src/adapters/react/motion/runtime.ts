function blendAdvancedEffects(
  from: MotionAdvancedEffectTarget[],
  to: MotionAdvancedEffectTarget[],
  progress: number
): MotionAdvancedEffectTarget[] {
  return from.map((value, index) => {
    const next = to[index]
    if (value.kind === 'blur') {
      return {
        kind: value.kind,
        index: value.index,
        radius: interpolateAdvancedNumber(
          value.radius,
          next?.kind === 'blur' ? next.radius : value.radius,
          progress
        )
      }
    }
    const shadow = next?.kind === 'shadow' ? next : value
    return {
      kind: value.kind,
      index: value.index,
      x: interpolateAdvancedNumber(value.x, shadow.x, progress),
      y: interpolateAdvancedNumber(value.y, shadow.y, progress),
      blur: interpolateAdvancedNumber(value.blur, shadow.blur, progress),
      spread: interpolateAdvancedNumber(value.spread, shadow.spread, progress),
      color: interpolateAdvancedColor(value.color, shadow.color, progress)
    }
  })
}

