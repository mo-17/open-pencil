const advancedPathNumber = /-?(?:\\d+\\.?\\d*|\\.\\d+)(?:e[-+]?\\d+)?/gi

function blendAdvancedPath(from: string, to: string, progress: number): string {
  const toNumbers = [...to.matchAll(advancedPathNumber)].map((match) => Number(match[0]))
  let index = 0
  return from.replace(advancedPathNumber, (token) => {
    const start = Number(token)
    const end = toNumbers[index++]
    if (!Number.isFinite(start) || !Number.isFinite(end)) return token
    return String(Math.round(interpolateAdvancedNumber(start, end, progress) * 1e6) / 1e6)
  })
}

function blendAdvancedVector(
  from: { topologyId: string; paths: string[] },
  to: { topologyId: string; paths: string[] },
  progress: number
): { topologyId: string; paths: string[] } {
  return {
    topologyId: from.topologyId,
    paths: from.paths.map((path, index) =>
      blendAdvancedPath(path, to.paths[index] ?? path, progress)
    )
  }
}

