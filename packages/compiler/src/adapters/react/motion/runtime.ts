function runtimeTrack(
  track: IRMotionTrack,
  token: string,
  index: number,
  motion: IRMotion
): unknown {
  const sourceIndex = track.composition?.sourceIndex ?? motion.tracks.indexOf(track)
  const composition =
    motion.version === 3
      ? {
          mode: track.composition?.mode ?? 'replace',
          weight: track.composition?.weight ?? 1,
          priority: track.composition?.priority ?? 0,
          sourceIndex,
          clock: motionCompositionClockVariableName(token, sourceIndex),
          weightVariable: motionCompositionWeightVariableName(token, sourceIndex),
          variables: Object.fromEntries(
            motionCompositionChannels(track).map((channel) => [
              channel,
              motionCompositionVariableName(token, sourceIndex, channel)
            ])
          ),
          sampling: {
            easing: track.timing.easing,
            keyframes: track.keyframes.map((frame) => ({
              offset: frame.offset,
              values: Object.fromEntries(
                motionCompositionChannels(track).flatMap((channel) =>
                  frame[channel] === undefined ? [] : [[channel, frame[channel]]]
                )
              ),
              ...(frame.easing ? { easing: frame.easing } : {})
            }))
          }
        }
      : undefined
  const advanced = runtimeAdvancedTrack(track, motion)
  return {
    id: track.id,
    trigger: track.trigger,
    exit: track.exit,
    keyframes: track.keyframes.map((frame) =>
      runtimeKeyframe(frame, track, motion, token, sourceIndex)
    ),
    timing: {
      duration: track.timing.durationMs,
      delay: track.timing.delayMs,
      easing: easingCss(track.timing.easing),
      iterations: track.timing.iterations,
      direction: track.timing.direction,
      fill: track.timing.fill
    },
    ...(composition ? { composition } : {}),
    ...(advanced ? { advanced } : {}),
    ...(motion.version !== 3 &&
    (track.trigger === 'mount' || track.trigger === 'pageEnter' || track.trigger === 'loop')
      ? {
          css: {
            variable: motionCssVariableName(token, index),
            animationNames: [
              motionCssAnimationName(token, index),
              motionCssAnimationName(token, index, true)
            ]
          }
        }
      : {})
  }
}

const ADVANCED_FRAME_KEYS = [
  'paints',
  'gradientStops',
  'effects',
  'cornerRadii',
  'textReveal',
  'fontAxes',
  'vectorMorph'
] as const

function runtimeAdvancedTrack(track: IRMotionTrack, motion: IRMotion): unknown {
  if (
    motion.version !== 3 ||
    !motion.target ||
    !track.keyframes.some((frame) => ADVANCED_FRAME_KEYS.some((key) => frame[key] !== undefined))
  ) {
    return undefined
  }
  return {
    target: motion.target,
    easing: track.timing.easing,
    keyframes: track.keyframes.map(runtimeAdvancedFrame)
  }
}

function runtimeAdvancedFrame(frame: IRMotionKeyframe): Record<string, unknown> {
  const result: Record<string, unknown> = { offset: frame.offset }
  for (const key of ADVANCED_FRAME_KEYS) {
    const value = frame[key]
    if (value === undefined) continue
    result[key] =
      key === 'vectorMorph' && frame.vectorMorph
        ? { topologyId: frame.vectorMorph.topologyId, paths: frame.vectorMorph.paths }
        : value
  }
  if (frame.easing) result.easing = frame.easing
  return result
}

function runtimeKeyframe(
  frame: IRMotionKeyframe,
  track: IRMotionTrack,
  motion: IRMotion,
  token: string,
  sourceIndex: number
): Record<string, string | number> {
  const hasPath = frame.pathProgress !== undefined && track.path !== undefined
  return {
    offset: frame.offset,
    ...(motion.version === 3
      ? runtimeStaticTransformFrame(frame, hasPath)
      : runtimeTransformFrame(frame, hasPath)),
    ...(motion.version === 3
      ? {
          [motionCompositionClockVariableName(token, sourceIndex)]: frame.offset,
          ...runtimeSampledPathCompositionFrame(frame, track, token, sourceIndex)
        }
      : {}),
    ...runtimePaintFrame(frame, motion),
    ...runtimePathFrame(frame, track, motion),
    ...runtimeLayoutFrame(frame),
    ...(frame.easing ? { easing: easingCss(frame.easing) } : {})
  }
}

function runtimeSampledPathCompositionFrame(
  frame: IRMotionKeyframe,
  track: IRMotionTrack,
  token: string,
  sourceIndex: number
): Record<string, number> {
  if (!track.sampledPath) return {}
  return Object.fromEntries(
    motionCompositionChannels(track).flatMap((channel) =>
      frame[channel] === undefined
        ? []
        : [[motionCompositionVariableName(token, sourceIndex, channel), frame[channel]]]
    )
  )
}

function runtimeStaticTransformFrame(
  frame: IRMotionKeyframe,
  pathOwnsTranslation: boolean
): Record<string, string | number> {
  const result = runtimeTransformFrame(frame, pathOwnsTranslation)
  delete result.opacity
  delete result.translate
  delete result.scale
  delete result.rotate
  return result
}

function runtimeTransformFrame(
  frame: IRMotionKeyframe,
  pathOwnsTranslation = false
): Record<string, string | number> {
  return {
    ...(frame.opacity !== undefined ? { opacity: frame.opacity } : {}),
    ...(!pathOwnsTranslation && (frame.x !== undefined || frame.y !== undefined)
      ? { translate: `${frame.x ?? 0}px ${frame.y ?? 0}px` }
      : {}),
    ...(frame.scaleX !== undefined || frame.scaleY !== undefined
      ? { scale: `${frame.scaleX ?? 1} ${frame.scaleY ?? 1}` }
      : {}),
    ...(frame.rotate !== undefined ? { rotate: `${frame.rotate}deg` } : {}),
    ...(frame.originX !== undefined || frame.originY !== undefined
      ? { transformOrigin: `${(frame.originX ?? 0.5) * 100}% ${(frame.originY ?? 0.5) * 100}%` }
      : {}),
    ...(frame.width !== undefined ? { width: `${frame.width}px` } : {}),
    ...(frame.height !== undefined ? { height: `${frame.height}px` } : {}),
    ...(frame.cornerRadius !== undefined ? { borderRadius: `${frame.cornerRadius}px` } : {})
  }
}

function runtimePaintFrame(frame: IRMotionKeyframe, motion: IRMotion): Record<string, string> {
  const kind = motionTargetKind(motion)
  const result: Record<string, string> = {}
  addRuntimePaintColors(result, frame, motion, kind)
  addRuntimeEffects(result, frame, kind)
  return result
}

function addRuntimePaintColors(
  result: Record<string, string>,
  frame: IRMotionKeyframe,
  motion: IRMotion,
  kind: ReturnType<typeof motionTargetKind>
): void {
  const target = motion.target
  if (frame.fillColor && target?.fillColor) {
    result[RUNTIME_FILL_PROPERTY[kind]] = colorToCSS(frame.fillColor)
  }
  if (frame.strokeColor && target?.strokeColor) {
    result[RUNTIME_STROKE_PROPERTY[kind]] = colorToCSS(frame.strokeColor)
  }
  if (frame.strokeWidth !== undefined && target?.strokeWidth !== undefined) {
    result[RUNTIME_STROKE_WIDTH_PROPERTY[kind]] =
      `${frame.strokeWidth}${kind === 'vector' ? '' : 'px'}`
  }
}

function addRuntimeEffects(
  result: Record<string, string>,
  frame: IRMotionKeyframe,
  kind: ReturnType<typeof motionTargetKind>
): void {
  const hasShadow = runtimeFrameHasShadow(frame)
  if (kind === 'vector') {
    const filters: string[] = []
    if (frame.blur !== undefined) filters.push(`blur(${frame.blur}px)`)
    if (hasShadow) filters.push(runtimeVectorDropShadow(frame))
    if (filters.length > 0) result.filter = filters.join(' ')
  } else if (frame.blur !== undefined) {
    result.filter = `blur(${frame.blur}px)`
  }
  if (hasShadow && kind === 'text') result.textShadow = runtimeTextShadow(frame)
  else if (hasShadow && kind === 'box') result.boxShadow = runtimeBoxShadow(frame)
}

function runtimeFrameHasShadow(frame: IRMotionKeyframe): boolean {
  return (
    frame.shadowX !== undefined ||
    frame.shadowY !== undefined ||
    frame.shadowBlur !== undefined ||
    frame.shadowSpread !== undefined ||
    frame.shadowColor !== undefined
  )
}

const RUNTIME_FILL_PROPERTY = {
  box: 'backgroundColor',
  text: 'color',
  vector: VECTOR_MOTION_FILL
} as const

const RUNTIME_STROKE_PROPERTY = {
  box: 'borderColor',
  text: 'WebkitTextStrokeColor',
  vector: VECTOR_MOTION_STROKE
} as const

const RUNTIME_STROKE_WIDTH_PROPERTY = {
  box: 'borderWidth',
  text: 'WebkitTextStrokeWidth',
  vector: VECTOR_MOTION_STROKE_WIDTH
} as const

function runtimePathFrame(
  frame: IRMotionKeyframe,
  track: IRMotionTrack,
  motion: IRMotion
): Record<string, string> {
  const result: Record<string, string> = {
    ...(frame.pathProgress !== undefined && track.path ? runtimeMotionPathFrame(frame, track) : {}),
    ...(motionTargetKind(motion) === 'vector' &&
    motion.target?.strokeColor &&
    (frame.trimStart !== undefined || frame.trimEnd !== undefined)
      ? {
          [VECTOR_MOTION_TRIM_VISIBLE]: String(
            Math.max(0, (frame.trimEnd ?? 1) - (frame.trimStart ?? 0))
          ),
          [VECTOR_MOTION_TRIM_HIDDEN]: String(
            1 - Math.max(0, (frame.trimEnd ?? 1) - (frame.trimStart ?? 0))
          ),
          [VECTOR_MOTION_TRIM_OFFSET]: String(-((frame.trimStart ?? 0) + (frame.trimOffset ?? 0)))
        }
      : {})
  }
  return result
}

function runtimeMotionPathFrame(
  frame: IRMotionKeyframe,
  track: IRMotionTrack
): Record<string, string> {
  const originX = frame.originX ?? 0.5
  const originY = frame.originY ?? 0.5
  const anchorX = (frame.width ?? 0) * originX + (frame.x ?? 0)
  const anchorY = (frame.height ?? 0) * originY + (frame.y ?? 0)
  return {
    offsetPath: runtimeOffsetPath(track.path?.points ?? [], anchorX, anchorY),
    offsetDistance: `${(frame.pathProgress ?? 0) * 100}%`,
    offsetAnchor: `${originX * 100}% ${originY * 100}%`,
    offsetRotate: track.path?.autoRotate ? 'auto' : '0deg'
  }
}

function runtimeBoxShadow(frame: IRMotionKeyframe): string {
  return `${frame.shadowX ?? 0}px ${frame.shadowY ?? 0}px ${frame.shadowBlur ?? 0}px ${frame.shadowSpread ?? 0}px ${colorToCSS(frame.shadowColor ?? TRANSPARENT)}`
}

function runtimeTextShadow(frame: IRMotionKeyframe): string {
  return `${frame.shadowX ?? 0}px ${frame.shadowY ?? 0}px ${runtimeSpreadlessShadowBlur(frame)}px ${colorToCSS(frame.shadowColor ?? TRANSPARENT)}`
}

function runtimeVectorDropShadow(frame: IRMotionKeyframe): string {
  return `drop-shadow(${frame.shadowX ?? 0}px ${frame.shadowY ?? 0}px ${runtimeSpreadlessShadowBlur(frame)}px ${colorToCSS(frame.shadowColor ?? TRANSPARENT)})`
}

function runtimeSpreadlessShadowBlur(frame: IRMotionKeyframe): number {
  return Math.max(0, (frame.shadowBlur ?? 0) + (frame.shadowSpread ?? 0))
}

function runtimeLayoutFrame(frame: IRMotionKeyframe): Record<string, string> {
  return {
    ...(frame.gap !== undefined ? { gap: `${frame.gap}px` } : {}),
    ...(frame.rowGap !== undefined ? { rowGap: `${frame.rowGap}px` } : {}),
    ...(frame.columnGap !== undefined ? { columnGap: `${frame.columnGap}px` } : {}),
    ...(frame.paddingTop !== undefined ? { paddingTop: `${frame.paddingTop}px` } : {}),
    ...(frame.paddingRight !== undefined ? { paddingRight: `${frame.paddingRight}px` } : {}),
    ...(frame.paddingBottom !== undefined ? { paddingBottom: `${frame.paddingBottom}px` } : {}),
    ...(frame.paddingLeft !== undefined ? { paddingLeft: `${frame.paddingLeft}px` } : {})
  }
}

function runtimeOffsetPath(
  points: NonNullable<IRMotionTrack['path']>['points'],
  anchorX: number,
  anchorY: number
): string {
  const [first, ...rest] = points
  return `path("${[
    `M ${first.x + anchorX} ${first.y + anchorY}`,
    ...rest.map((point) => `L ${point.x + anchorX} ${point.y + anchorY}`)
  ].join(' ')}")`
}
