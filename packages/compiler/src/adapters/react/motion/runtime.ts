function specFor(element: Element): MotionSpec | undefined {
  const token = element.getAttribute('data-op-motion')
  return token ? registry[token] : undefined
}

function managedSpecFor(element: Element): MotionSpec | undefined {
  const token = element.getAttribute('data-op-motion')
  return token && runtimeTokens.has(token) ? registry[token] : undefined
}

function matchingElements(
  root: ParentNode,
  targetNodeId: string,
  includeCssOnly = false
): Element[] {
  const elements: Element[] = []
  if (root instanceof Element && root.matches(selector)) elements.push(root)
  elements.push(...root.querySelectorAll(selector))
  return elements.filter(
    (element) =>
      element.getAttribute('data-node-id') === targetNodeId &&
      (includeCssOnly ? specFor(element) : managedSpecFor(element))
  )
}

function elementsForNodeId(
  targetNodeId: string,
  scope?: Element,
  includeCssOnly = false
): Element[] {
  if (!runtimeDocument || typeof targetNodeId !== 'string' || targetNodeId.length === 0) return []
  if (scope instanceof Element) {
    let localRoot = scope.closest('[data-op-motion-scope]')
    if (!localRoot) {
      const scoped = matchingElements(scope, targetNodeId, includeCssOnly)
      if (scoped.length > 0) return scoped
    }
    while (localRoot) {
      const scoped = matchingElements(localRoot, targetNodeId, includeCssOnly)
      if (scoped.length > 0) return scoped
      localRoot = localRoot.parentElement?.closest('[data-op-motion-scope]') ?? null
    }
  }
  return matchingElements(runtimeDocument, targetNodeId, includeCssOnly)
}

function motionElements(target: EventTarget | null): Element[] {
  if (!(target instanceof Element)) return []
  const elements: Element[] = []
  for (let element: Element | null = target; element; element = element.parentElement) {
    if (element.matches(selector) && managedSpecFor(element)) elements.push(element)
  }
  return elements
}

