function captureAdvancedSnapshot(element: Element): MotionAdvancedSnapshot {
  const existing = advancedSnapshots.get(element)
  if (existing) return existing
  const style = cssStyleFor(element)
  const styles = style
    ? advancedStyleNames.map((name) => ({
        name,
        value: style.getPropertyValue(name),
        priority: style.getPropertyPriority(name)
      }))
    : []
  const attributes = advancedGeometry(element).flatMap((geometry) =>
    advancedGeometryAttributeNames.map((name) => ({
      element: geometry,
      name,
      value: geometry.getAttribute(name)
    }))
  )
  const text: MotionAdvancedTextSnapshot[] = []
  if (runtimeDocument) {
    const walker = runtimeDocument.createTreeWalker(element, 4)
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      text.push({ node: node as Text, value: node.nodeValue ?? '' })
    }
  }
  const snapshot = { styles, attributes, text }
  advancedSnapshots.set(element, snapshot)
  return snapshot
}

function restoreAdvancedSnapshot(element: Element, forget = false): void {
  const snapshot = advancedSnapshots.get(element)
  if (!snapshot) return
  const style = cssStyleFor(element)
  if (style) {
    for (const item of snapshot.styles) {
      if (item.value) style.setProperty(item.name, item.value, item.priority)
      else style.removeProperty(item.name)
    }
  }
  for (const item of snapshot.attributes) {
    if (item.value === null) item.element.removeAttribute(item.name)
    else item.element.setAttribute(item.name, item.value)
  }
  for (const item of snapshot.text) item.node.nodeValue = item.value
  if (forget) advancedSnapshots.delete(element)
}

function interpolateAdvancedNumber(from: number, to: number, progress: number): number {
  return from + (to - from) * progress
}

function interpolateAdvancedColor(
  from: MotionAdvancedColor,
  to: MotionAdvancedColor,
  progress: number
): MotionAdvancedColor {
  return {
    r: Math.min(1, Math.max(0, interpolateAdvancedNumber(from.r, to.r, progress))),
    g: Math.min(1, Math.max(0, interpolateAdvancedNumber(from.g, to.g, progress))),
    b: Math.min(1, Math.max(0, interpolateAdvancedNumber(from.b, to.b, progress))),
    a: Math.min(1, Math.max(0, interpolateAdvancedNumber(from.a, to.a, progress)))
  }
}

interface MotionAdvancedTimedValue<T> {
  offset: number
  easing?: MotionSamplingEasing
  value: T
}

function sampleAdvancedValue<T>(
  track: MotionAdvancedTrack,
  progress: number,
  read: (frame: MotionAdvancedFrame) => T | undefined,
  clone: (value: T) => T,
  blend: (from: T, to: T, progress: number) => T
): T | undefined {
  const frames = track.keyframes.flatMap((frame): MotionAdvancedTimedValue<T>[] => {
    const value = read(frame)
    return value === undefined
      ? []
      : [{ offset: frame.offset, easing: frame.easing, value }]
  })
  if (frames.length === 0) return undefined
  let startIndex = 0
  for (let index = 1; index < frames.length; index++) {
    if (frames[index].offset > progress) break
    startIndex = index
  }
  const start = frames[startIndex]
  const end = frames[startIndex + 1]
  if (!end || progress <= start.offset) return clone(start.value)
  const span = end.offset - start.offset
  if (span <= 0) return clone(end.value)
  const eased = sampleRuntimeEasing(
    start.easing ?? track.easing,
    (progress - start.offset) / span
  )
  return blend(start.value, end.value, eased)
}

function cloneAdvancedPaints(values: MotionAdvancedPaintTarget[]): MotionAdvancedPaintTarget[] {
  return values.map((value) => ({
    ...value,
    ...(value.color ? { color: { ...value.color } } : {})
  }))
}

function blendAdvancedPaints(
  from: MotionAdvancedPaintTarget[],
  to: MotionAdvancedPaintTarget[],
  progress: number
): MotionAdvancedPaintTarget[] {
  return from.map((value, index) => {
    const next = to[index]
    return {
      kind: value.kind,
      index: value.index,
      ...(value.color && next?.color
        ? { color: interpolateAdvancedColor(value.color, next.color, progress) }
        : {}),
      ...(value.opacity !== undefined && next?.opacity !== undefined
        ? { opacity: interpolateAdvancedNumber(value.opacity, next.opacity, progress) }
        : {})
    }
  })
}

