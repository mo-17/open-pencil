/**
 * Phase 3 §15 — inline shadcn/ui component source (faithful to the published
 * shadcn templates, Tailwind v4 flavor). Emitted verbatim into the output
 * project under `src/components/ui/*` + `src/lib/utils.ts` so the distributable
 * is self-contained (no `npx shadcn add` post-step). The interactive design
 * nodes (BUTTON/INPUT/TEXTAREA/LABEL) are rewritten by the adapter to import
 * these components and pass their design classes through via `className`.
 *
 * The components reference semantic color utilities (`bg-primary`,
 * `border-input`, …) that only exist once the theme tokens in `SHADCN_THEME_CSS`
 * are registered in `@theme`; `themeCss()` injects them into `src/index.css`.
 */

/** `src/lib/utils.ts` — the `cn` class-merge helper every component imports. */
export const UTILS_TS = `import { type ClassValue, clsx } from "clsx"
import { twMerge } from "tailwind-merge"

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}
`

