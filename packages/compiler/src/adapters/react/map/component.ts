import { MAP_MODULE_ATTRIBUTION } from '@open-pencil/core/plugins'

/** The exact MapLibre GL JS version emitted projects install. */
export const MAPLIBRE_GL_VERSION = '6.0.0'

const OPENSTREETMAP_COPYRIGHT_URL = 'https://www.openstreetmap.org/copyright'
const OPENSTREETMAP_ATTRIBUTION_HTML = `<a href="${OPENSTREETMAP_COPYRIGHT_URL}" target="_blank" rel="noopener noreferrer">${MAP_MODULE_ATTRIBUTION}</a>`

/** Build the contents of `src/__openpencil_map.tsx`. */
export function buildOpenPencilMapComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import { useEffect, useRef, useState, type HTMLAttributes } from 'react'
import {
  Map as MapLibreMap,
  Marker as MapLibreMarker,
  Popup as MapLibrePopup,
  type StyleSpecification
} from 'maplibre-gl'
import 'maplibre-gl/dist/maplibre-gl.css'

export interface OpenPencilMapMarker {
  id: string
  lng: number
  lat: number
  label?: string
}

export interface OpenPencilMapConfig {
  provider: 'openstreetmap'
  style: 'standard' | 'light' | 'dark'
  center: readonly [number, number]
  zoom: number
  interactive: boolean
  markers: readonly OpenPencilMapMarker[]
  layers: readonly unknown[]
  attribution: string
}

export interface OpenPencilMapProps extends HTMLAttributes<HTMLDivElement> {
  config: OpenPencilMapConfig
}

const OPENSTREETMAP_TILES = ['https://tile.openstreetmap.org/{z}/{x}/{y}.png']
const OPENSTREETMAP_ATTRIBUTION = ${JSON.stringify(OPENSTREETMAP_ATTRIBUTION_HTML)}

const STYLE_FILTERS: Record<OpenPencilMapConfig['style'], string> = {
  standard: 'none',
  light: 'grayscale(0.2) brightness(1.08) contrast(0.9)',
  dark: 'invert(0.92) hue-rotate(180deg) brightness(0.72) contrast(1.18) saturate(0.7)'
}

function openStreetMapStyle(): StyleSpecification {
  return {
    version: 8,
    sources: {
      openstreetmap: {
        type: 'raster',
        tiles: OPENSTREETMAP_TILES,
        tileSize: 256,
        maxzoom: 19,
        attribution: OPENSTREETMAP_ATTRIBUTION
      }
    },
    layers: [{ id: 'openstreetmap', type: 'raster', source: 'openstreetmap' }]
  }
}

function supportsWebGl(): boolean {
  try {
    const canvas = document.createElement('canvas')
    const context = canvas.getContext('webgl2')
    context?.getExtension('WEBGL_lose_context')?.loseContext()
    return context !== null
  } catch {
    return false
  }
}

function addMarkers(map: MapLibreMap, markers: readonly OpenPencilMapMarker[]) {
  return markers.map((marker) => {
    const instance = new MapLibreMarker().setLngLat([marker.lng, marker.lat])
    if (marker.label) {
      const label = document.createElement('span')
      label.textContent = marker.label
      instance.setPopup(new MapLibrePopup({ offset: 24 }).setDOMContent(label))
    }
    return instance.addTo(map)
  })
}

export function OpenPencilMap({
  config,
  className,
  children,
  style,
  ...hostProps
}: OpenPencilMapProps) {
  const containerRef = useRef<HTMLDivElement>(null)
  const [failed, setFailed] = useState(false)
  const positionedByClass = className
    ?.split(' ')
    .some((token) => ['absolute', 'fixed', 'relative', 'sticky'].includes(token))
  const positionedByStyle = style?.position !== undefined && style.position !== 'static'
  const hostStyle =
    positionedByClass || positionedByStyle
      ? style
      : { ...style, position: 'relative' as const }
  // The compiler emits data-only configs. Comparing their serialized value avoids
  // recreating the WebGL context when a parent rerenders an equivalent object.
  const serializedConfig = JSON.stringify(config)

  useEffect(() => {
    const container = containerRef.current
    if (!container) return

    const activeConfig = JSON.parse(serializedConfig) as OpenPencilMapConfig
    if (activeConfig.provider !== 'openstreetmap' || !supportsWebGl()) {
      setFailed(true)
      return
    }

    let map: MapLibreMap | undefined
    let markers: MapLibreMarker[] = []
    let active = true
    let canvas: HTMLCanvasElement | undefined

    const releaseMap = () => {
      for (const marker of markers) marker.remove()
      markers = []
      const current = map
      map = undefined
      current?.remove()
    }

    const fail = () => {
      if (!active) return
      releaseMap()
      setFailed(true)
    }

    const handleContextLost = (event: Event) => {
      event.preventDefault()
      fail()
    }

    try {
      setFailed(false)
      map = new MapLibreMap({
        container,
        style: openStreetMapStyle(),
        center: [activeConfig.center[0], activeConfig.center[1]],
        zoom: activeConfig.zoom,
        maxZoom: 19,
        interactive: activeConfig.interactive,
        attributionControl: { compact: false }
      })

      if (!activeConfig.interactive) {
        map.boxZoom.disable()
        map.doubleClickZoom.disable()
        map.dragPan.disable()
        map.dragRotate.disable()
        map.keyboard.disable()
        map.scrollZoom.disable()
        map.touchZoomRotate.disable()
      }

      canvas = map.getCanvas()
      canvas.style.filter = STYLE_FILTERS[activeConfig.style]
      canvas.addEventListener('webglcontextlost', handleContextLost)
      markers = addMarkers(map, activeConfig.markers)
    } catch {
      fail()
    }

    return () => {
      active = false
      canvas?.removeEventListener('webglcontextlost', handleContextLost)
      releaseMap()
    }
  }, [serializedConfig])

  return (
    <div {...hostProps} className={className} style={hostStyle}>
      <div ref={containerRef} style={{ height: '100%', inset: 0, position: 'absolute', width: '100%' }} />
      {failed ? (
        <div
          role="status"
          style={{
            alignItems: 'center',
            background: '#e5e7eb',
            color: '#4b5563',
            display: 'flex',
            inset: 0,
            justifyContent: 'center',
            minHeight: 120,
            position: 'absolute'
          }}
        >
          Map unavailable
        </div>
      ) : null}
      {children}
    </div>
  )
}

export default OpenPencilMap
`
}
