/**
 * Phase 3 §10 v3: scaffold `src/_lowcode_confirm.tsx`, the runtime that backs
 * the `confirm` workflow action. Compiled event handlers `await` the
 * module-level `__opConfirm(message)`, which shows a modal and resolves to the
 * user's choice (`true` = OK, `false` = Cancel). The auto-mounted
 * `<ConfirmHost/>` (mounted by `main.tsx`, like the toast host) subscribes to a
 * tiny module-level store via React's built-in `useSyncExternalStore` and
 * renders the pending prompt — so there is NO new npm dependency. The file is
 * emitted only when a page fires a `confirm` action.
 */

