/**
 * Phase 3 §10 v2: scaffold `src/_lowcode_toast.tsx`, the runtime that backs the
 * `toast` workflow action. Compiled event handlers call the module-level
 * `__opToast(message, variant)`; the auto-mounted `<ToastHost/>` (mounted by
 * `main.tsx`, like the i18n provider) subscribes to a tiny module-level store
 * via React's built-in `useSyncExternalStore` and renders the active toasts —
 * so there is NO new npm dependency (unlike the zustand-backed doc-state
 * runtime). The file is emitted only when a page fires a `toast` action.
 */

