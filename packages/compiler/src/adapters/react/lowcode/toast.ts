/** Build the contents of `src/_lowcode_toast.tsx`. */
export function buildLowcodeToastRuntime(): string {
  return `// Auto-generated by OpenPencil compiler (Phase 3 §10 v2 / v5). Do not edit by hand.
import { useEffect, useSyncExternalStore } from 'react'

export type ToastVariant = 'info' | 'success' | 'error'
export type ToastPosition =
  | 'top-left'
  | 'top-center'
  | 'top-right'
  | 'bottom-left'
  | 'bottom-center'
  | 'bottom-right'

export interface ToastOptions {
  position?: ToastPosition
  durationMs?: number
}

interface Toast {
  id: number
  message: string
  variant: ToastVariant
  position: ToastPosition
}

// Module-level store: a plain list + a listener set, read through React's
// useSyncExternalStore. The list reference changes only when a toast is added
// or removed, so getSnapshot is stable between renders (no re-render loop).
let toasts: Toast[] = []
let seq = 0
const listeners = new Set<() => void>()

// Phase 3 §10 v8: cap the number of simultaneously stacked toasts; when a new
// toast pushes past the cap the oldest is dropped so the stack can't grow
// without bound (e.g. a toast fired in a loop / on every keystroke).
const MAX_TOASTS = 5
const MAX_MESSAGE_LENGTH = 2048
const MAX_DURATION_MS = 60_000
const variants = new Set<ToastVariant>(['info', 'success', 'error'])
const positions = new Set<ToastPosition>([
  'top-left', 'top-center', 'top-right', 'bottom-left', 'bottom-center', 'bottom-right'
])

${buildToastTimerRuntime('dismiss')}

function emitChange(): void {
  for (const listener of listeners) listener()
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener)
  return () => {
    listeners.delete(listener)
  }
}

function getSnapshot(): Toast[] {
  return toasts
}

/** Remove a toast by id. Shared by the auto-dismiss timer and the manual
 *  close (×) button. */
function dismiss(id: number): void {
  clearTimer(id)
  if (!toasts.some((toast) => toast.id === id)) return
  toasts = toasts.filter((t) => t.id !== id)
  emitChange()
}

export function __opClearToasts(): void {
  for (const toast of toasts) clearTimer(toast.id)
  if (toasts.length === 0) return
  toasts = []
  emitChange()
}

/** Show a transient toast. Called by compiled event handlers. Auto-dismisses
 *  after \`options.durationMs\` (default 3000ms); pass \`durationMs: 0\` for a
 *  persistent toast that only closes when the user clicks ×. \`options.position\`
 *  picks the screen corner (default 'bottom-right'). */
export function __opToast(
  message: unknown,
  variant: ToastVariant = 'info',
  options: ToastOptions = {}
): void {
  const position = options.position && positions.has(options.position) ? options.position : 'bottom-right'
  variant = variants.has(variant) ? variant : 'info'
  const text = String(message).slice(0, MAX_MESSAGE_LENGTH)
  const authoredDuration = options.durationMs ?? 3000
  const duration = Number.isFinite(authoredDuration) && authoredDuration >= 0
    ? Math.min(authoredDuration, MAX_DURATION_MS) : 3000
  // Phase 3 §10 v8: skip a toast whose message + variant duplicates one already
  // on screen, so a repeatedly-fired action doesn't stack identical copies.
  if (toasts.some((t) => t.message === text && t.variant === variant && t.position === position)) return
  const id = ++seq
  let next = [...toasts, { id, message: text, variant, position }]
  // Phase 3 §10 v8: enforce the stack cap by dropping the oldest toasts.
  if (next.length > MAX_TOASTS) {
    for (const toast of next.slice(0, next.length - MAX_TOASTS)) clearTimer(toast.id)
    next = next.slice(next.length - MAX_TOASTS)
  }
  toasts = next
  emitChange()
  if (duration > 0) {
    startTimer(id, duration)
  }
}

const VARIANT_CLASSES: Record<ToastVariant, string> = {
  info: 'border-border bg-secondary text-secondary-foreground',
  success: 'border-border bg-primary text-primary-foreground',
  error: 'border-destructive bg-destructive text-destructive-foreground'
}

const POSITION_CLASSES: Record<ToastPosition, string> = {
  'top-left': 'top-[calc(1rem+env(safe-area-inset-top))] left-[calc(1rem+env(safe-area-inset-left))]',
  'top-center': 'top-[calc(1rem+env(safe-area-inset-top))] left-1/2 -translate-x-1/2',
  'top-right': 'top-[calc(1rem+env(safe-area-inset-top))] right-[calc(1rem+env(safe-area-inset-right))]',
  'bottom-left': 'bottom-[calc(1rem+env(safe-area-inset-bottom))] left-[calc(1rem+env(safe-area-inset-left))]',
  'bottom-center': 'bottom-[calc(1rem+env(safe-area-inset-bottom))] left-1/2 -translate-x-1/2',
  'bottom-right': 'bottom-[calc(1rem+env(safe-area-inset-bottom))] right-[calc(1rem+env(safe-area-inset-right))]'
}

/** Renders the active toasts, grouped into one fixed container per position in
 *  use. Auto-mounted by main.tsx — place nothing yourself. */
export function ToastHost() {
  const active = useSyncExternalStore(subscribe, getSnapshot, getSnapshot)
  useEffect(() => () => __opClearToasts(), [])
  const positions = [...new Set(active.map((t) => t.position))]
  const dismissLabel = typeof document !== 'undefined' && document.documentElement.lang.startsWith('zh')
    ? '关闭通知' : 'Dismiss notification'
  return (
    <div aria-live="polite" aria-relevant="additions text">
      {positions.map((position) => (
        <div key={position} className={'fixed z-50 flex flex-col gap-2 pointer-events-none max-h-[50dvh] overflow-y-auto overscroll-contain w-[min(26rem,calc(100vw-2rem-env(safe-area-inset-left)-env(safe-area-inset-right)))] ' + POSITION_CLASSES[position]}>
          {active
            .filter((t) => t.position === position)
            .map((t) => (
              <div
                key={t.id}
                role={t.variant === 'error' ? 'alert' : 'status'}
                aria-atomic="true"
                onPointerEnter={() => __opPauseToast(t.id, 'pointer')}
                onPointerLeave={() => __opResumeToast(t.id, 'pointer')}
                onFocus={() => __opPauseToast(t.id, 'focus')}
                onBlur={(event) => {
                  if (!event.currentTarget.contains(event.relatedTarget)) __opResumeToast(t.id, 'focus')
                }}
                className={'flex shrink-0 items-center gap-2 rounded border px-4 py-2 text-sm shadow-lg pointer-events-auto ' + VARIANT_CLASSES[t.variant]}
              >
                <span className="min-w-0 max-h-40 overflow-y-auto whitespace-pre-wrap [overflow-wrap:anywhere]">{t.message}</span>
                <button
                  type="button"
                  aria-label={dismissLabel}
                  onClick={() => dismiss(t.id)}
                  className="ml-auto min-h-11 min-w-11 shrink-0 cursor-pointer leading-none opacity-70 hover:opacity-100 focus-visible:outline-2 focus-visible:outline-offset-2"
                >
                  ×
                </button>
              </div>
            ))}
        </div>
      ))}
    </div>
  )
}
`
}
