import { FLOATING_POSITION_SOURCE } from '#compiler/adapters/floating/position'
import { POPOVER_CONTROLLER_SOURCE } from '#compiler/adapters/popover/controller'
import * as popoverSource from '#compiler/adapters/popover/source'

import { POPOVER_MODULE_TYPE, POPOVER_PLUGIN_ID } from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

export function buildOpenPencilPopoverComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import {useEffect,useId,useRef,type CSSProperties,type HTMLAttributes,type ReactNode} from 'react'
${popoverSource.POPOVER_CONFIG_SOURCE}
${FLOATING_POSITION_SOURCE}
${popoverSource.POPOVER_VISUAL_SOURCE}
${POPOVER_CONTROLLER_SOURCE}
export interface OpenPencilPopoverProps extends Omit<HTMLAttributes<HTMLDivElement>,'children'|'content'> {config:OpenPencilPopoverConfig;content?:ReactNode}
export default function OpenPencilPopover({config,content,className,style,...hostProps}:OpenPencilPopoverProps){
 ${REACT_MODULE_POSITIONED_HOST_SOURCE}
 const root=useRef<HTMLDivElement>(null),trigger=useRef<HTMLButtonElement>(null),panel=useRef<HTMLDivElement>(null),status=useRef<HTMLSpanElement>(null),current=useRef(config)
 current.current=config
 const configKey=popoverConfigKey(config),baseId=useId(),controller=useRef<ReturnType<typeof attachPopover>|null>(null)
 useEffect(()=>{if(!root.current||!trigger.current||!panel.current||!status.current)return
  const attached=attachPopover(root.current,trigger.current,panel.current,status.current,()=>current.current)
  controller.current=attached
  return ()=>{attached.destroy();controller.current=null}
 },[])
 useEffect(()=>{controller.current?.reset()},[configKey])
 return <div {...hostProps} ref={root} data-openpencil-popover="" className={className} style={{...hostStyle,...popoverStyle(config)} as CSSProperties}>
  <style>{${JSON.stringify(popoverSource.POPOVER_STYLE_SOURCE)}}</style>
  <button ref={trigger} data-popover-trigger="" type="button" disabled={config.disabled} aria-haspopup="dialog" aria-controls={baseId+'-panel'} aria-expanded="false">{config.triggerLabel}</button>
  <div ref={panel} id={baseId+'-panel'} data-popover-panel="" role="dialog" aria-labelledby={config.title?baseId+'-title':undefined} aria-label={config.title?undefined:config.triggerLabel} tabIndex={-1} popover="manual" hidden>
   <div data-popover-heading=""><h2 data-popover-title="" id={baseId+'-title'}>{config.title}</h2><button data-popover-close="" aria-label="Close popover" type="button">×</button></div>
   <div data-popover-content="">{config.contentChildName?content:config.content}</div>
   {config.mode==='confirm'&&<div data-popover-actions=""><button data-popover-action="cancel" type="button">{config.cancelLabel}</button><button data-popover-action="confirm" type="button">{config.confirmLabel}</button></div>}
  </div>
  <span ref={status} data-popover-status="" role="status" aria-live="polite"/>
 </div>
}
`
}
export const POPOVER_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: POPOVER_PLUGIN_ID,
  moduleType: POPOVER_MODULE_TYPE,
  componentName: 'OpenPencilPopover',
  runtimePath: 'src/__openpencil_popover.tsx',
  rootImportPath: './__openpencil_popover',
  nestedImportPath: '../__openpencil_popover',
  buildRuntime: buildOpenPencilPopoverComponent
})
