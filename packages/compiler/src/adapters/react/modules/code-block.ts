import { CODE_BLOCK_MODULE_TYPE, CODE_BLOCK_PLUGIN_ID } from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

const CODE_BLOCK_RUNTIME = `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import { useEffect, useMemo, useState, type HTMLAttributes } from 'react'

type CodeLanguage =
  | 'plaintext' | 'javascript' | 'typescript' | 'json' | 'html'
  | 'css' | 'bash' | 'python' | 'rust' | 'dart'

export interface OpenPencilCodeBlockConfig {
  label: string
  code: string
  language: CodeLanguage
  theme: 'light' | 'dark'
  showLineNumbers: boolean
  wrapLines: boolean
  showCopyButton: boolean
  fontSize: number
  tabSize: number
  backgroundColor: string
  textColor: string
  accentColor: string
}

export interface OpenPencilCodeBlockProps extends HTMLAttributes<HTMLDivElement> {
  config: OpenPencilCodeBlockConfig
}

export default function OpenPencilCodeBlock({
  config,
  className,
  children,
  style,
  ...hostProps
}: OpenPencilCodeBlockProps) {
  const [copyStatus, setCopyStatus] = useState('')
  const lineNumbers = useMemo(() => {
    const count = config.code.split('\\n').length
    return Array.from({ length: count }, (_, index) => String(index + 1)).join('\\n')
  }, [config.code])
${REACT_MODULE_POSITIONED_HOST_SOURCE}

  useEffect(() => setCopyStatus(''), [config.code])

  async function copyCode(): Promise<void> {
    try {
      if (!navigator.clipboard?.writeText) throw new Error('Clipboard access is unavailable')
      await navigator.clipboard.writeText(config.code)
      setCopyStatus('Copied')
    } catch (cause) {
      setCopyStatus(cause instanceof Error ? cause.message : String(cause))
    }
  }

  const codeStyle = {
    color: config.textColor,
    font: config.fontSize + 'px/1.55 ui-monospace, SFMono-Regular, Menlo, Consolas, monospace',
    margin: 0,
    tabSize: config.tabSize,
    whiteSpace: config.wrapLines ? 'pre-wrap' as const : 'pre' as const,
    wordBreak: config.wrapLines ? 'break-word' as const : undefined
  }

  return (
    <div
      {...hostProps}
      aria-label={config.label}
      className={className}
      data-language={config.language}
      data-openpencil-code-block=""
      data-theme={config.theme}
      role="region"
      style={{ ...hostStyle, background: config.backgroundColor, color: config.textColor, overflow: 'hidden' }}
    >
      <div style={{ alignItems: 'center', borderBottom: '1px solid ' + config.accentColor + '55', display: 'flex', gap: 8, justifyContent: 'space-between', minHeight: 36, padding: '6px 10px' }}>
        <span style={{ font: '600 12px/1.3 system-ui, sans-serif' }}>{config.label}</span>
        <span style={{ color: config.accentColor, font: '11px/1.3 ui-monospace, monospace' }}>{config.language}</span>
        {config.showCopyButton ? (
          <button
            onClick={() => void copyCode()}
            style={{ background: 'transparent', border: '1px solid ' + config.accentColor, borderRadius: 4, color: config.textColor, cursor: 'pointer', font: '11px system-ui, sans-serif', padding: '4px 8px' }}
            type="button"
          >
            Copy
          </button>
        ) : null}
      </div>
      <div style={{ display: 'flex', height: 'calc(100% - 36px)', overflow: 'auto', padding: '12px 0' }}>
        {config.showLineNumbers ? (
          <pre aria-hidden="true" style={{ ...codeStyle, color: config.accentColor, flex: '0 0 auto', padding: '0 10px', textAlign: 'end', userSelect: 'none' }}>
            {lineNumbers}
          </pre>
        ) : null}
        <pre style={{ ...codeStyle, flex: '1 0 auto', minWidth: 0, padding: '0 12px' }}>
          <code>{config.code}</code>
        </pre>
      </div>
      <span aria-live="polite" style={{ clipPath: 'inset(50%)', height: 1, overflow: 'hidden', position: 'absolute', width: 1 }}>
        {copyStatus}
      </span>
      {children}
    </div>
  )
}
`

export function buildOpenPencilCodeBlockComponent(): string {
  return CODE_BLOCK_RUNTIME
}

