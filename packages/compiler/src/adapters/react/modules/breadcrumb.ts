import {
  BREADCRUMB_CONFIG_SOURCE,
  BREADCRUMB_STYLE_SOURCE
} from '#compiler/adapters/navigation/breadcrumb'

import { BREADCRUMB_MODULE_TYPE, BREADCRUMB_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { ReactModuleAdapter } from './types'

export function buildOpenPencilBreadcrumbComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import type { CSSProperties, HTMLAttributes } from 'react'
${BREADCRUMB_CONFIG_SOURCE}
interface BreadcrumbProps extends HTMLAttributes<HTMLElement> { config: OpenPencilBreadcrumbConfig }
export default function OpenPencilBreadcrumb({config,style,children,...hostProps}: BreadcrumbProps) {
  return <nav {...hostProps} data-openpencil-breadcrumb="" aria-label={config.label}
    style={{...style,background:config.backgroundColor,color:config.textColor,'--op-crumb-font':config.fontSize+'px',
      '--op-crumb-accent':config.accentColor,'--op-crumb-wrap':config.wrap?'wrap':'nowrap'} as CSSProperties}>
    <style>{${JSON.stringify(BREADCRUMB_STYLE_SOURCE)}}</style>
    <ol>{config.items.map((item,index) => {
      const current = index === config.items.length - 1
      const href = current ? undefined : breadcrumbHref(item.href)
      return <li key={index}>
        {index > 0 && <span data-crumb-separator="" aria-hidden="true">{breadcrumbSeparator(config.separator)}</span>}
        {href ? <a data-crumb-label="" href={href} title={item.label}>{item.label}</a>
          : <span data-crumb-label="" aria-current={current?'page':undefined} title={item.label}>{item.label}</span>}
      </li>
    })}</ol>{children}
  </nav>
}
`
}
export const BREADCRUMB_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: BREADCRUMB_PLUGIN_ID,
  moduleType: BREADCRUMB_MODULE_TYPE,
  componentName: 'OpenPencilBreadcrumb',
  runtimePath: 'src/__openpencil_breadcrumb.tsx',
  rootImportPath: './__openpencil_breadcrumb',
  nestedImportPath: '../__openpencil_breadcrumb',
  buildRuntime: buildOpenPencilBreadcrumbComponent
})
