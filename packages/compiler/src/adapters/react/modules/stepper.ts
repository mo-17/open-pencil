import {
  STEPPER_CONFIG_SOURCE,
  STEPPER_RUNTIME_SOURCE,
  STEPPER_STYLE_SOURCE
} from '#compiler/adapters/navigation/stepper/source'

import { STEPPER_MODULE_TYPE, STEPPER_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { ReactModuleAdapter } from './types'

export function buildOpenPencilStepperComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import { useEffect, useRef, useState, type CSSProperties, type HTMLAttributes, type KeyboardEvent } from 'react'
${STEPPER_CONFIG_SOURCE}
${STEPPER_RUNTIME_SOURCE}
interface StepperProps extends HTMLAttributes<HTMLDivElement>, StepperInputs {
  config: OpenPencilStepperConfig
  onStepChange?: (index: number) => void
  onStepsChange?: (event: CustomEvent<StepperChangeDetail>) => void
}
export default function OpenPencilStepper({config, currentIndex, currentIndexBound, onStepChange, onStepsChange, disabled, readOnly, style, lang, children, ...hostProps}: StepperProps) {
  const host = useRef<HTMLDivElement>(null)
  const identity = JSON.stringify(config.items)
  const [selection, setSelection] = useState({ identity, initial: config.currentIndex, index: config.currentIndex })
  const local = selection.identity === identity && selection.initial === config.currentIndex ? selection.index : config.currentIndex
  const projection = stepperProjection(config, {currentIndex,currentIndexBound,disabled,readOnly}, local, Boolean(onStepChange))
  const current = projection.current
  const [focused, setFocused] = useState(current ?? 0)
  const [language, setLanguage] = useState(lang)
  useEffect(() => { setSelection({ identity, initial: config.currentIndex, index: config.currentIndex }) }, [identity, config.currentIndex])
  useEffect(() => { setFocused(current ?? 0) }, [identity, current])
  useEffect(() => { setLanguage(lang ?? host.current?.closest('[lang]')?.getAttribute('lang') ?? undefined) }, [lang])
  useEffect(() => installStepperEvents(host.current, event => onStepsChange?.(event), () => {
    if (!currentIndexBound) {
      setSelection({identity,initial:config.currentIndex,index:config.currentIndex})
      setFocused(config.currentIndex)
    }
  }), [identity,config.currentIndex,currentIndexBound,onStepsChange])
  function select(index: number): void {
    if (!projection.interactive || current === null || index === current || stepperCurrentIndex(config,index,true) === null) return
    if (!currentIndexBound) setSelection({identity,initial:config.currentIndex,index})
    setFocused(index)
    onStepChange?.(index)
    dispatchStepperChange(host.current,index,current)
  }
  function keyboard(event: KeyboardEvent<HTMLButtonElement>, index: number): void {
    if (!projection.interactive) return
    const next = stepperKeyboardIndex(config,index,event.key)
    if (next === null) return
    event.preventDefault()
    setFocused(next)
    host.current?.querySelector<HTMLButtonElement>('[data-step-index="'+next+'"]')?.focus()
  }
  return <div {...hostProps} ref={host} data-openpencil-stepper="" data-orientation={config.orientation} aria-label={config.label} lang={lang}
    data-invalid={projection.invalid} data-disabled={projection.disabled} data-readonly={projection.readOnly}
    aria-invalid={projection.invalid || undefined} aria-disabled={projection.disabled || undefined}
    style={{...style, background:config.backgroundColor,color:config.textColor,
      '--op-step-background':config.backgroundColor,'--op-step-accent':config.accentColor,
      '--op-step-error':config.errorColor,'--op-step-muted':config.textColor+'33','--op-step-font':config.fontSize+'px'} as CSSProperties}>
    <style>{${JSON.stringify(STEPPER_STYLE_SOURCE)}}</style>
    <ol>{config.items.map((item,index) => {
      const state = stepState(item,index,current)
      const content = <><span data-step-mark="" aria-hidden="true">{stepMark(item,index,current,config.showNumbers)}</span>
        <span data-step-copy=""><span data-step-title="" title={item.title}>{item.title}</span>
        {item.description && <span data-step-description="" title={item.description}>{item.description}</span>}</span></>
      const label = item.title + (state === 'error' ? ' — error' : state === 'completed' ? ' — completed' : '')
      return <li key={index} data-state={state} data-disabled={item.disabled || undefined} aria-current={index === current ? 'step' : undefined}>
        {config.allowStepClick ? <button type="button" data-step-index={index} disabled={item.disabled || !projection.interactive} aria-label={label}
          tabIndex={focused === index ? 0 : -1} onFocus={() => setFocused(index)}
          onKeyDown={event => keyboard(event,index)} onClick={() => select(index)}>{content}</button>
          : <div aria-label={label}>{content}</div>}
      </li>
    })}</ol><span data-step-status="" role="status" aria-live="polite">{stepperStatus(current,config.items.length,language)}</span>{children}
  </div>
}
`
}
