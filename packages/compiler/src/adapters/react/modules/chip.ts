import { CHIP_CONFIG_SOURCE, CHIP_STYLE_SOURCE } from '#compiler/adapters/chip/source'

import { CHIP_MODULE_TYPE, CHIP_PLUGIN_ID } from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

export function buildOpenPencilChipComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import {useEffect,useRef,useState,type CSSProperties,type HTMLAttributes,type KeyboardEvent} from 'react'
${CHIP_CONFIG_SOURCE}
export interface OpenPencilChipProps extends HTMLAttributes<HTMLDivElement> { config:OpenPencilChipConfig }
function ChipState({config,className,children,style,...hostProps}:OpenPencilChipProps){
  const [selected,setSelected]=useState(config.selectable && config.initialSelected)
  const [removed,setRemoved]=useState(false)
  const host=useRef<HTMLDivElement>(null)
  useEffect(()=>{ if(removed) host.current?.focus() },[removed])
${REACT_MODULE_POSITIONED_HOST_SOURCE}
  function remove():void { if(config.deletable && !config.disabled) setRemoved(true) }
  function onKeyDown(event:KeyboardEvent<HTMLElement>):void {
    if((event.key==='Delete'||event.key==='Backspace') && config.deletable && !config.disabled){
      event.preventDefault(); event.stopPropagation(); remove()
    }
  }
  const content=<><span data-chip-label="" title={config.label}>{config.label}</span></>
  const mark=selected?<svg aria-hidden="true" viewBox="0 0 16 16" focusable="false"><path d={checkPath}/></svg>:null
  return <div {...hostProps} ref={host} tabIndex={-1} data-openpencil-chip="" data-variant={config.variant}
    data-selected={selected} data-disabled={config.disabled} data-removed={removed} className={className}
    aria-label={removed?config.label+': '+config.removedLabel:undefined}
    style={{...hostStyle,'--chip-font':config.fontSize+'px','--chip-radius':config.borderRadius+'px',
      '--chip-color':config.color,'--chip-color-soft':config.color+'1F','--chip-filled-text':config.filledTextColor} as CSSProperties}>
    <style>{${JSON.stringify(CHIP_STYLE_SOURCE)}}</style>
    {!removed&&<div data-chip-body="">
      {config.selectable?<button type="button" data-chip-main="" aria-label={config.label} aria-pressed={selected}
        disabled={config.disabled} onKeyDown={onKeyDown} onClick={()=>{if(!config.disabled)setSelected(!selected)}}>{mark}{content}</button>
        :<span data-chip-main="">{content}</span>}
      {config.deletable&&<button type="button" data-chip-delete="" disabled={config.disabled}
        aria-label={config.deleteLabel+': '+config.label} onKeyDown={onKeyDown} onClick={remove}>
        <svg aria-hidden="true" viewBox="0 0 16 16" focusable="false"><path d={deletePath}/></svg>
      </button>}
    </div>}
    <span data-chip-announcement="" role="status">{removed?config.label+': '+config.removedLabel:''}</span>
    {children}
  </div>
}
export default function OpenPencilChip(props:OpenPencilChipProps){return <ChipState key={chipConfigKey(props.config)} {...props}/>}
`
}
