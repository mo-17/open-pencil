import { CHART_MODULE_TYPE, CHART_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { ReactModuleAdapter } from './types'

const CHART_RUNTIME = `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import type { HTMLAttributes } from 'react'

export interface OpenPencilChartConfig {
  chartType: 'bar'
  values: readonly number[]
  labels: readonly string[]
  color: string
  showValues: boolean
}

export interface OpenPencilChartProps extends HTMLAttributes<HTMLDivElement> {
  config: OpenPencilChartConfig
}

export default function OpenPencilChart({
  config,
  className,
  children,
  style,
  ...hostProps
}: OpenPencilChartProps) {
  const minValue = Math.min(0, ...config.values)
  const maxValue = Math.max(0, ...config.values)
  const span = Math.max(1, maxValue - minValue)
  const plotTop = 8
  const plotBottom = 84
  const plotHeight = plotBottom - plotTop
  const zeroY = plotTop + (maxValue / span) * plotHeight
  const count = Math.max(1, config.values.length)
  const slotWidth = 100 / count
  const positionedByClass = className
    ?.split(' ')
    .some((token) => ['absolute', 'fixed', 'relative', 'sticky'].includes(token))
  const positionedByStyle = style?.position !== undefined && style.position !== 'static'
  const hostStyle =
    positionedByClass || positionedByStyle
      ? style
      : { ...style, position: 'relative' as const }

  return (
    <div {...hostProps} className={className} style={hostStyle}>
      <svg
        aria-label="Bar chart"
        preserveAspectRatio="none"
        role="img"
        style={{ height: '100%', inset: 0, overflow: 'visible', position: 'absolute', width: '100%' }}
        viewBox="0 0 100 100"
      >
        <line stroke="currentColor" strokeOpacity="0.16" x1="0" x2="100" y1={zeroY} y2={zeroY} />
        {config.values.map((value, index) => {
          const valueY = plotTop + ((maxValue - value) / span) * plotHeight
          const height = Math.abs(zeroY - valueY)
          const width = slotWidth * 0.64
          const x = index * slotWidth + (slotWidth - width) / 2
          const y = Math.min(zeroY, valueY)
          const valueLabelY = value >= 0 ? Math.max(5, y - 2) : Math.min(88, y + height + 5)
          return (
            <g key={index}>
              <rect fill={config.color} height={height} rx="1" width={width} x={x} y={y} />
              {config.showValues ? (
                <text fill="currentColor" fontSize="4" textAnchor="middle" x={x + width / 2} y={valueLabelY}>
                  {value}
                </text>
              ) : null}
              <text fill="currentColor" fontSize="4" textAnchor="middle" x={x + width / 2} y="94">
                {config.labels[index] ?? ''}
              </text>
            </g>
          )
        })}
      </svg>
      {children}
    </div>
  )
}
`

export function buildOpenPencilChartComponent(): string {
  return CHART_RUNTIME
}

export const CHART_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: CHART_PLUGIN_ID,
  moduleType: CHART_MODULE_TYPE,
  componentName: 'OpenPencilChart',
  runtimePath: 'src/__openpencil_chart.tsx',
  rootImportPath: './__openpencil_chart',
  nestedImportPath: '../__openpencil_chart',
  buildRuntime: buildOpenPencilChartComponent
})
