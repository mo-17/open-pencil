import { SLIDE_MENU_MODULE_TYPE, SLIDE_MENU_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { ReactModuleAdapter } from './types'

const SLIDE_MENU_RUNTIME = `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import {
  useCallback,
  useEffect,
  useId,
  useRef,
  useState,
  type CSSProperties,
  type HTMLAttributes,
  type KeyboardEvent as ReactKeyboardEvent,
  type MouseEvent as ReactMouseEvent
} from 'react'
import { createPortal } from 'react-dom'

export interface OpenPencilSlideMenuItem {
  label: string
  href: string
}

export interface OpenPencilSlideMenuConfig {
  presentation: 'menu' | 'dialog'
  direction: 'left' | 'right' | 'top' | 'bottom'
  triggerLabel: string
  title: string
  description: string
  items: readonly OpenPencilSlideMenuItem[]
  closeOnBackdrop: boolean
  showCloseButton: boolean
  panelSize: number
  panelBackground: string
  textColor: string
  overlayOpacity: number
}

export interface OpenPencilSlideMenuProps extends HTMLAttributes<HTMLDivElement> {
  config: OpenPencilSlideMenuConfig
}

const FOCUSABLE_SELECTOR = [
  'a[href]',
  'button:not([disabled])',
  'input:not([disabled])',
  'select:not([disabled])',
  'textarea:not([disabled])',
  '[tabindex]:not([tabindex="-1"])'
].join(',')
const TRANSITION_MS = 220
let bodyScrollLockCount = 0
let previousBodyOverflow: string | null = null

interface OpenSlideMenuEntry {
  token: symbol
  panel: HTMLElement
  restoreFocus: HTMLElement | null
}

const openSlideMenus: OpenSlideMenuEntry[] = []

function pushOpenSlideMenu(entry: OpenSlideMenuEntry): void {
  const existingIndex = openSlideMenus.findIndex((candidate) => candidate.token === entry.token)
  if (existingIndex >= 0) openSlideMenus.splice(existingIndex, 1)
  openSlideMenus.push(entry)
}

function removeOpenSlideMenu(token: symbol): {
  wasTop: boolean
  nextTop: OpenSlideMenuEntry | undefined
} {
  const index = openSlideMenus.findIndex((entry) => entry.token === token)
  const wasTop = index >= 0 && index === openSlideMenus.length - 1
  if (index >= 0) openSlideMenus.splice(index, 1)
  return { wasTop, nextTop: openSlideMenus[openSlideMenus.length - 1] }
}

function isTopOpenSlideMenu(token: symbol): boolean {
  return openSlideMenus[openSlideMenus.length - 1]?.token === token
}

function lockBodyScroll(): () => void {
  if (bodyScrollLockCount === 0) {
    previousBodyOverflow = document.body.style.overflow
    document.body.style.overflow = 'hidden'
  }
  bodyScrollLockCount += 1
  let released = false
  return () => {
    if (released) return
    released = true
    bodyScrollLockCount = Math.max(0, bodyScrollLockCount - 1)
    if (bodyScrollLockCount !== 0) return
    document.body.style.overflow = previousBodyOverflow ?? ''
    previousBodyOverflow = null
  }
}

function focusableElements(panel: HTMLElement): HTMLElement[] {
  return [...panel.querySelectorAll<HTMLElement>(FOCUSABLE_SELECTOR)].filter(
    (element) => !element.hasAttribute('disabled') && element.getAttribute('aria-hidden') !== 'true'
  )
}

function focusPanel(panel: HTMLElement): void {
  ;(focusableElements(panel)[0] ?? panel).focus({ preventScroll: true })
}

function menuPlacement(config: OpenPencilSlideMenuConfig): CSSProperties {
  const size = config.panelSize + 'px'
  const width = 'min(' + size + ', calc(100vw - 16px))'
  const height = 'min(' + size + ', calc(100vh - 16px))'
  const base: CSSProperties = { position: 'absolute' }
  if (config.direction === 'left') return { ...base, height: '100%', left: 0, top: 0, width }
  if (config.direction === 'right') return { ...base, height: '100%', right: 0, top: 0, width }
  if (config.direction === 'top') return { ...base, height, left: 0, top: 0, width: '100%' }
  return { ...base, bottom: 0, height, left: 0, width: '100%' }
}

function dialogPlacement(config: OpenPencilSlideMenuConfig): CSSProperties {
  return {
    left: '50%',
    maxHeight: 'calc(100vh - 32px)',
    position: 'absolute',
    top: '50%',
    width: 'min(' + config.panelSize + 'px, calc(100vw - 32px))'
  }
}

function closedTransform(config: OpenPencilSlideMenuConfig): string {
  if (config.presentation === 'menu') {
    if (config.direction === 'left') return 'translate3d(-100%, 0, 0)'
    if (config.direction === 'right') return 'translate3d(100%, 0, 0)'
    if (config.direction === 'top') return 'translate3d(0, -100%, 0)'
    return 'translate3d(0, 100%, 0)'
  }
  if (config.direction === 'left') return 'translate(calc(-50% - 48px), -50%)'
  if (config.direction === 'right') return 'translate(calc(-50% + 48px), -50%)'
  if (config.direction === 'top') return 'translate(-50%, calc(-50% - 48px))'
  return 'translate(-50%, calc(-50% + 48px))'
}

function openTransform(config: OpenPencilSlideMenuConfig): string {
  return config.presentation === 'dialog' ? 'translate(-50%, -50%)' : 'translate3d(0, 0, 0)'
}

function panelStyle(
  config: OpenPencilSlideMenuConfig,
  visible: boolean,
  reducedMotion: boolean
): CSSProperties {
  return {
    ...(config.presentation === 'dialog' ? dialogPlacement(config) : menuPlacement(config)),
    background: config.panelBackground,
    boxSizing: 'border-box',
    boxShadow: '0 24px 80px #00000040',
    color: config.textColor,
    opacity: visible ? 1 : 0,
    overflowY: 'auto',
    padding: 24,
    transform: visible ? openTransform(config) : closedTransform(config),
    transition: reducedMotion
      ? 'none'
      : 'transform ' + TRANSITION_MS + 'ms ease, opacity ' + TRANSITION_MS + 'ms ease',
    zIndex: 1
  }
}

export default function OpenPencilSlideMenu({
  config,
  className,
  children,
  onClick,
  onKeyDown,
  style,
  tabIndex,
  ...hostProps
}: OpenPencilSlideMenuProps) {
  const triggerRef = useRef<HTMLDivElement>(null)
  const panelRef = useRef<HTMLElement>(null)
  const closeTimerRef = useRef<number | null>(null)
  const openFrameRef = useRef<number | null>(null)
  const modalTokenRef = useRef(Symbol('open-pencil-slide-menu'))
  const [mounted, setMounted] = useState(false)
  const [visible, setVisible] = useState(false)
  const [reducedMotion, setReducedMotion] = useState(false)
  const baseId = useId().replaceAll(':', '')
  const panelId = baseId + '-panel'
  const titleId = baseId + '-title'
  const descriptionId = baseId + '-description'

  const clearCloseTimer = useCallback(() => {
    if (closeTimerRef.current === null) return
    window.clearTimeout(closeTimerRef.current)
    closeTimerRef.current = null
  }, [])

  const clearOpenFrame = useCallback(() => {
    if (openFrameRef.current === null) return
    window.cancelAnimationFrame(openFrameRef.current)
    openFrameRef.current = null
  }, [])

  const openPanel = useCallback(() => {
    clearCloseTimer()
    if (mounted) setVisible(true)
    else setMounted(true)
  }, [clearCloseTimer, mounted])

  const closePanel = useCallback(() => {
    clearCloseTimer()
    clearOpenFrame()
    setVisible(false)
    if (reducedMotion) {
      setMounted(false)
      return
    }
    closeTimerRef.current = window.setTimeout(() => {
      closeTimerRef.current = null
      setMounted(false)
    }, TRANSITION_MS)
  }, [clearCloseTimer, clearOpenFrame, reducedMotion])

  useEffect(() => {
    if (typeof window === 'undefined') return
    const query = window.matchMedia('(prefers-reduced-motion: reduce)')
    const sync = () => setReducedMotion(query.matches)
    sync()
    query.addEventListener('change', sync)
    return () => query.removeEventListener('change', sync)
  }, [])

  useEffect(() => {
    if (!mounted) return
    clearOpenFrame()
    openFrameRef.current = window.requestAnimationFrame(() => {
      openFrameRef.current = null
      setVisible(true)
    })
    return clearOpenFrame
  }, [clearOpenFrame, mounted])

  useEffect(() => {
    if (!mounted) return
    const panel = panelRef.current
    if (!panel) return
    const entry: OpenSlideMenuEntry = {
      token: modalTokenRef.current,
      panel,
      restoreFocus:
        document.activeElement instanceof HTMLElement ? document.activeElement : null
    }
    pushOpenSlideMenu(entry)
    const releaseBodyScroll = lockBodyScroll()
    const frame = window.requestAnimationFrame(() => focusPanel(panel))
    return () => {
      window.cancelAnimationFrame(frame)
      const { wasTop, nextTop } = removeOpenSlideMenu(entry.token)
      releaseBodyScroll()
      if (!wasTop) return
      if (nextTop) {
        if (
          entry.restoreFocus?.isConnected &&
          nextTop.panel.contains(entry.restoreFocus)
        ) {
          entry.restoreFocus.focus({ preventScroll: true })
        } else {
          focusPanel(nextTop.panel)
        }
        return
      }
      triggerRef.current?.focus({ preventScroll: true })
    }
  }, [mounted])

  useEffect(() => {
    if (!mounted) return
    const handleKeyDown = (event: KeyboardEvent) => {
      if (!isTopOpenSlideMenu(modalTokenRef.current)) return
      if (event.key === 'Escape') {
        event.preventDefault()
        closePanel()
        return
      }
      if (event.key !== 'Tab') return
      const panel = panelRef.current
      if (!panel) return
      const focusable = focusableElements(panel)
      if (focusable.length === 0) {
        event.preventDefault()
        panel.focus({ preventScroll: true })
        return
      }
      const first = focusable[0]
      const last = focusable[focusable.length - 1]
      const active = document.activeElement
      if (event.shiftKey && (active === first || !panel.contains(active))) {
        event.preventDefault()
        last.focus({ preventScroll: true })
      } else if (!event.shiftKey && (active === last || !panel.contains(active))) {
        event.preventDefault()
        first.focus({ preventScroll: true })
      }
    }
    document.addEventListener('keydown', handleKeyDown)
    return () => document.removeEventListener('keydown', handleKeyDown)
  }, [closePanel, mounted])

  useEffect(
    () => () => {
      clearCloseTimer()
      clearOpenFrame()
    },
    [clearCloseTimer, clearOpenFrame]
  )

  const handleTriggerClick = (event: ReactMouseEvent<HTMLDivElement>) => {
    onClick?.(event)
    if (!event.defaultPrevented) openPanel()
  }
  const handleTriggerKeyDown = (event: ReactKeyboardEvent<HTMLDivElement>) => {
    onKeyDown?.(event)
    if (event.defaultPrevented || (event.key !== 'Enter' && event.key !== ' ')) return
    event.preventDefault()
    openPanel()
  }
  const positionedByClass = className
    ?.split(' ')
    .some((token) => ['absolute', 'fixed', 'relative', 'sticky'].includes(token))
  const positionedByStyle = style?.position !== undefined && style.position !== 'static'
  const hostStyle =
    positionedByClass || positionedByStyle
      ? style
      : { ...style, position: 'relative' as const }
  const accessibleLabel = config.triggerLabel || 'Open slide menu'

  const portal =
    mounted && typeof document !== 'undefined'
      ? createPortal(
          <div
            data-openpencil-slide-menu-overlay=""
            style={{ inset: 0, pointerEvents: visible ? 'auto' : 'none', position: 'fixed', zIndex: 2147483647 }}
          >
            <div
              data-openpencil-slide-menu-backdrop=""
              onMouseDown={() => {
                if (config.closeOnBackdrop) closePanel()
              }}
              style={{
                background: '#000000',
                inset: 0,
                opacity: visible ? config.overlayOpacity : 0,
                position: 'absolute',
                transition: reducedMotion ? 'none' : 'opacity ' + TRANSITION_MS + 'ms ease'
              }}
            />
            <section
              aria-describedby={config.description ? descriptionId : undefined}
              aria-label={config.title ? undefined : accessibleLabel}
              aria-labelledby={config.title ? titleId : undefined}
              aria-modal="true"
              data-direction={config.direction}
              data-openpencil-slide-menu-panel=""
              data-presentation={config.presentation}
              data-state={visible ? 'open' : 'closed'}
              id={panelId}
              ref={panelRef}
              role="dialog"
              style={panelStyle(config, visible, reducedMotion)}
              tabIndex={-1}
            >
              {config.title ? <h2 id={titleId}>{config.title}</h2> : null}
              {config.description ? <p id={descriptionId}>{config.description}</p> : null}
              {config.showCloseButton ? (
                <button aria-label="Close" onClick={closePanel} type="button">
                  Close
                </button>
              ) : null}
              <nav aria-label={config.title || accessibleLabel}>
                <ul>
                  {config.items.map((item, index) => (
                    <li key={item.href + '-' + index}>
                      <a href={item.href} onClick={closePanel}>{item.label}</a>
                    </li>
                  ))}
                </ul>
              </nav>
            </section>
          </div>,
          document.body
        )
      : null

  return (
    <>
      <div
        {...hostProps}
        aria-controls={panelId}
        aria-expanded={mounted && visible}
        aria-haspopup="dialog"
        aria-label={accessibleLabel}
        className={className}
        data-openpencil-slide-menu-trigger=""
        onClick={handleTriggerClick}
        onKeyDown={handleTriggerKeyDown}
        ref={triggerRef}
        role="button"
        style={hostStyle}
        tabIndex={tabIndex ?? 0}
      >
        {children ?? config.triggerLabel}
      </div>
      {portal}
    </>
  )
}
`

export function buildOpenPencilSlideMenuComponent(): string {
  return SLIDE_MENU_RUNTIME
}

export const SLIDE_MENU_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: SLIDE_MENU_PLUGIN_ID,
  moduleType: SLIDE_MENU_MODULE_TYPE,
  componentName: 'OpenPencilSlideMenu',
  runtimePath: 'src/__openpencil_slide_menu.tsx',
  rootImportPath: './__openpencil_slide_menu',
  nestedImportPath: '../__openpencil_slide_menu',
  buildRuntime: buildOpenPencilSlideMenuComponent
})
