import { TIMELINE_CONFIG_SOURCE, TIMELINE_STYLE_SOURCE } from '#compiler/adapters/timeline/source'

import { TIMELINE_MODULE_TYPE, TIMELINE_PLUGIN_ID } from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

export function buildOpenPencilTimelineComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import type {CSSProperties,HTMLAttributes} from 'react'
${TIMELINE_CONFIG_SOURCE}
export interface OpenPencilTimelineProps extends HTMLAttributes<HTMLDivElement>{config:OpenPencilTimelineConfig}
export default function OpenPencilTimeline({config,className,children,style,lang,...hostProps}:OpenPencilTimelineProps){
${REACT_MODULE_POSITIONED_HOST_SOURCE}
 const statusLabels=timelineStatusLabels(lang)
 return <div {...hostProps} data-openpencil-timeline="" data-layout={config.layout} className={className} lang={lang}
   style={{...hostStyle,...timelineStyles(config)} as CSSProperties}>
   <style>{${JSON.stringify(TIMELINE_STYLE_SOURCE)}}</style>
   <ol role="list" aria-label={config.label} data-timeline-list="">
    {config.items.map(item=><li key={item.id} data-timeline-item={item.id} data-status={item.status} aria-current={item.status==='current'?'true':undefined}>
      <span data-timeline-marker="" role="img" aria-label={statusLabels[item.status]}>
       <svg aria-hidden="true" viewBox="0 0 16 16" focusable="false">
        <circle cx="8" cy="8" r={item.status==='pending'?7:8} fill={item.status==='pending'?'var(--timeline-background)':'currentColor'} stroke="currentColor" strokeWidth={item.status==='pending'?2:0}/>
        {item.status==='current'&&<circle cx="8" cy="8" r={8/3} fill="var(--timeline-background)"/>}
        {(item.status==='completed'||item.status==='error')&&<path d={timelinePaths[item.status]} stroke="#FFFFFF" strokeWidth="1.8" fill="none"/>}
       </svg>
      </span>
      <div data-timeline-content="">
       {item.time&&<span data-timeline-time="">{item.time}</span>}
       <span data-timeline-title="">{item.title}</span>
       {item.description&&<span data-timeline-description="">{item.description}</span>}
      </div>
    </li>)}
   </ol>
   {!config.items.length&&<p data-timeline-empty="">{config.emptyText}</p>}
   {children}
 </div>
}
`
}
export const TIMELINE_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: TIMELINE_PLUGIN_ID,
  moduleType: TIMELINE_MODULE_TYPE,
  componentName: 'OpenPencilTimeline',
  runtimePath: 'src/__openpencil_timeline.tsx',
  rootImportPath: './__openpencil_timeline',
  nestedImportPath: '../__openpencil_timeline',
  buildRuntime: buildOpenPencilTimelineComponent
})
