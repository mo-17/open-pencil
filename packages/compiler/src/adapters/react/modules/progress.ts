import * as progressSource from '#compiler/adapters/progress/source'

import { PROGRESS_MODULE_TYPE, PROGRESS_PLUGIN_ID } from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

export function buildOpenPencilProgressComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import type { CSSProperties, HTMLAttributes } from 'react'
${progressSource.PROGRESS_CONFIG_SOURCE}
${progressSource.PROGRESS_PRESENTATION_SOURCE}
export interface OpenPencilProgressProps extends HTMLAttributes<HTMLDivElement> { config: OpenPencilProgressConfig }
export default function OpenPencilProgress({config,className,style,children,...hostProps}: OpenPencilProgressProps) {
  const visual = progressPresentation(config)
${REACT_MODULE_POSITIONED_HOST_SOURCE}
  return <div {...hostProps} data-openpencil-progress="" data-indeterminate={config.indeterminate} className={className}
    style={{...hostStyle,...visual.styles} as CSSProperties} role="progressbar" aria-label={config.label}
    aria-valuemin={0} aria-valuemax={100} aria-valuenow={config.indeterminate ? undefined : config.value}
    aria-valuetext={config.indeterminate ? config.pendingLabel : config.value+'%'}>
    <style>{${JSON.stringify(progressSource.PROGRESS_STYLE_SOURCE)}}</style>
    {(config.showLabel || visual.valueText) && <div data-progress-header="">
      {config.showLabel && <span data-progress-label="">{config.label}</span>}
      {visual.valueText && <span data-progress-value="">{visual.valueText}</span>}
    </div>}
    <div data-progress-body="">{config.variant === 'linear' ? <div data-progress-track="" aria-hidden="true">
      <span data-progress-fill="" style={config.indeterminate ? undefined : {width:config.value+'%'}}/>
    </div> : <svg data-progress-ring="" viewBox="0 0 100 100" preserveAspectRatio="xMidYMin meet" aria-hidden="true" focusable="false">
      <g data-progress-rotation=""><circle cx="50" cy="50" r={visual.radius} fill="none" stroke={config.trackColor} strokeWidth={visual.stroke}/>
      <circle data-progress-arc="" cx="50" cy="50" r={visual.radius} pathLength="100" fill="none"
        stroke={config.accentColor} strokeWidth={visual.stroke} strokeDasharray={visual.dash}/></g>
    </svg>}</div>
    {children}
  </div>
}
`
}

export const PROGRESS_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: PROGRESS_PLUGIN_ID,
  moduleType: PROGRESS_MODULE_TYPE,
  componentName: 'OpenPencilProgress',
  runtimePath: 'src/__openpencil_progress.tsx',
  rootImportPath: './__openpencil_progress',
  nestedImportPath: '../__openpencil_progress',
  buildRuntime: buildOpenPencilProgressComponent
})
