import * as badgeSource from '#compiler/adapters/badge/source'

import * as badge from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

export function buildOpenPencilBadgeComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import type {CSSProperties,HTMLAttributes} from 'react'
${badgeSource.BADGE_CONFIG_SOURCE}
${badgeSource.BADGE_RUNTIME_SOURCE}
export interface OpenPencilBadgeProps extends Omit<HTMLAttributes<HTMLDivElement>,'children'> {config:OpenPencilBadgeConfig}
export default function OpenPencilBadge({config,className,style,...hostProps}:OpenPencilBadgeProps){
${REACT_MODULE_POSITIONED_HOST_SOURCE}
  const visible=badgeVisible(config)
  return <div {...hostProps} data-openpencil-badge="" data-badge-mode={config.mode} data-badge-placement={config.placement} className={className} style={{...hostStyle,...badgeStyle(config)} as CSSProperties}>
    <style>{${JSON.stringify(badgeSource.BADGE_STYLE_SOURCE)}}</style>
    <span data-badge-host=""><span data-badge-host-text="">{config.hostLabel}</span></span>
    {visible&&<span data-badge-value="" aria-hidden="true"><span data-badge-value-text="">{badgeText(config)}</span></span>}
    {visible&&config.mode==='count'&&<span data-badge-count-label="">{config.label}: {config.count}</span>}
  </div>
}
`
}

export const BADGE_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: badge.BADGE_PLUGIN_ID,
  moduleType: badge.BADGE_MODULE_TYPE,
  componentName: 'OpenPencilBadge',
  runtimePath: 'src/__openpencil_badge.tsx',
  rootImportPath: './__openpencil_badge',
  nestedImportPath: '../__openpencil_badge',
  buildRuntime: buildOpenPencilBadgeComponent
})
