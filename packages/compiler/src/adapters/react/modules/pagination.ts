import {
  PAGINATION_CONFIG_SOURCE,
  PAGINATION_MATH_SOURCE,
  PAGINATION_STYLE_SOURCE
} from '#compiler/adapters/pagination/source'

import { PAGINATION_MODULE_TYPE, PAGINATION_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { ReactModuleAdapter } from './types'

export function buildOpenPencilPaginationComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import { useEffect,useRef,useState,type CSSProperties,type HTMLAttributes } from 'react'
${PAGINATION_CONFIG_SOURCE}
${PAGINATION_MATH_SOURCE}
const paginationCSS=${JSON.stringify(PAGINATION_STYLE_SOURCE)}
export interface OpenPencilPaginationProps extends HTMLAttributes<HTMLElement>,PaginationInputs {config:OpenPencilPaginationConfig;onPageChange?:(page:number)=>void}
export default function OpenPencilPagination({config,currentPage,currentPageBound,total,totalBound,pageSize,pageSizeBound,onPageChange,className,style,lang,children,...hostProps}:OpenPencilPaginationProps){
 const host=useRef<HTMLElement>(null),[width,setWidth]=useState(440),[localPage,setLocalPage]=useState(config.initialPage),[language,setLanguage]=useState(lang)
 useEffect(()=>setLocalPage(config.initialPage),[config.initialPage])
 useEffect(()=>{
  const element=host.current;if(!element)return
  const measure=()=>setWidth(element.clientWidth)
  const localize=()=>setLanguage(lang??element.closest('[lang]')?.getAttribute('lang')??undefined)
  measure();localize()
  const resize=typeof ResizeObserver==='undefined'?undefined:new ResizeObserver(measure);resize?.observe(element)
  const languageObserver=typeof MutationObserver==='undefined'?undefined:new MutationObserver(localize)
  languageObserver?.observe(element.ownerDocument.documentElement,{attributes:true,attributeFilter:['lang'],subtree:true})
  window.addEventListener('resize',measure)
  return()=>{resize?.disconnect();languageObserver?.disconnect();window.removeEventListener('resize',measure)}
 },[lang])
 const layout=paginationProjection(config,{currentPage,currentPageBound,total,totalBound,pageSize,pageSizeBound},localPage,width),zh=paginationChinese(language)
 const status=paginationStatus(layout,zh)
 function change(page:number|null):void{
  if(layout.disabled||layout.empty||page===null||page===layout.page||page<1||page>layout.pageCount)return
  if(currentPageBound){onPageChange?.(page)}else{setLocalPage(page);onPageChange?.(page)}
 }
 const hostStyle={...style,...paginationStyles(config)} as CSSProperties
 return <nav {...hostProps} ref={host} aria-label={config.label} lang={lang} className={className} style={hostStyle} data-openpencil-pagination="" data-invalid={layout.invalid} data-clamped={layout.clamped} data-disabled={layout.disabled} data-pagination-mode={layout.mode}>
  <style>{paginationCSS}</style>
  <div data-pagination-items="" style={{gap:layout.gap}}>
   {layout.cells.map(cell=>cell.page===null?<span key={cell.key} data-pagination-cell="" data-pagination-summary={cell.kind==='summary'?'':undefined} aria-hidden={cell.kind==='ellipsis'||undefined} title={cell.kind==='summary'?status:undefined} style={{width:cell.width,height:layout.buttonSize,fontSize:layout.fontSize}}>{layout.invalid&&cell.kind==='summary'?'—':cell.text}</span>:<button key={cell.key} type="button" data-pagination-cell="" data-pagination-kind={cell.kind} disabled={cell.disabled||(currentPageBound&&!onPageChange)} aria-current={cell.active?'page':undefined} aria-label={paginationCellLabel(cell,zh)} style={{width:cell.width,height:layout.buttonSize,fontSize:layout.fontSize}} onClick={()=>change(cell.page)}>{cell.kind==='page'?cell.text:<span data-pagination-arrow="" aria-hidden="true">{paginationArrow(cell.kind)}</span>}</button>)}
  </div>
  <span data-pagination-status="" role="status" aria-live="polite">{status}</span>{children}
 </nav>
}
`
}
export const PAGINATION_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: PAGINATION_PLUGIN_ID,
  moduleType: PAGINATION_MODULE_TYPE,
  componentName: 'OpenPencilPagination',
  runtimePath: 'src/__openpencil_pagination.tsx',
  rootImportPath: './__openpencil_pagination',
  nestedImportPath: '../__openpencil_pagination',
  buildRuntime: buildOpenPencilPaginationComponent
})
