import * as emptySource from '#compiler/adapters/empty-state/source'

import * as emptyState from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

export function buildOpenPencilEmptyStateComponent(): string {
  const metrics = emptySource.EMPTY_STATE_SVG_METRICS
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import {useId,type CSSProperties,type HTMLAttributes} from 'react'
${emptySource.EMPTY_STATE_CONFIG_SOURCE}
export interface OpenPencilEmptyStateProps extends HTMLAttributes<HTMLDivElement>{config:OpenPencilEmptyStateConfig}
export default function OpenPencilEmptyState({config,className,style,children,...hostProps}:OpenPencilEmptyStateProps){
 const id=useId(),titleId=id+'-title',descriptionId=id+'-description'
${REACT_MODULE_POSITIONED_HOST_SOURCE}
 return <div {...hostProps} data-openpencil-empty-state="" data-alignment={config.alignment} role="group" aria-labelledby={titleId}
 aria-describedby={config.description?descriptionId:undefined} className={className} style={{...hostStyle,...emptyStateStyles(config)} as CSSProperties}>
 <style>{${JSON.stringify(emptySource.EMPTY_STATE_STYLE_SOURCE)}}</style><div data-empty-body="">
 {config.illustration!=='none'&&<svg data-empty-illustration="" aria-hidden="true" focusable="false" viewBox="0 0 ${metrics.viewBox} ${metrics.viewBox}">
 <circle cx="32" cy="32" r="30" fill="currentColor" opacity={${metrics.illustrationOpacity}}/>
 <path d={emptyIllustrations[config.illustration]} fill="none" stroke="currentColor" strokeWidth={${metrics.illustrationStroke}}/></svg>}
 <p data-empty-title="" id={titleId}>{config.title}</p>
 {config.description&&<p data-empty-description="" id={descriptionId}>{config.description}</p>}
 </div>{children}</div>
}
`
}
export const EMPTY_STATE_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: emptyState.EMPTY_STATE_PLUGIN_ID,
  moduleType: emptyState.EMPTY_STATE_MODULE_TYPE,
  componentName: 'OpenPencilEmptyState',
  runtimePath: 'src/__openpencil_empty_state.tsx',
  rootImportPath: './__openpencil_empty_state',
  nestedImportPath: '../__openpencil_empty_state',
  buildRuntime: buildOpenPencilEmptyStateComponent
})
