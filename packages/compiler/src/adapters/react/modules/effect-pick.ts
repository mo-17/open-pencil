import { effectPickRuntimeSource } from '#compiler/adapters/effect-pick/source'

import {
  EFFECT_PICK_CATALOG,
  EFFECT_PICK_MODULE_TYPE,
  EFFECT_PICK_PLUGIN_ID
} from '@open-pencil/core/plugins'

import type { ReactModuleAdapter, ReactModuleRuntimeOptions } from './types'

export function buildOpenPencilEffectPickComponent(options?: ReactModuleRuntimeOptions): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import {useEffect,useRef,type HTMLAttributes} from 'react'
${effectPickRuntimeSource(options?.effectPickArtifacts ?? EFFECT_PICK_CATALOG, true)}
interface OpenPencilEffectPickProps extends Omit<HTMLAttributes<HTMLDivElement>,'onClick'> {
  config: OpenPencilEffectPickConfig
  onClick?: (event: MouseEvent) => void
}
export default function OpenPencilEffectPick({config,onClick,children,...hostProps}:OpenPencilEffectPickProps) {
  const host=useRef<HTMLDivElement>(null),controller=useRef<ReturnType<typeof mountEffectPick>|null>(null),callback=useRef(onClick)
  callback.current=onClick
  useEffect(()=>{
    if(!host.current)return
    const mounted=mountEffectPick(host.current,config,event=>callback.current?.(event))
    controller.current=mounted
    return ()=>{mounted.destroy();if(controller.current===mounted)controller.current=null}
  },[])
  useEffect(()=>{controller.current?.setConfig(config)},[config.effectId,config.collectionVersion,config.artifactDigest,config.text,config.color,config.secondaryColor,config.speed])
  return <div {...hostProps} data-openpencil-effect-pick=""><div ref={host} style={{width:'100%',height:'100%'}}/>{children}</div>
}
`
}

export const EFFECT_PICK_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: EFFECT_PICK_PLUGIN_ID,
  moduleType: EFFECT_PICK_MODULE_TYPE,
  componentName: 'OpenPencilEffectPick',
  runtimePath: 'src/__openpencil_effect_pick.tsx',
  rootImportPath: './__openpencil_effect_pick',
  nestedImportPath: '../__openpencil_effect_pick',
  buildRuntime: buildOpenPencilEffectPickComponent
})
