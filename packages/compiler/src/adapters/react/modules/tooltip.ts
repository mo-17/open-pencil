import { TOOLTIP_CONTROLLER_SOURCE } from '#compiler/adapters/tooltip/controller'
import * as tooltipSource from '#compiler/adapters/tooltip/source'

import * as tooltip from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'
export function buildOpenPencilTooltipComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import {useEffect,useId,useRef,type CSSProperties,type HTMLAttributes} from 'react'
${tooltipSource.TOOLTIP_CONFIG_SOURCE}
${tooltipSource.TOOLTIP_POSITION_SOURCE}
${tooltipSource.TOOLTIP_VISUAL_SOURCE}
${TOOLTIP_CONTROLLER_SOURCE}
export interface OpenPencilTooltipProps extends Omit<HTMLAttributes<HTMLDivElement>,'children'> {config:OpenPencilTooltipConfig}
export default function OpenPencilTooltip({config,className,style,...hostProps}:OpenPencilTooltipProps){
 ${REACT_MODULE_POSITIONED_HOST_SOURCE}
 const root=useRef<HTMLDivElement>(null),trigger=useRef<HTMLButtonElement>(null),bubble=useRef<HTMLDivElement>(null),current=useRef(config)
 current.current=config
 const configKey=tooltipConfigKey(config)
 const tooltipId=useId(),controller=useRef<ReturnType<typeof attachTooltip>|null>(null)
 useEffect(()=>{if(!root.current||!trigger.current||!bubble.current)return
  controller.current=attachTooltip(root.current,trigger.current,bubble.current,()=>current.current)
  return ()=>{controller.current?.destroy();controller.current=null}
 },[])
 useEffect(()=>{controller.current?.reset()},[configKey])
 return <div {...hostProps} ref={root} data-openpencil-tooltip="" className={className} style={{...hostStyle,...tooltipStyle(config)} as CSSProperties}>
  <style>{${JSON.stringify(tooltipSource.TOOLTIP_STYLE_SOURCE)}}</style>
  <button ref={trigger} data-tooltip-trigger="" type="button">{config.triggerLabel}</button>
  <div ref={bubble} id={tooltipId} data-tooltip-bubble="" role="tooltip" popover="manual" hidden><span data-tooltip-text="">{config.content}</span></div>
 </div>
}
`
}
export const TOOLTIP_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: tooltip.TOOLTIP_PLUGIN_ID,
  moduleType: tooltip.TOOLTIP_MODULE_TYPE,
  componentName: 'OpenPencilTooltip',
  runtimePath: 'src/__openpencil_tooltip.tsx',
  rootImportPath: './__openpencil_tooltip',
  nestedImportPath: '../__openpencil_tooltip',
  buildRuntime: buildOpenPencilTooltipComponent
})
