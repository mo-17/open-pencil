import {
  buildLottieSafetySource,
  LOTTIE_CONFIG_SOURCE,
  LOTTIE_WEB_VERSION
} from '#compiler/adapters/lottie/source'

import { LOTTIE_MODULE_TYPE, LOTTIE_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { ReactModuleAdapter } from './types'

export { LOTTIE_WEB_VERSION } from '#compiler/adapters/lottie/source'

export function buildOpenPencilLottieComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import { useEffect, useRef, useState, type HTMLAttributes } from 'react'
// @ts-ignore -- lottie-web does not publish declarations for its expression-free light subpath.
import lottie from 'lottie-web/build/player/lottie_light'

${LOTTIE_CONFIG_SOURCE}export interface OpenPencilLottieProps extends HTMLAttributes<HTMLDivElement> {
  config: OpenPencilLottieConfig
}

${buildLottieSafetySource()}export default function OpenPencilLottie({
  config,
  className,
  children,
  style,
  ...hostProps
}: OpenPencilLottieProps) {
  const containerRef = useRef<HTMLDivElement>(null)
  const requestNonceRef = useRef(0)
  const [networkRequest, setNetworkRequest] = useState<NetworkRequest | null>(null)
  const [status, setStatus] = useState<LoadStatus>('idle')
  const serializedConfig = JSON.stringify(config)
  const positionedByClass = className
    ?.split(' ')
    .some((token) => ['absolute', 'fixed', 'relative', 'sticky'].includes(token))
  const positionedByStyle = style?.position !== undefined && style.position !== 'static'
  const hostStyle =
    positionedByClass || positionedByStyle
      ? style
      : { ...style, position: 'relative' as const }

  useEffect(() => {
    const container = containerRef.current
    if (!container) return
    container.replaceChildren()
    const activeConfig = JSON.parse(serializedConfig) as OpenPencilLottieConfig
    const controller = new AbortController()
    let active = true
    let animation: ReturnType<typeof lottie.loadAnimation> | undefined
    const cleanup = () => {
      active = false
      controller.abort()
      try {
        animation?.destroy()
      } catch {
        // A third-party teardown failure must not leave generated SVG nodes behind.
      } finally {
        container.replaceChildren()
      }
    }

    if (activeConfig.source === 'url') {
      if (activeConfig.url === '' || networkRequest?.url !== activeConfig.url) {
        setStatus('idle')
        return cleanup
      }
    }
    setStatus('loading')

    const fail = () => {
      if (active) setStatus('error')
    }
    const load = async () => {
      const data =
        activeConfig.source === 'json'
          ? validateAnimationData(activeConfig.data)
          : await fetchBoundedAnimationData(activeConfig.url, controller)
      if (!active) return
      const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches
      animation = lottie.loadAnimation({
        animationData: structuredClone(data),
        autoplay: activeConfig.autoplay && !reducedMotion,
        container,
        loop: activeConfig.loop,
        renderer: 'svg',
        rendererSettings: { preserveAspectRatio: preserveAspectRatio(activeConfig.fit) }
      })
      animation.setDirection(activeConfig.direction === 'reverse' ? -1 : 1)
      animation.setSpeed(activeConfig.speed)
      if (reducedMotion) animation.goToAndStop(0, true)
      setStatus('ready')
    }
    void load().catch(fail)

    return cleanup
  }, [networkRequest, serializedConfig])

  const requestNetworkAnimation = () => {
    requestNonceRef.current += 1
    setNetworkRequest({ url: config.url, nonce: requestNonceRef.current })
  }
  const needsActivation =
    config.source === 'url' &&
    config.url !== '' &&
    (networkRequest?.url !== config.url || status === 'error')

  return (
    <div {...hostProps} className={className} data-openpencil-lottie="" style={hostStyle}>
      <div
        aria-label="Lottie animation"
        data-openpencil-lottie-container=""
        ref={containerRef}
        role="img"
        style={{ height: '100%', inset: 0, overflow: 'hidden', position: 'absolute', width: '100%' }}
      />
      {children}
      {needsActivation ? (
        <button
          data-openpencil-lottie-load=""
          onClick={requestNetworkAnimation}
          style={{
            background: '#0F172AE8',
            border: '1px solid #FFFFFFB8',
            borderRadius: 6,
            color: '#FFFFFF',
            cursor: 'pointer',
            font: '600 14px/1 system-ui, sans-serif',
            left: '50%',
            padding: '10px 14px',
            position: 'absolute',
            top: '50%',
            transform: 'translate(-50%, -50%)',
            zIndex: 2147483647
          }}
          type="button"
        >
          {status === 'error' ? 'Retry Lottie animation' : 'Load Lottie animation'}
        </button>
      ) : config.source === 'url' && config.url === '' ? (
        <span data-openpencil-lottie-status="" style={{ inset: 0, placeItems: 'center', position: 'absolute' }}>
          Add a canonical HTTPS Lottie URL
        </span>
      ) : status === 'loading' ? (
        <span aria-live="polite" data-openpencil-lottie-status="" style={{ inset: 0, placeItems: 'center', position: 'absolute' }}>
          Loading animation…
        </span>
      ) : status === 'error' && config.source === 'json' ? (
        <span aria-live="polite" data-openpencil-lottie-status="" style={{ inset: 0, placeItems: 'center', position: 'absolute' }}>
          Animation unavailable
        </span>
      ) : null}
    </div>
  )
}
`
}

export const LOTTIE_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: LOTTIE_PLUGIN_ID,
  moduleType: LOTTIE_MODULE_TYPE,
  componentName: 'OpenPencilLottie',
  runtimePath: 'src/__openpencil_lottie.tsx',
  rootImportPath: './__openpencil_lottie',
  nestedImportPath: '../__openpencil_lottie',
  dependencies: Object.freeze({ 'lottie-web': LOTTIE_WEB_VERSION }),
  optimizeDeps: Object.freeze(['lottie-web']),
  buildRuntime: buildOpenPencilLottieComponent
})
