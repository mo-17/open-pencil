import * as alertSource from '#compiler/adapters/alert/source'

import { ALERT_MODULE_TYPE, ALERT_PLUGIN_ID } from '@open-pencil/core/plugins'

import { REACT_MODULE_POSITIONED_HOST_SOURCE } from './runtime-source'
import type { ReactModuleAdapter } from './types'

export function buildOpenPencilAlertComponent(): string {
  return `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import {useEffect,useRef,useState,type HTMLAttributes} from 'react'
${alertSource.ALERT_CONFIG_SOURCE}
${alertSource.ALERT_RUNTIME_SOURCE}
export interface OpenPencilAlertProps extends HTMLAttributes<HTMLDivElement> {config:OpenPencilAlertConfig}
export default function OpenPencilAlert({config,className,children,style,...hostProps}:OpenPencilAlertProps){
  const host=useRef<HTMLDivElement>(null)
  const key=alertKey(config)
  const [closedKey,setClosedKey]=useState<string|null>(null)
  useEffect(()=>{setClosedKey(null)},[key])
  const closed=closedKey===key
${REACT_MODULE_POSITIONED_HOST_SOURCE}
  function dismiss():void { if(host.current) focusAfterAlertDismiss(host.current); setClosedKey(key) }
  return <div {...hostProps} ref={host} hidden={closed} data-openpencil-alert="" data-alert-tone={config.tone} data-alert-variant={config.variant}
    className={className} style={{...hostStyle,...alertColors(config)}}>
    <style>{${JSON.stringify(alertSource.ALERT_STYLE_SOURCE)}}</style>
    {!closed&&<div data-alert-layout="">
      {config.showIcon&&<svg data-alert-icon="" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d={alertIcons[config.tone]} fill="none" stroke="currentColor" strokeWidth="1.8"/></svg>}
      <div data-alert-copy="" role={alertRole(config)} aria-live={config.announcement} aria-atomic="true">
        {config.title&&<strong data-alert-title="">{config.title}</strong>}
        {config.description&&<p data-alert-description="">{config.description}</p>}
      </div>
      {config.closable&&<button type="button" data-alert-close="" aria-label={config.closeLabel} onClick={dismiss}>
        <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d={alertClosePath} fill="none" stroke="currentColor" strokeWidth="1.8"/></svg>
      </button>}
    </div>}
    {!closed&&children}
  </div>
}
`
}

export const ALERT_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: ALERT_PLUGIN_ID,
  moduleType: ALERT_MODULE_TYPE,
  componentName: 'OpenPencilAlert',
  runtimePath: 'src/__openpencil_alert.tsx',
  rootImportPath: './__openpencil_alert',
  nestedImportPath: '../__openpencil_alert',
  buildRuntime: buildOpenPencilAlertComponent
})
