import { DATA_GRID_CSV_RUNTIME } from '#compiler/adapters/data-grid/csv'
import { DATA_GRID_FEEDBACK_RUNTIME } from '#compiler/adapters/data-grid/feedback'
import { DATA_GRID_ROWS_RUNTIME } from '#compiler/adapters/data-grid/rows'
import {
  DATA_GRID_TYPES,
  DATA_GRID_CELL_RUNTIME,
  DATA_GRID_LAYOUT_RUNTIME
} from '#compiler/adapters/data-grid/source'

import { DATA_GRID_MODULE_TYPE, DATA_GRID_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { ReactModuleAdapter } from './types'

const DATA_GRID_RUNTIME = `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import { useEffect, useId, useMemo, useRef, useState, type HTMLAttributes } from 'react'

${DATA_GRID_TYPES}
export interface OpenPencilDataGridProps extends HTMLAttributes<HTMLDivElement> {
  config: OpenPencilDataGridConfig
  rowsBound?: boolean
  rows?: unknown
}

${DATA_GRID_CSV_RUNTIME}
${DATA_GRID_CELL_RUNTIME}
${DATA_GRID_ROWS_RUNTIME}
${DATA_GRID_FEEDBACK_RUNTIME}
${DATA_GRID_LAYOUT_RUNTIME}
export default function OpenPencilDataGrid({
  config,
  rowsBound = false,
  rows: boundSource,
  children,
  className,
  style,
  lang,
  ...hostProps
}: OpenPencilDataGridProps) {
  const chinese = (lang ?? (typeof document === 'undefined' ? 'en' : document.documentElement.lang)).toLowerCase().startsWith('zh')
  const copy = dataGridCopy(chinese)
  const [localRows, setRows] = useState<readonly OpenPencilDataGridRow[]>(() => config.data.rows)
  const boundRows = rowsBound ? resolveBoundDataGridRows(boundSource, config.data.columns) : { ok: true, rows: [] }
  const rows = rowsBound ? boundRows.rows : localRows
  const rowsUnavailable = rowsBound && !boundRows.ok
  const boundFingerprint = JSON.stringify({ columns: config.data.columns, boundRows })
  const [sort, setSort] = useState<OpenPencilDataGridSort | null>(config.initialSort)
  const [queries, setQueries] = useState<Record<string, string>>({})
  const [page, setPage] = useState(0)
  const [selectedIds, setSelectedIds] = useState<Set<string>>(() => new Set())
  const [csvOpen, setCsvOpen] = useState(false)
  const [csvSource, setCsvSource] = useState('')
  const [csvOutput, setCsvOutput] = useState('')
  const [csvStatus, setCsvStatus] = useState<'imported' | 'prepared' | ''>('')
  const [importedCount, setImportedCount] = useState(0)
  const [csvError, setCsvError] = useState('')
  const [sanitizedCount, setSanitizedCount] = useState(0)
  const selectionName = 'openpencil-data-grid-selection-' + useId()
  const selectAllRef = useRef<HTMLInputElement>(null)
  const scrollAreaRef = useRef<HTMLDivElement>(null)
  const tableHeaderRef = useRef<HTMLTableSectionElement>(null)
  const [stickyHeaderFits, setStickyHeaderFits] = useState(false)
  useEffect(() => {
    const viewport = scrollAreaRef.current
    const header = tableHeaderRef.current
    if (!config.showHeader || !config.stickyHeader || !viewport || !header) {
      setStickyHeaderFits(false)
      return
    }
    return observeDataGridStickyHeader(viewport, header, setStickyHeaderFits)
  }, [config.showHeader, config.stickyHeader])
  const resetFingerprint = useMemo(
    () =>
      JSON.stringify({
        data: { columns: config.data.columns, rows: rowsBound ? boundRows.rows : config.data.rows },
        rowsBound,
        rowsUnavailable,
        filters: config.filters,
        initialSort: config.initialSort,
        pageSize: config.pageSize,
        selectionMode: config.selectionMode
      }),
    [config.data, config.filters, config.initialSort, config.pageSize, config.selectionMode, rowsBound, rowsUnavailable, boundFingerprint]
  )

  useEffect(() => {
    setRows(config.data.rows)
    setSort(config.initialSort)
    setQueries({})
    setPage(0)
    setSelectedIds(new Set())
    setCsvSource('')
    setCsvOutput('')
    setCsvStatus('')
    setCsvError('')
    setSanitizedCount(0)
  }, [resetFingerprint])

  const columnIndexes = useMemo(
    () => new Map(config.data.columns.map((column, index) => [column.id, index])),
    [config.data.columns]
  )

  const filteredRows = useMemo(
    () =>
      rows.filter((row) => {
        for (const filter of config.filters) {
          const columnIndex = columnIndexes.get(filter.columnId)
          if (columnIndex === undefined || !matchesFilter(row.cells[columnIndex] ?? null, filter)) {
            return false
          }
        }
        for (const column of config.data.columns) {
          const query = queries[column.id]?.trim().toLocaleLowerCase()
          if (!query) continue
          const columnIndex = columnIndexes.get(column.id)
          if (
            columnIndex === undefined ||
            !cellText(row.cells[columnIndex] ?? null).toLocaleLowerCase().includes(query)
          ) {
            return false
          }
        }
        return true
      }),
    [columnIndexes, config.data.columns, config.filters, queries, rows]
  )

  const importPastedCsv = () => {
    if (rowsBound) return
    try {
      const importedRows = importCsvRows(csvSource, config.data.columns)
      setRows(importedRows)
      setSort(config.initialSort)
      setQueries({})
      setPage(0)
      setSelectedIds(new Set())
      setCsvOutput('')
      setSanitizedCount(0)
      setCsvError('')
      setImportedCount(importedRows.length)
      setCsvStatus('imported')
    } catch (cause) {
      setCsvStatus('')
      setCsvError(cause instanceof Error ? cause.message : String(cause))
    }
  }

  const prepareCsvText = () => {
    try {
      const prepared = exportCsvRows(config.data.columns, rowsBound ? sortedRows : rows)
      setCsvOutput(prepared.text)
      setSanitizedCount(prepared.sanitizedCount)
      setCsvError('')
      setCsvStatus('prepared')
    } catch (cause) {
      setCsvOutput('')
      setSanitizedCount(0)
      setCsvStatus('')
      setCsvError(cause instanceof Error ? cause.message : String(cause))
    }
  }

  const sortedRows = useMemo(() => {
    if (!sort) return filteredRows
    const columnIndex = columnIndexes.get(sort.columnId)
    if (columnIndex === undefined) return filteredRows
    const direction = sort.direction === 'ascending' ? 1 : -1
    return filteredRows
      .map((row, sourceIndex) => ({ row, sourceIndex }))
      .sort((left, right) => {
        const compared =
          compareCells(
            left.row.cells[columnIndex] ?? null,
            right.row.cells[columnIndex] ?? null
          ) * direction
        return compared || left.sourceIndex - right.sourceIndex
      })
      .map(({ row }) => row)
  }, [columnIndexes, filteredRows, sort])

  const pageCount = Math.max(1, Math.ceil(sortedRows.length / config.pageSize))
  useEffect(() => setPage((value) => Math.min(value, pageCount - 1)), [pageCount])
  const pageRows = sortedRows.slice(page * config.pageSize, (page + 1) * config.pageSize)

  const selectionSummaryId = selectionName + '-summary'
  const selectionText = copy.selected(selectedIds.size, selectedIds.size - pageRows.filter(row => selectedIds.has(row.id)).length)
  const hasQueries = Object.values(queries).some(value => value.length > 0)
  const hasSelection = config.selectionMode !== 'none' && selectedIds.size > 0
  const showFeedback = hasSelection || hasQueries || config.filters.length > 0
  const statusText = csvStatus === 'prepared' ? copy.prepared : csvStatus === 'imported' ? copy.imported(importedCount) : ''
  const clearQueries = () => {
    ;(scrollAreaRef.current?.querySelector<HTMLInputElement>('input[type="search"]') ?? scrollAreaRef.current)?.focus()
    setQueries({})
    setPage(0)
  }
  const clearSelection = () => {
    ;(scrollAreaRef.current?.querySelector<HTMLInputElement>('input[type="checkbox"]:not(:disabled), input[type="radio"]:not(:disabled)') ?? scrollAreaRef.current)?.focus()
    setSelectedIds(new Set())
  }

  const toggleSort = (column: OpenPencilDataGridColumn) => {
    if (!column.sortable) return
    setPage(0)
    setSort((current) => {
      if (!current || current.columnId !== column.id) {
        return { columnId: column.id, direction: 'ascending' }
      }
      if (current.direction === 'ascending') {
        return { columnId: column.id, direction: 'descending' }
      }
      return null
    })
  }

  const toggleRow = (rowId: string) => {
    if (config.selectionMode === 'none') return
    setSelectedIds((current) => {
      if (config.selectionMode === 'single') {
        return current.has(rowId) ? new Set() : new Set([rowId])
      }
      const next = new Set(current)
      if (next.has(rowId)) next.delete(rowId)
      else next.add(rowId)
      return next
    })
  }

  const allPageRowsSelected =
    pageRows.length > 0 && pageRows.every((row) => selectedIds.has(row.id))
  const somePageRowsSelected = pageRows.some((row) => selectedIds.has(row.id))
  const pageSelectionIsMixed = somePageRowsSelected && !allPageRowsSelected
  useEffect(() => {
    if (selectAllRef.current) {
      selectAllRef.current.indeterminate = pageSelectionIsMixed
    }
  }, [config.selectionMode, config.showHeader, pageSelectionIsMixed])

  const togglePageRows = () => {
    if (config.selectionMode !== 'multiple') return
    setSelectedIds((current) => {
      const next = new Set(current)
      if (allPageRowsSelected) pageRows.forEach((row) => next.delete(row.id))
      else pageRows.forEach((row) => next.add(row.id))
      return next
    })
  }

  const positionedByClass = className
    ?.split(' ')
    .some((token) => ['absolute', 'fixed', 'relative', 'sticky'].includes(token))
  const positionedByStyle = style?.position !== undefined && style.position !== 'static'
  const hostStyle = {
    ...(positionedByClass || positionedByStyle ? style : { ...style, position: 'relative' as const }),
    color: config.textColor,
    display: 'flex',
    flexDirection: 'column' as const,
    fontSize: config.fontSize,
    overflow: 'hidden'
  }
  const cellStyle = (column: OpenPencilDataGridColumn) => ({
    border: '1px solid ' + config.borderColor,
    boxSizing: 'border-box' as const,
    height: config.density === 'compact' ? 30 : 42,
    padding: config.density === 'compact' ? '4px 8px' : '8px 12px',
    textAlign: column.align,
    verticalAlign: 'middle' as const,
    width: column.width
  })
  const buttonStyle = { minHeight: 44, padding: '6px 10px', border: '1px solid ' + config.borderColor, borderRadius: 4, background: config.headerBackground, color: config.textColor, cursor: 'pointer' }
  const inputStyle = { boxSizing: 'border-box' as const, display: 'block', width: '100%', minHeight: 36, padding: 6, border: '1px solid ' + config.borderColor, borderRadius: 4, background: '#FFFFFF', color: config.textColor }
  const selectionColumn = config.selectionMode === 'none' ? 0 : 44
  const tableWidth =
    config.data.columns.reduce((total, column) => total + column.width, selectionColumn)
  const visuallyHiddenStyle = {
    border: 0,
    clip: 'rect(0 0 0 0)',
    clipPath: 'inset(50%)',
    height: 1,
    margin: -1,
    overflow: 'hidden',
    padding: 0,
    position: 'absolute' as const,
    whiteSpace: 'nowrap' as const,
    width: 1
  }

  return (
    <div
      {...hostProps}
      className={className}
      lang={lang}
      data-openpencil-data-grid=""
      data-openpencil-data-grid-unavailable={rowsUnavailable || undefined}
      style={hostStyle}
    >
      {config.showCsvTools === true ? <div
        aria-label={copy.tools}
        data-openpencil-data-grid-csv-tools=""
        role="region"
        style={{ borderBottom: '1px solid ' + config.borderColor, padding: 8, flexShrink: 0 }}
      >
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6 }}>
          <button disabled={rowsBound} style={buttonStyle} onClick={() => setCsvOpen((value) => !value)} type="button">
            {csvOpen ? copy.close : copy.paste}
          </button>
          <button disabled={rowsUnavailable} style={buttonStyle} onClick={prepareCsvText} type="button">{copy.prepare}</button>
        </div>
        {rowsBound ? <p>{copy.boundReadOnly}</p> : null}
        {csvOpen && !rowsBound ? (
          <div style={{ marginTop: 6 }}>
            <label>
              {copy.source}
              <textarea
                maxLength={CSV_MAX_BYTES}
                onChange={(event) => setCsvSource(event.target.value)}
                rows={5}
                spellCheck={false}
                style={inputStyle}
                value={csvSource}
              />
            </label>
            <button disabled={rowsBound} style={buttonStyle} onClick={importPastedCsv} type="button">{copy.import}</button>
            <p>
              {copy.local}
            </p>
          </div>
        ) : null}
        {csvOutput ? (
          <div style={{ marginTop: 6 }}>
            <label>
              {copy.output}
              <textarea
                readOnly
                rows={5}
                spellCheck={false}
                style={inputStyle}
                value={csvOutput}
              />
            </label>
            <p>
              {copy.manual}
              {sanitizedCount > 0
                ? ' ' + copy.sanitized(sanitizedCount)
                : ''}
            </p>
          </div>
        ) : null}
        {statusText ? <p aria-live="polite">{statusText}</p> : null}
        {csvError ? <p aria-live="assertive" role="alert">{copy.failure} {csvError}</p> : null}
      </div> : null}
      {config.selectionMode !== 'none' || showFeedback ? (
        <div data-openpencil-data-grid-feedback="" data-openpencil-data-grid-feedback-hidden={showFeedback ? undefined : ''} style={showFeedback ? { borderBottom: '1px solid ' + config.borderColor, padding: 8, flexShrink: 0 } : visuallyHiddenStyle}>
          <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8, alignItems: 'center' }}>
            {config.selectionMode !== 'none' ?
              <span id={selectionSummaryId} role="status" aria-live="polite" aria-atomic="true">{selectionText}</span>
            : null}
            {hasSelection ? <button type="button" style={buttonStyle} onClick={clearSelection}>{copy.clearSelection}</button> : null}
            {hasQueries ? <button type="button" style={buttonStyle} onClick={clearQueries}>{copy.clearFilters}</button> : null}
          </div>
          {config.filters.length ? <p style={{ margin: '4px 0 0' }}>{copy.configuredFilters}</p> : null}
        </div>
      ) : null}
      <div
        aria-label={copy.scroll}
        data-openpencil-data-grid-scroll=""
        ref={scrollAreaRef}
        role="region"
        style={{ flex: 1, minHeight: 0, overflow: 'auto' }}
        tabIndex={0}
      >
        <table
          aria-colcount={config.data.columns.length + (selectionColumn ? 1 : 0)}
          aria-rowcount={filteredRows.length}
          style={{ borderCollapse: 'collapse', minWidth: '100%', tableLayout: 'fixed', width: tableWidth }}
        >
          <thead
            ref={tableHeaderRef}
            data-visually-hidden={config.showHeader ? undefined : ''}
            style={
              config.showHeader
                ? {
                    background: config.headerBackground,
                    position: config.stickyHeader && stickyHeaderFits ? 'sticky' : undefined,
                    top: config.stickyHeader && stickyHeaderFits ? 0 : undefined,
                    zIndex: config.stickyHeader && stickyHeaderFits ? 1 : undefined
                  }
                : visuallyHiddenStyle
            }
          >
            <tr>
              {config.selectionMode !== 'none' ? (
                <th scope="col" style={{ border: '1px solid ' + config.borderColor, width: 44 }}>
                  {!config.showHeader ? (
                    copy.selection
                  ) : config.selectionMode === 'multiple' ? (
                    <input
                      aria-checked={pageSelectionIsMixed ? 'mixed' : allPageRowsSelected}
                      aria-label={copy.all}
                      aria-describedby={selectionSummaryId}
                      disabled={pageRows.length === 0}
                      checked={allPageRowsSelected}
                      onChange={togglePageRows}
                      ref={selectAllRef}
                      type="checkbox"
                    />
                  ) : (
                    <span aria-hidden="true">•</span>
                  )}
                </th>
              ) : null}
              {config.data.columns.map((column) => {
                const ariaSort =
                  sort?.columnId === column.id ? sort.direction : ('none' as const)
                return (
                  <th aria-sort={ariaSort} key={column.id} scope="col" style={cellStyle(column)}>
                    {config.showHeader && column.sortable ? (
                      <button style={buttonStyle} onClick={() => toggleSort(column)} type="button">
                        {column.label}
                      </button>
                    ) : (
                      column.label
                    )}
                  </th>
                )
              })}
            </tr>
            {config.showHeader && config.data.columns.some((column) => column.filterable) ? (
              <tr data-openpencil-data-grid-filters="">
                {config.selectionMode !== 'none' ? <th aria-hidden="true" /> : null}
                {config.data.columns.map((column) => (
                  <th key={column.id} scope="col" style={cellStyle(column)}>
                    {column.filterable ? (
                      <input
                        style={inputStyle}
                        aria-label={copy.filter + column.label}
                        onChange={(event) => {
                          setPage(0)
                          setQueries((current) => ({
                            ...current,
                            [column.id]: event.target.value
                          }))
                        }}
                        type="search"
                        value={queries[column.id] ?? ''}
                      />
                    ) : null}
                  </th>
                ))}
              </tr>
            ) : null}
          </thead>
          <tbody>
            {pageRows.map((row, rowIndex) => {
              const selected = selectedIds.has(row.id)
              return (
                <tr
                  aria-selected={config.selectionMode === 'none' ? undefined : selected}
                  data-selected={selected || undefined}
                  key={row.id}
                  style={{
                    background: selected
                      ? config.accentColor + '20'
                      : config.striped && rowIndex % 2 === 1
                        ? '#F9FAFB'
                        : undefined
                  }}
                >
                  {config.selectionMode !== 'none' ? (
                    <td style={{ border: '1px solid ' + config.borderColor, textAlign: 'center' }}>
                      <input
                        aria-label={copy.select + row.id}
                        aria-describedby={selectionSummaryId}
                        checked={selected}
                        name={config.selectionMode === 'single' ? selectionName : undefined}
                        onChange={() => toggleRow(row.id)}
                        type={config.selectionMode === 'single' ? 'radio' : 'checkbox'}
                      />
                    </td>
                  ) : null}
                  {config.data.columns.map((column, columnIndex) => (
                    <td key={column.id} style={cellStyle(column)}>
                      {cellText(row.cells[columnIndex] ?? null)}
                    </td>
                  ))}
                </tr>
              )
            })}
            {pageRows.length === 0 ? (
              <tr>
                <td
                  colSpan={config.data.columns.length + (selectionColumn ? 1 : 0)}
                  style={{ padding: 16, textAlign: 'center' }}
                >
                  {rowsUnavailable ? <span role="alert">{copy.boundUnavailable}</span> : copy.empty}
                </td>
              </tr>
            ) : null}
          </tbody>
        </table>
      </div>

      <div
        aria-label={copy.pagination}
        data-openpencil-data-grid-pagination=""
        role="navigation"
        style={{ flexShrink: 0, display: 'flex', flexWrap: 'wrap', gap: 8, alignItems: 'center', padding: 8, borderTop: '1px solid ' + config.borderColor }}
      >
        <button style={{ ...buttonStyle, opacity: page === 0 ? 0.5 : 1 }} disabled={page === 0} onClick={() => setPage((value) => value - 1)} type="button">
          {copy.previous}
        </button>
        <span aria-live="polite">
          {copy.page(page + 1, pageCount, filteredRows.length)}
        </span>
        <button
          style={{ ...buttonStyle, opacity: page >= pageCount - 1 ? 0.5 : 1 }}
          disabled={page >= pageCount - 1}
          onClick={() => setPage((value) => value + 1)}
          type="button"
        >
          {copy.next}
        </button>
      </div>
      {children}
    </div>
  )
}
`

export function buildOpenPencilDataGridComponent(): string {
  return DATA_GRID_RUNTIME
}

export const DATA_GRID_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: DATA_GRID_PLUGIN_ID,
  moduleType: DATA_GRID_MODULE_TYPE,
  componentName: 'OpenPencilDataGrid',
  runtimePath: 'src/__openpencil_data_grid.tsx',
  rootImportPath: './__openpencil_data_grid',
  nestedImportPath: '../__openpencil_data_grid',
  buildRuntime: buildOpenPencilDataGridComponent
})
