import { DATA_GRID_MODULE_TYPE, DATA_GRID_PLUGIN_ID } from '@open-pencil/core/plugins'

import { DATA_GRID_CSV_RUNTIME } from './data-grid-csv-runtime'
import type { ReactModuleAdapter } from './types'

const DATA_GRID_RUNTIME = `// Auto-generated by OpenPencil compiler. Do not edit by hand.
import { useEffect, useId, useMemo, useRef, useState, type HTMLAttributes } from 'react'

export type OpenPencilDataGridCell = string | number | boolean | null

export interface OpenPencilDataGridColumn {
  id: string
  label: string
  type: 'text' | 'number' | 'date' | 'boolean'
  align: 'start' | 'center' | 'end'
  width: number
  sortable: boolean
  filterable: boolean
}

export interface OpenPencilDataGridRow {
  id: string
  cells: readonly OpenPencilDataGridCell[]
}

export interface OpenPencilDataGridSort {
  columnId: string
  direction: 'ascending' | 'descending'
}

export interface OpenPencilDataGridFilter {
  columnId: string
  operator: 'contains' | 'equals' | 'greater-than' | 'less-than'
  value: OpenPencilDataGridCell
}

export interface OpenPencilDataGridConfig {
  data: {
    columns: readonly OpenPencilDataGridColumn[]
    rows: readonly OpenPencilDataGridRow[]
  }
  initialSort: OpenPencilDataGridSort | null
  filters: readonly OpenPencilDataGridFilter[]
  pageSize: number
  selectionMode: 'none' | 'single' | 'multiple'
  density: 'compact' | 'comfortable'
  showHeader: boolean
  stickyHeader: boolean
  striped: boolean
  borderColor: string
  headerBackground: string
  textColor: string
  accentColor: string
  fontSize: number
}

export interface OpenPencilDataGridProps extends HTMLAttributes<HTMLDivElement> {
  config: OpenPencilDataGridConfig
}

${DATA_GRID_CSV_RUNTIME}
function cellText(value: OpenPencilDataGridCell): string {
  if (value === null) return ''
  if (typeof value === 'boolean') return value ? 'True' : 'False'
  return String(value)
}

function compareCells(left: OpenPencilDataGridCell, right: OpenPencilDataGridCell): number {
  if (left === right) return 0
  if (left === null) return 1
  if (right === null) return -1
  if (typeof left === 'number' && typeof right === 'number') return left - right
  if (typeof left === 'boolean' && typeof right === 'boolean') return Number(left) - Number(right)
  return String(left).localeCompare(String(right), undefined, {
    numeric: true,
    sensitivity: 'base'
  })
}

function matchesFilter(
  value: OpenPencilDataGridCell,
  filter: OpenPencilDataGridFilter
): boolean {
  const comparison = compareCells(value, filter.value)
  if (filter.operator === 'equals') return comparison === 0
  if (filter.operator === 'greater-than') return comparison > 0
  if (filter.operator === 'less-than') return comparison < 0
  return cellText(value).toLocaleLowerCase().includes(cellText(filter.value).toLocaleLowerCase())
}

export default function OpenPencilDataGrid({
  config,
  children,
  className,
  style,
  ...hostProps
}: OpenPencilDataGridProps) {
  const [rows, setRows] = useState<readonly OpenPencilDataGridRow[]>(() => config.data.rows)
  const [sort, setSort] = useState<OpenPencilDataGridSort | null>(config.initialSort)
  const [queries, setQueries] = useState<Record<string, string>>({})
  const [page, setPage] = useState(0)
  const [selectedIds, setSelectedIds] = useState<Set<string>>(() => new Set())
  const [csvOpen, setCsvOpen] = useState(false)
  const [csvSource, setCsvSource] = useState('')
  const [csvOutput, setCsvOutput] = useState('')
  const [csvStatus, setCsvStatus] = useState('')
  const [csvError, setCsvError] = useState('')
  const [sanitizedCount, setSanitizedCount] = useState(0)
  const selectionName = 'openpencil-data-grid-selection-' + useId()
  const selectAllRef = useRef<HTMLInputElement>(null)
  const resetFingerprint = useMemo(
    () =>
      JSON.stringify({
        data: config.data,
        filters: config.filters,
        initialSort: config.initialSort,
        pageSize: config.pageSize,
        selectionMode: config.selectionMode
      }),
    [config.data, config.filters, config.initialSort, config.pageSize, config.selectionMode]
  )

  useEffect(() => {
    setRows(config.data.rows)
    setSort(config.initialSort)
    setQueries({})
    setPage(0)
    setSelectedIds(new Set())
    setCsvOutput('')
    setCsvStatus('')
    setCsvError('')
    setSanitizedCount(0)
  }, [resetFingerprint])

  const columnIndexes = useMemo(
    () => new Map(config.data.columns.map((column, index) => [column.id, index])),
    [config.data.columns]
  )

  const filteredRows = useMemo(
    () =>
      rows.filter((row) => {
        for (const filter of config.filters) {
          const columnIndex = columnIndexes.get(filter.columnId)
          if (columnIndex === undefined || !matchesFilter(row.cells[columnIndex] ?? null, filter)) {
            return false
          }
        }
        for (const column of config.data.columns) {
          const query = queries[column.id]?.trim().toLocaleLowerCase()
          if (!query) continue
          const columnIndex = columnIndexes.get(column.id)
          if (
            columnIndex === undefined ||
            !cellText(row.cells[columnIndex] ?? null).toLocaleLowerCase().includes(query)
          ) {
            return false
          }
        }
        return true
      }),
    [columnIndexes, config.data.columns, config.filters, queries, rows]
  )

  const importPastedCsv = () => {
    try {
      const importedRows = importCsvRows(csvSource, config.data.columns)
      setRows(importedRows)
      setSort(config.initialSort)
      setQueries({})
      setPage(0)
      setSelectedIds(new Set())
      setCsvOutput('')
      setSanitizedCount(0)
      setCsvError('')
      setCsvStatus('Imported ' + importedRows.length + ' rows for this local running session only.')
    } catch (cause) {
      setCsvStatus('')
      setCsvError(cause instanceof Error ? cause.message : String(cause))
    }
  }

  const prepareCsvText = () => {
    try {
      const prepared = exportCsvRows(config.data.columns, rows)
      setCsvOutput(prepared.text)
      setSanitizedCount(prepared.sanitizedCount)
      setCsvError('')
      setCsvStatus('CSV text prepared for manual copying.')
    } catch (cause) {
      setCsvOutput('')
      setSanitizedCount(0)
      setCsvStatus('')
      setCsvError(cause instanceof Error ? cause.message : String(cause))
    }
  }

  const sortedRows = useMemo(() => {
    if (!sort) return filteredRows
    const columnIndex = columnIndexes.get(sort.columnId)
    if (columnIndex === undefined) return filteredRows
    const direction = sort.direction === 'ascending' ? 1 : -1
    return filteredRows
      .map((row, sourceIndex) => ({ row, sourceIndex }))
      .sort((left, right) => {
        const compared =
          compareCells(
            left.row.cells[columnIndex] ?? null,
            right.row.cells[columnIndex] ?? null
          ) * direction
        return compared || left.sourceIndex - right.sourceIndex
      })
      .map(({ row }) => row)
  }, [columnIndexes, filteredRows, sort])

  const pageCount = Math.max(1, Math.ceil(sortedRows.length / config.pageSize))
  useEffect(() => setPage((value) => Math.min(value, pageCount - 1)), [pageCount])
  const pageRows = sortedRows.slice(page * config.pageSize, (page + 1) * config.pageSize)

  const toggleSort = (column: OpenPencilDataGridColumn) => {
    if (!column.sortable) return
    setPage(0)
    setSort((current) => {
      if (!current || current.columnId !== column.id) {
        return { columnId: column.id, direction: 'ascending' }
      }
      if (current.direction === 'ascending') {
        return { columnId: column.id, direction: 'descending' }
      }
      return null
    })
  }

  const toggleRow = (rowId: string) => {
    if (config.selectionMode === 'none') return
    setSelectedIds((current) => {
      if (config.selectionMode === 'single') {
        return current.has(rowId) ? new Set() : new Set([rowId])
      }
      const next = new Set(current)
      if (next.has(rowId)) next.delete(rowId)
      else next.add(rowId)
      return next
    })
  }

  const allPageRowsSelected =
    pageRows.length > 0 && pageRows.every((row) => selectedIds.has(row.id))
  const somePageRowsSelected = pageRows.some((row) => selectedIds.has(row.id))
  const pageSelectionIsMixed = somePageRowsSelected && !allPageRowsSelected
  useEffect(() => {
    if (selectAllRef.current) {
      selectAllRef.current.indeterminate = pageSelectionIsMixed
    }
  }, [config.selectionMode, config.showHeader, pageSelectionIsMixed])

  const togglePageRows = () => {
    if (config.selectionMode !== 'multiple') return
    setSelectedIds((current) => {
      const next = new Set(current)
      if (allPageRowsSelected) pageRows.forEach((row) => next.delete(row.id))
      else pageRows.forEach((row) => next.add(row.id))
      return next
    })
  }

  const positionedByClass = className
    ?.split(' ')
    .some((token) => ['absolute', 'fixed', 'relative', 'sticky'].includes(token))
  const positionedByStyle = style?.position !== undefined && style.position !== 'static'
  const hostStyle = {
    ...(positionedByClass || positionedByStyle ? style : { ...style, position: 'relative' as const }),
    color: config.textColor,
    display: 'flex',
    flexDirection: 'column' as const,
    fontSize: config.fontSize,
    overflow: 'hidden'
  }
  const cellStyle = (column: OpenPencilDataGridColumn) => ({
    border: '1px solid ' + config.borderColor,
    boxSizing: 'border-box' as const,
    height: config.density === 'compact' ? 30 : 42,
    padding: config.density === 'compact' ? '4px 8px' : '8px 12px',
    textAlign: column.align,
    verticalAlign: 'middle' as const,
    width: column.width
  })
  const selectionColumn = config.selectionMode === 'none' ? 0 : 44
  const tableWidth =
    config.data.columns.reduce((total, column) => total + column.width, selectionColumn)
  const visuallyHiddenHeaderStyle = {
    border: 0,
    clip: 'rect(0 0 0 0)',
    clipPath: 'inset(50%)',
    height: 1,
    margin: -1,
    overflow: 'hidden',
    padding: 0,
    position: 'absolute' as const,
    whiteSpace: 'nowrap' as const,
    width: 1
  }

  return (
    <div
      {...hostProps}
      className={className}
      data-openpencil-data-grid=""
      style={hostStyle}
    >
      <div
        aria-label="Data grid CSV tools"
        data-openpencil-data-grid-csv-tools=""
        role="region"
        style={{ borderBottom: '1px solid ' + config.borderColor, padding: 8 }}
      >
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6 }}>
          <button onClick={() => setCsvOpen((value) => !value)} type="button">
            {csvOpen ? 'Close CSV import' : 'Paste CSV (local session)'}
          </button>
          <button onClick={prepareCsvText} type="button">Prepare CSV text</button>
        </div>
        {csvOpen ? (
          <div style={{ marginTop: 6 }}>
            <label>
              CSV import text
              <textarea
                maxLength={CSV_MAX_BYTES}
                onChange={(event) => setCsvSource(event.target.value)}
                rows={5}
                spellCheck={false}
                style={{ boxSizing: 'border-box', display: 'block', width: '100%' }}
                value={csvSource}
              />
            </label>
            <button onClick={importPastedCsv} type="button">Import pasted CSV</button>
            <p>
              Imported rows stay local to this running app and do not modify the source design.
            </p>
          </div>
        ) : null}
        {csvOutput ? (
          <div style={{ marginTop: 6 }}>
            <label>
              Prepared CSV text
              <textarea
                readOnly
                rows={5}
                spellCheck={false}
                style={{ boxSizing: 'border-box', display: 'block', width: '100%' }}
                value={csvOutput}
              />
            </label>
            <p>
              Copy manually. No file or clipboard permission is requested.
              {sanitizedCount > 0
                ? ' ' + sanitizedCount + ' formula-like text fields were neutralized.'
                : ''}
            </p>
          </div>
        ) : null}
        {csvStatus ? <p aria-live="polite">{csvStatus}</p> : null}
        {csvError ? <p aria-live="assertive" role="alert">{csvError}</p> : null}
      </div>
      <div
        aria-label="Data grid scroll area"
        data-openpencil-data-grid-scroll=""
        role="region"
        style={{ flex: 1, minHeight: 0, overflow: 'auto' }}
        tabIndex={0}
      >
        <table
          aria-colcount={config.data.columns.length + (selectionColumn ? 1 : 0)}
          aria-rowcount={filteredRows.length}
          style={{ borderCollapse: 'collapse', minWidth: '100%', tableLayout: 'fixed', width: tableWidth }}
        >
          <thead
            data-visually-hidden={config.showHeader ? undefined : ''}
            style={
              config.showHeader
                ? {
                    background: config.headerBackground,
                    position: config.stickyHeader ? 'sticky' : undefined,
                    top: config.stickyHeader ? 0 : undefined,
                    zIndex: config.stickyHeader ? 1 : undefined
                  }
                : visuallyHiddenHeaderStyle
            }
          >
            <tr>
              {config.selectionMode !== 'none' ? (
                <th scope="col" style={{ border: '1px solid ' + config.borderColor, width: 44 }}>
                  {!config.showHeader ? (
                    'Selection'
                  ) : config.selectionMode === 'multiple' ? (
                    <input
                      aria-checked={pageSelectionIsMixed ? 'mixed' : allPageRowsSelected}
                      aria-label="Select all rows on this page"
                      checked={allPageRowsSelected}
                      onChange={togglePageRows}
                      ref={selectAllRef}
                      type="checkbox"
                    />
                  ) : (
                    <span aria-hidden="true">•</span>
                  )}
                </th>
              ) : null}
              {config.data.columns.map((column) => {
                const ariaSort =
                  sort?.columnId === column.id ? sort.direction : ('none' as const)
                return (
                  <th aria-sort={ariaSort} key={column.id} scope="col" style={cellStyle(column)}>
                    {config.showHeader && column.sortable ? (
                      <button onClick={() => toggleSort(column)} type="button">
                        {column.label}
                      </button>
                    ) : (
                      column.label
                    )}
                  </th>
                )
              })}
            </tr>
            {config.showHeader && config.data.columns.some((column) => column.filterable) ? (
              <tr data-openpencil-data-grid-filters="">
                {config.selectionMode !== 'none' ? <th aria-hidden="true" /> : null}
                {config.data.columns.map((column) => (
                  <th key={column.id} scope="col" style={cellStyle(column)}>
                    {column.filterable ? (
                      <input
                        aria-label={'Filter ' + column.label}
                        onChange={(event) => {
                          setPage(0)
                          setQueries((current) => ({
                            ...current,
                            [column.id]: event.target.value
                          }))
                        }}
                        type="search"
                        value={queries[column.id] ?? ''}
                      />
                    ) : null}
                  </th>
                ))}
              </tr>
            ) : null}
          </thead>
          <tbody>
            {pageRows.map((row, rowIndex) => {
              const selected = selectedIds.has(row.id)
              return (
                <tr
                  aria-selected={config.selectionMode === 'none' ? undefined : selected}
                  data-selected={selected || undefined}
                  key={row.id}
                  style={{
                    background: selected
                      ? config.accentColor + '20'
                      : config.striped && rowIndex % 2 === 1
                        ? '#F9FAFB'
                        : undefined
                  }}
                >
                  {config.selectionMode !== 'none' ? (
                    <td style={{ border: '1px solid ' + config.borderColor, textAlign: 'center' }}>
                      <input
                        aria-label={'Select row ' + row.id}
                        checked={selected}
                        name={config.selectionMode === 'single' ? selectionName : undefined}
                        onChange={() => toggleRow(row.id)}
                        type={config.selectionMode === 'single' ? 'radio' : 'checkbox'}
                      />
                    </td>
                  ) : null}
                  {config.data.columns.map((column, columnIndex) => (
                    <td key={column.id} style={cellStyle(column)}>
                      {cellText(row.cells[columnIndex] ?? null)}
                    </td>
                  ))}
                </tr>
              )
            })}
            {pageRows.length === 0 ? (
              <tr>
                <td
                  colSpan={config.data.columns.length + (selectionColumn ? 1 : 0)}
                  style={{ padding: 16, textAlign: 'center' }}
                >
                  No matching rows
                </td>
              </tr>
            ) : null}
          </tbody>
        </table>
      </div>

      <div
        aria-label="Data grid pagination"
        data-openpencil-data-grid-pagination=""
        role="navigation"
      >
        <button disabled={page === 0} onClick={() => setPage((value) => value - 1)} type="button">
          Previous page
        </button>
        <span aria-live="polite">
          Page {page + 1} of {pageCount} · {filteredRows.length} rows
        </span>
        <button
          disabled={page >= pageCount - 1}
          onClick={() => setPage((value) => value + 1)}
          type="button"
        >
          Next page
        </button>
      </div>
      {children}
    </div>
  )
}
`

export function buildOpenPencilDataGridComponent(): string {
  return DATA_GRID_RUNTIME
}

export const DATA_GRID_REACT_MODULE_ADAPTER: ReactModuleAdapter = Object.freeze({
  pluginId: DATA_GRID_PLUGIN_ID,
  moduleType: DATA_GRID_MODULE_TYPE,
  componentName: 'OpenPencilDataGrid',
  runtimePath: 'src/__openpencil_data_grid.tsx',
  rootImportPath: './__openpencil_data_grid',
  nestedImportPath: '../__openpencil_data_grid',
  buildRuntime: buildOpenPencilDataGridComponent
})
