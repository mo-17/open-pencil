interface OpenModalEntry {
  token: symbol
  dialog: HTMLDialogElement
  restoreFocus: HTMLElement | null
}

const openModals: OpenModalEntry[] = []
let bodyLockCount = 0
let bodyOverflowBeforeLock: string | null = null

function addOpenModal(entry: OpenModalEntry): void {
  const previous = openModals.findIndex((candidate) => candidate.token === entry.token)
  if (previous >= 0) openModals.splice(previous, 1)
  openModals.push(entry)
}

function removeOpenModal(token: symbol): { wasTop: boolean; nextTop?: OpenModalEntry } {
  const index = openModals.findIndex((entry) => entry.token === token)
  const wasTop = index >= 0 && index === openModals.length - 1
  if (index >= 0) openModals.splice(index, 1)
  return { wasTop, nextTop: openModals[openModals.length - 1] }
}

function isTopModal(token: symbol): boolean {
  return openModals[openModals.length - 1]?.token === token
}

function lockBody(): () => void {
  if (bodyLockCount === 0) {
    bodyOverflowBeforeLock = document.body.style.overflow
    document.body.style.overflow = 'hidden'
  }
  bodyLockCount += 1
  let released = false
  return () => {
    if (released) return
    released = true
    bodyLockCount = Math.max(0, bodyLockCount - 1)
    if (bodyLockCount > 0) return
    document.body.style.overflow = bodyOverflowBeforeLock ?? ''
    bodyOverflowBeforeLock = null
  }
}

function focusableElements(dialog: HTMLDialogElement): HTMLElement[] {
  return [...dialog.querySelectorAll<HTMLElement>(FOCUSABLE_SELECTOR)].filter(
    (element) => !element.hasAttribute('disabled') && element.getAttribute('aria-hidden') !== 'true'
  )
}

function focusDialog(dialog: HTMLDialogElement): void {
  dialog.focus({ preventScroll: true })
}

function trapTab(event: ReactKeyboardEvent<HTMLDialogElement>): void {
  if (event.key !== 'Tab') return
  const dialog = event.currentTarget
  const focusable = focusableElements(dialog)
  if (focusable.length === 0) {
    event.preventDefault()
    focusDialog(dialog)
    return
  }
  const first = focusable[0]
  const last = focusable[focusable.length - 1]
  const active = document.activeElement
  if (event.shiftKey && (active === first || active === dialog || !dialog.contains(active))) {
    event.preventDefault()
    last.focus({ preventScroll: true })
  } else if (!event.shiftKey && (active === last || !dialog.contains(active))) {
    event.preventDefault()
    first.focus({ preventScroll: true })
  }
}

function footerJustify(align: OpenPencilModalConfig['footerAlign']): CSSProperties['justifyContent'] {
  if (align === 'left') return 'flex-start'
  if (align === 'center') return 'center'
  return 'flex-end'
}

