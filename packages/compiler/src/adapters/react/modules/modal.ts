  const [mounted, setMounted] = useState(false)
  const [visible, setVisible] = useState(false)
  const [reducedMotion, setReducedMotion] = useState(false)
  const baseId = useId().replaceAll(':', '')
  const titleId = baseId + '-title'
  const contentId = baseId + '-content'
  const panelId = baseId + '-panel'

  const clearTimers = useCallback(() => {
    if (closeTimerRef.current !== null) window.clearTimeout(closeTimerRef.current)
    if (openFrameRef.current !== null) window.cancelAnimationFrame(openFrameRef.current)
    closeTimerRef.current = null
    openFrameRef.current = null
  }, [])

  const openModal = useCallback(() => {
    clearTimers()
    if (mounted) setVisible(true)
    else setMounted(true)
  }, [clearTimers, mounted])

  const closeModal = useCallback(() => {
    clearTimers()
    setVisible(false)
    if (reducedMotion) {
      setMounted(false)
      return
    }
    closeTimerRef.current = window.setTimeout(() => {
      closeTimerRef.current = null
      setMounted(false)
    }, TRANSITION_MS)
  }, [clearTimers, reducedMotion])

  useEffect(() => {
    const query = window.matchMedia('(prefers-reduced-motion: reduce)')
    const sync = () => setReducedMotion(query.matches)
    sync()
    query.addEventListener('change', sync)
    return () => query.removeEventListener('change', sync)
  }, [])

  useEffect(() => {
    if (!mounted) return
    const dialog = dialogRef.current
    if (!dialog) return
    const entry: OpenModalEntry = {
      token: tokenRef.current,
      dialog,
      restoreFocus: document.activeElement instanceof HTMLElement ? document.activeElement : null
    }
    dialog.showModal()
    addOpenModal(entry)
    const releaseBody = lockBody()
    openFrameRef.current = window.requestAnimationFrame(() => {
      openFrameRef.current = null
      setVisible(true)
      focusDialog(dialog)
    })
    return () => {
      clearTimers()
      if (dialog.open) dialog.close()
      const { wasTop, nextTop } = removeOpenModal(entry.token)
      releaseBody()
      if (!wasTop) return
      if (nextTop?.dialog.open) focusDialog(nextTop.dialog)
      else if (entry.restoreFocus?.isConnected) entry.restoreFocus.focus({ preventScroll: true })
      else triggerRef.current?.focus({ preventScroll: true })
    }
  }, [clearTimers, mounted])

