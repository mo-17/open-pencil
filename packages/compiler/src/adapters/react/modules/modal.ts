export function buildOpenPencilModalComponent(options?: ReactModuleRuntimeOptions): string {
  if (!options?.microfrontend) return MODAL_RUNTIME
  return MODAL_RUNTIME.replace(
    "import { createPortal } from 'react-dom'",
    "import { createPortal } from 'react-dom'\nimport { microfrontendPortalTarget } from './__microfrontend-context'"
  ).replace(
    '        document.body\n      )',
    '        microfrontendPortalTarget() ?? document.body\n      )'
  )
}

