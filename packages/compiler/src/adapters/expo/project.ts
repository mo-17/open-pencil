export function buildExpoRouteProxy(routeFile: string, pageSlug: string): string {
  const depth = routeFile.split('/').length - 1
  const prefix = '../'.repeat(depth)
  return `export { default } from '${prefix}src/pages/${pageSlug}'\n`
}

export function buildExpoDocumentState(states: readonly IRDocStateDecl[]): string {
  const defaults = Object.fromEntries(
    states.map((state) => [state.name, safeNativeStateDefault(state)])
  )
  return `import { useSyncExternalStore } from 'react'

const values: Record<string, unknown> = ${JSON.stringify(defaults, null, 2)}
const listeners = new Set<() => void>()

function subscribe(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

export function getDocState<T>(name: string): T {
  return values[name] as T
}

export function useDocState<T>(name: string): T {
  return useSyncExternalStore(subscribe, () => getDocState<T>(name), () => getDocState<T>(name))
}

export function setDocState<T>(name: string, next: T | ((previous: T) => T)): void {
  const previous = getDocState<T>(name)
  values[name] = typeof next === 'function' ? (next as (value: T) => T)(previous) : next
  for (const listener of listeners) listener()
}
`
}

function safePackageName(value: string): string {
  const normalized = value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, '-')
    .replace(/^-+|-+$/g, '')
  return normalized || 'openpencil-expo-app'
}

function safeExpoScheme(packageName: string): string {
  const normalized = packageName.replaceAll('_', '-')
  return /^[a-z]/.test(normalized) ? normalized : `openpencil-${normalized}`
}
