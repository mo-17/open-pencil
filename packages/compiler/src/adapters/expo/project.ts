import { safeNativeStateDefault } from '../native-shared'

const EXPO_VERSION = '~57.0.10'
const REACT_VERSION = '19.2.3'
const REACT_NATIVE_VERSION = '0.86.2'
const EXPO_ROUTER_VERSION = '~57.0.10'

export function buildExpoPackageJson(options: CompilerOptions, router: boolean): string {
  const dependencies: Record<string, string> = {
    expo: EXPO_VERSION,
    react: REACT_VERSION,
    'react-native': REACT_NATIVE_VERSION,
    'react-native-safe-area-context': '~5.7.0'
  }
  if (router) {
    dependencies['expo-constants'] = '~57.0.9'
    dependencies['expo-linking'] = '~57.0.5'
    dependencies['expo-router'] = EXPO_ROUTER_VERSION
    dependencies['expo-status-bar'] = '~57.0.1'
    dependencies['react-native-screens'] = '~4.26.0'
  }
  return `${JSON.stringify(
    {
      name: safePackageName(options.packageName),
      version: '0.0.0',
      private: true,
      engines: { node: '>=22.13.0' },
      main: router ? 'expo-router/entry' : 'expo/AppEntry',
      scripts: {
        start: 'expo start',
        android: 'expo start --android',
        ios: 'expo start --ios',
        typecheck: 'tsc --noEmit'
      },
      dependencies,
      devDependencies: { '@types/react': '~19.2.2', typescript: '~6.0.3' }
    },
    null,
    2
  )}\n`
}

export function buildExpoAppJson(options: CompilerOptions, router: boolean): string {
  const packageName = safePackageName(options.packageName)
  const scheme = safeExpoScheme(packageName)
  const productName = options.productName?.trim() || options.packageName.trim() || 'OpenPencil App'
  const expo = {
    name: productName,
    slug: packageName,
    version: '1.0.0',
    orientation: 'default',
    userInterfaceStyle: 'automatic',
    newArchEnabled: true,
    ...(router ? { scheme, plugins: ['expo-router'] } : {})
  }
  return `${JSON.stringify({ expo }, null, 2)}\n`
}

