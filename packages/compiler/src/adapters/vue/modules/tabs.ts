import { TABS_MODULE_TYPE, TABS_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

const TABS_RUNTIME = `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import { computed, ref, useId, watch } from 'vue'

interface TabItem { id: string; label: string; content: string; contentChildName?: string }
interface TabsConfig {
  label: string
  tabs: readonly TabItem[]
  initialTabId: string
  orientation: 'horizontal' | 'vertical'
  activationMode: 'automatic' | 'manual'
  showDivider: boolean
  backgroundColor: string
  textColor: string
  accentColor: string
  fontSize: number
}
const props = defineProps<{ config: TabsConfig }>()
const instanceId = useId().replaceAll(':', '')
const activeId = ref(props.config.initialTabId)
const focusId = ref(props.config.initialTabId)
const tabRefs = new Map<string, HTMLButtonElement>()
const active = computed(() => props.config.tabs.find((tab) => tab.id === activeId.value) ?? props.config.tabs[0])
watch(() => [props.config.initialTabId, props.config.tabs.map((tab) => tab.id).join('\\u0000')], () => {
  const fallback = props.config.tabs.find((tab) => tab.id === props.config.initialTabId)?.id ?? props.config.tabs[0]?.id ?? ''
  if (!props.config.tabs.some((tab) => tab.id === activeId.value)) activeId.value = fallback
  if (!props.config.tabs.some((tab) => tab.id === focusId.value)) focusId.value = fallback
})
const hostStyle = computed(() => ({
  background: props.config.backgroundColor,
  color: props.config.textColor,
  display: 'flex',
  flexDirection: props.config.orientation === 'vertical' ? 'row' as const : 'column' as const,
  minWidth: 0, minHeight: 0
}))
const listStyle = computed(() => ({
  display: 'flex',
  flexDirection: props.config.orientation === 'vertical' ? 'column' as const : 'row' as const,
  flexShrink: 0, gap: '4px', padding: '8px',
  borderBottom: props.config.orientation === 'horizontal' && props.config.showDivider ? '1px solid ' + props.config.accentColor : undefined,
  borderRight: props.config.orientation === 'vertical' && props.config.showDivider ? '1px solid ' + props.config.accentColor : undefined
}))
function focusTab(index: number, activate: boolean): void {
  const length = props.config.tabs.length
  if (!length) return
  const tab = props.config.tabs[((index % length) + length) % length]
  if (!tab) return
  focusId.value = tab.id
  if (activate) activeId.value = tab.id
  tabRefs.get(tab.id)?.focus()
}
function onTabKeyDown(event: KeyboardEvent, index: number): void {
  const previous = props.config.orientation === 'vertical' ? 'ArrowUp' : 'ArrowLeft'
  const next = props.config.orientation === 'vertical' ? 'ArrowDown' : 'ArrowRight'
  const target = event.key === previous ? index - 1 : event.key === next ? index + 1 : event.key === 'Home' ? 0 : event.key === 'End' ? props.config.tabs.length - 1 : null
  if (target !== null) {
    event.preventDefault()
    focusTab(target, props.config.activationMode === 'automatic')
  } else if (props.config.activationMode === 'manual' && (event.key === 'Enter' || event.key === ' ')) {
    event.preventDefault()
    const tab = props.config.tabs[index]
    if (tab) activeId.value = tab.id
  }
}
function setTabRef(id: string, element: unknown): void {
  if (element instanceof HTMLButtonElement) tabRefs.set(id, element)
  else tabRefs.delete(id)
}
</script>
<template>
  <div data-openpencil-tabs="" :style="hostStyle">
    <div role="tablist" :aria-label="config.label" :aria-orientation="config.orientation" :style="listStyle">
      <button v-for="(tab, index) in config.tabs" :key="tab.id" :ref="(element) => setTabRef(tab.id, element)"
        :id="instanceId + '-tab-' + tab.id" role="tab" type="button"
        :aria-controls="instanceId + '-panel-' + tab.id" :aria-selected="tab.id === active?.id"
        :tabindex="tab.id === focusId ? 0 : -1"
        :style="{ background: tab.id === active?.id ? config.accentColor : 'transparent', color: tab.id === active?.id ? config.backgroundColor : config.textColor, fontSize: config.fontSize + 'px' }"
        @click="activeId = tab.id; focusId = tab.id" @focus="focusId = tab.id" @keydown="onTabKeyDown($event, index)"
      >{{ tab.label }}</button>
    </div>
    <div v-if="active" :key="active.id" :id="instanceId + '-panel-' + active.id" role="tabpanel"
      :aria-labelledby="instanceId + '-tab-' + active.id" tabindex="0" class="openpencil-tab-panel"
      :style="{ fontSize: config.fontSize + 'px' }"
    >
      <slot v-if="active.contentChildName || $slots['panel-' + active.id]" :name="'panel-' + active.id" />
      <template v-else>{{ active.content }}</template>
    </div>
    <slot />
  </div>
</template>
<style scoped>
[role=tab]{border:0;border-radius:6px;cursor:pointer;font-family:system-ui,sans-serif;font-weight:600;line-height:1.3;padding:8px 12px;text-align:start}
.openpencil-tab-panel{font-family:system-ui,sans-serif;line-height:1.6;min-height:0;min-width:0;overflow:auto;padding:16px;position:relative}
</style>
`

export function buildOpenPencilVueTabs(): string {
  return TABS_RUNTIME
}

export const TABS_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: TABS_PLUGIN_ID,
  moduleType: TABS_MODULE_TYPE,
  componentName: 'OpenPencilTabs',
  runtimePath: 'src/__openpencil_tabs.vue',
  importPath: '../__openpencil_tabs.vue',
  buildRuntime: buildOpenPencilVueTabs
})
