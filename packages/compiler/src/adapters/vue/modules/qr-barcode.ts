import {
  JSBARCODE_VERSION,
  QRCODE_VERSION,
  QR_BARCODE_RUNTIME_SOURCE
} from '#compiler/adapters/qr-barcode/source'

import { QR_BARCODE_MODULE_TYPE, QR_BARCODE_PLUGIN_ID } from '@open-pencil/core/plugins'

import { VUE_MEDIA_HOST_SOURCE } from './media-host'
import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueQrBarcode(): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import { computed, normalizeClass, normalizeStyle, onBeforeUnmount, onMounted, ref, useAttrs, watch } from 'vue'
// @ts-ignore -- generated source relies on the package's browser entry.
import QRCode from 'qrcode'
import JsBarcode from 'jsbarcode'
${QR_BARCODE_RUNTIME_SOURCE}
defineOptions({ inheritAttrs: false })
const props = defineProps<{ config: OpenPencilQrBarcodeConfig }>()
${VUE_MEDIA_HOST_SOURCE}
const barcode = ref<SVGSVGElement | null>(null), qrDataUrl = ref(''), error = ref('')
let revision = 0
function refresh() {
  const current = ++revision, config = props.config
  error.value = ''; qrDataUrl.value = ''
  if (config.format === 'qr') {
    void QRCode.toDataURL(config.value, qrCodeOptions(config)).then((url: string) => {
      if (current === revision) qrDataUrl.value = url
    }, (cause: unknown) => {
      if (current === revision) error.value = cause instanceof Error ? cause.message : String(cause)
    })
  } else if (barcode.value) {
    try { JsBarcode(barcode.value, config.value, barcodeOptions(config)) }
    catch (cause) { error.value = cause instanceof Error ? cause.message : String(cause) }
  }
}
onMounted(refresh)
watch(() => [props.config.backgroundColor, props.config.errorCorrection, props.config.foregroundColor, props.config.format, props.config.quietZone, props.config.value], refresh, { flush: 'post' })
onBeforeUnmount(() => { revision++ })
</script>
<template><div v-bind="attrs" data-openpencil-qr-barcode="" :style="[hostStyle, { background: config.backgroundColor, color: config.foregroundColor, padding: Math.min(config.quietZone,32)+'px' }]">
  <p v-if="error" role="alert">Unable to generate code: {{error}}</p>
  <template v-if="!error && config.format === 'qr'"><img v-if="qrDataUrl" :src="qrDataUrl" :alt="config.caption || 'QR code'" :draggable="false"/><span v-else aria-live="polite">Generating QR code…</span></template>
  <svg v-if="config.format === 'code128'" v-show="!error" ref="barcode" role="img" :aria-label="config.caption || 'Code 128 barcode'"/>
  <p v-if="config.showCaption && config.caption" data-code-caption="">{{config.caption}}</p><slot/>
</div></template>
<style scoped>
[data-openpencil-qr-barcode]{align-items:center;display:flex;flex-direction:column;justify-content:center;overflow:hidden}
img{height:min(80%,100%);image-rendering:pixelated;max-width:100%;object-fit:contain}
svg{height:min(75%,180px);max-width:100%;width:100%}
span{font:12px system-ui,sans-serif}
[role=alert]{font:12px/1.4 system-ui,sans-serif;margin:12px}
[data-code-caption]{font:600 13px/1.3 system-ui,sans-serif;margin:8px 0 0;text-align:center}
</style>`
}

