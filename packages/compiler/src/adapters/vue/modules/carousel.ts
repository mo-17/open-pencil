import {
  CAROUSEL_TYPES,
  CAROUSEL_INDEX_RUNTIME,
  CAROUSEL_STYLES
} from '#compiler/adapters/carousel/source'
import { CAROUSEL_SWIPE_RUNTIME } from '#compiler/adapters/carousel/swipe'

import { CAROUSEL_MODULE_TYPE, CAROUSEL_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { VueModuleAdapter, VueModuleRuntimeOptions } from './types'

export function buildOpenPencilVueCarousel(options: VueModuleRuntimeOptions = {}): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script lang="ts">
${CAROUSEL_TYPES}
${CAROUSEL_INDEX_RUNTIME}
${CAROUSEL_SWIPE_RUNTIME}
</script>
<script setup lang="ts">
import { computed, normalizeClass, normalizeStyle, onMounted, onUnmounted, ref, useAttrs, watch, type CSSProperties } from 'vue'

defineOptions({ inheritAttrs: false })
const props = defineProps<{ config: OpenPencilCarouselConfig }>()
const attrs = useAttrs()
const REMOTE_MEDIA_ENABLED_BY_DEFAULT = ${options.devMode ? 'false' : 'true'}
const activeIndex = ref(clampIndex(props.config.initialIndex, props.config.slides.length))
const hovered = ref(false)
const focusWithin = ref(false)
const userPaused = ref(false)
const pageHidden = ref(false)
const reducedMotion = ref(false)
const announcement = ref('')
const interacting = ref(false)
const hostRef = ref<HTMLDivElement | null>(null)
const swipeEnabled = computed(() => props.config.swipeEnabled === true && props.config.slides.length > 1)
watch([hostRef, swipeEnabled], (_, __, onCleanup) => {
  if (!hostRef.value || !swipeEnabled.value) return
  onCleanup(installCarouselSwipe(hostRef.value, (direction) => {
    if (props.config.swipeEnabled === true && props.config.slides.length > 1) selectSlide(activeIndex.value + direction)
  }, (active) => { interacting.value = active }))
}, { flush: 'post' })
const paginationHost = ref<HTMLDivElement | null>(null)
const paginationStyle = computed(() => props.config.paginationStyle ?? 'dots')
const authorizedRemoteMediaUrls = ref(new Set<string>())
watch([paginationHost, activeIndex, paginationStyle, () => props.config.showDots, () => props.config.slides.length], (_, __, onCleanup) => {
  onCleanup(observeCarouselPagination(paginationHost.value))
}, { flush: 'post' })
watch([() => props.config.initialIndex, () => props.config.slides.length], () => {
  activeIndex.value = clampIndex(props.config.initialIndex, props.config.slides.length)
})
const paused = computed(() => userPaused.value || pageHidden.value || reducedMotion.value ||
  (props.config.pauseOnHover && hovered.value) || focusWithin.value || interacting.value)
const autoplayEnabled = computed(() => props.config.autoplay && !paused.value && props.config.slides.length > 1 &&
  (props.config.loop || activeIndex.value < props.config.slides.length - 1))
let releaseEnvironment: (() => void) | undefined
onMounted(() => {
  const query = window.matchMedia('(prefers-reduced-motion: reduce)')
  const syncMotion = () => { reducedMotion.value = query.matches }
  const syncVisibility = () => { pageHidden.value = document.hidden }
  syncMotion()
  syncVisibility()
  query.addEventListener('change', syncMotion)
  document.addEventListener('visibilitychange', syncVisibility)
  releaseEnvironment = () => {
    query.removeEventListener('change', syncMotion)
    document.removeEventListener('visibilitychange', syncVisibility)
  }
})
onUnmounted(() => releaseEnvironment?.())
watch([autoplayEnabled, () => props.config.intervalMs, () => props.config.loop, () => props.config.slides.length], (_, __, onCleanup) => {
  if (!autoplayEnabled.value || typeof window === 'undefined') return
  const timer = window.setInterval(() => {
    activeIndex.value = carouselIndex(activeIndex.value + 1, props.config.slides.length, props.config.loop)
  }, props.config.intervalMs)
  onCleanup(() => window.clearInterval(timer))
}, { immediate: true })

function selectSlide(requested: number): void {
  const next = carouselIndex(requested, props.config.slides.length, props.config.loop)
  if (next !== activeIndex.value) {
    const title = props.config.slides[next]?.title ?? ''
    announcement.value = 'Slide ' + (next + 1) + ' of ' + props.config.slides.length + ': ' + title
    activeIndex.value = next
  }
}
function onKeyDown(event: KeyboardEvent): void {
  if (event.defaultPrevented || event.target !== event.currentTarget) return
  const next = event.key === 'ArrowLeft' ? activeIndex.value - 1 : event.key === 'ArrowRight' ? activeIndex.value + 1 : event.key === 'Home' ? 0 : event.key === 'End' ? props.config.slides.length - 1 : null
  if (next === null) return
  event.preventDefault()
  selectSlide(next)
}
function onFocusOut(event: FocusEvent): void {
  const host = event.currentTarget
  if (!(host instanceof Node && event.relatedTarget instanceof Node && host.contains(event.relatedTarget)))
    focusWithin.value = false
}
function allowRemoteMedia(url: string): void {
  hostRef.value?.focus()
  authorizedRemoteMediaUrls.value = new Set([...authorizedRemoteMediaUrls.value, url])
}
const hostStyle = computed(() => {
  const normalized = normalizeStyle([attrs.style])
  const style = typeof normalized === 'object' ? normalized as CSSProperties : undefined
  const positioned = normalizeClass(attrs.class).split(' ').some(token => ['absolute', 'fixed', 'relative', 'sticky'].includes(token))
  return {
    ...(positioned || (style?.position && style.position !== 'static') ? style : { ...style, position: 'relative' as const }),
    '--openpencil-carousel-accent': props.config.accentColor,
    '--openpencil-carousel-background': props.config.backgroundColor,
    '--openpencil-carousel-overlay-opacity': props.config.overlayOpacity ?? 0.45,
    background: props.config.backgroundColor, color: props.config.textColor, overflow: 'hidden'
  }
})
const hostTabIndex = computed(() => typeof attrs.tabindex === 'number' || typeof attrs.tabindex === 'string' ? attrs.tabindex : 0)
const transitionStyle = computed(() => reducedMotion.value ? 'none' : props.config.transition === 'fade' ? 'opacity 300ms ease' : 'transform 300ms ease, opacity 300ms ease')
</script>
<template>
  <div ref="hostRef" v-bind="$attrs" :aria-label="config.label" aria-roledescription="carousel" data-openpencil-carousel="" :data-autoplay="config.autoplay ? true : undefined"
    :data-arrow-position="config.arrowPosition ?? 'bottom-corners'" :data-swipe="swipeEnabled ? true : undefined"
    :data-arrows="config.showArrows && config.slides.length > 1 ? true : undefined" :data-layout="config.layout ?? 'split'" :data-text-position="config.textPosition ?? 'bottom'"
    role="region" :style="hostStyle" :tabindex="hostTabIndex" @keydown="onKeyDown"
    @pointerenter="!$event.defaultPrevented && (hovered = true)" @pointerleave="!$event.defaultPrevented && (hovered = false)" @focusin="focusWithin = true" @focusout="onFocusOut">
    <div data-openpencil-carousel-track="" style="height:100%;position:relative">
      <section v-for="(slide, index) in config.slides" :key="index" :aria-hidden="index !== activeIndex" :inert="index !== activeIndex"
        :aria-label="(index + 1) + ' of ' + config.slides.length + ': ' + slide.title" aria-roledescription="slide"
        :data-active="index === activeIndex ? true : undefined" :data-media="slide.imageUrl ? true : undefined" data-openpencil-carousel-slide="" role="group"
        :data-needs-media="slide.imageUrl && !REMOTE_MEDIA_ENABLED_BY_DEFAULT && !authorizedRemoteMediaUrls.has(slide.imageUrl) ? true : undefined"
        :style="{ inset: 0, opacity: index === activeIndex ? 1 : 0, pointerEvents: index === activeIndex ? 'auto' : 'none', position: 'absolute', transform: config.transition === 'slide' ? 'translateX(' + (index - activeIndex) * 100 + '%)' : undefined, transition: transitionStyle }">
        <div v-if="slide.imageUrl" data-openpencil-carousel-media="">
          <img v-if="REMOTE_MEDIA_ENABLED_BY_DEFAULT || authorizedRemoteMediaUrls.has(slide.imageUrl)" :src="slide.imageUrl" :alt="slide.alt" loading="lazy" :draggable="false" :style="{height:'100%',objectFit:config.imageFit ?? 'cover',width:'100%'}" />
          <button v-else-if="index === activeIndex" data-openpencil-carousel-load-media="" type="button" @click="allowRemoteMedia(slide.imageUrl)">Load remote slide media</button>
        </div>
        <div data-openpencil-carousel-copy="" :style="{textAlign: config.textAlign ?? 'left'}">
          <div data-openpencil-carousel-text="">
          <h2><a v-if="slide.href" :href="slide.href" :tabindex="index === activeIndex ? undefined : -1" style="color:inherit">{{ slide.title }}</a><template v-else>{{ slide.title }}</template></h2>
          <p v-if="slide.description">{{ slide.description }}</p>
          </div>
        </div>
      </section>
    </div>
    <div v-if="config.showArrows && config.slides.length > 1" data-openpencil-carousel-arrows="">
      <button aria-label="Previous slide" :disabled="!config.loop && activeIndex === 0" type="button" @click="selectSlide(activeIndex - 1)">‹</button>
      <button aria-label="Next slide" :disabled="!config.loop && activeIndex === config.slides.length - 1" type="button" @click="selectSlide(activeIndex + 1)">›</button>
    </div>
    <div v-if="config.showDots && (config.slides.length > 1 || paginationStyle !== 'dots')" ref="paginationHost" :aria-label="paginationStyle === 'fraction' ? 'Slide pagination' : 'Choose slide'" data-openpencil-carousel-dots="" :data-pagination="paginationStyle" role="group">
      <span v-if="paginationStyle === 'fraction'">{{ activeIndex + 1 }} / {{ config.slides.length }}</span>
      <template v-else><button v-for="(slide, index) in config.slides" :key="index" :aria-current="index === activeIndex ? 'true' : undefined" :aria-label="'Show slide ' + (index + 1) + ': ' + slide.title"
        type="button" :style="{ color: paginationStyle === 'dots' && index === activeIndex ? config.accentColor : undefined }" @click="selectSlide(index)"><span :hidden="paginationStyle === 'dots'">{{ index + 1 }}</span></button></template>
    </div>
    <button v-if="config.autoplay && config.slides.length > 1" :aria-label="userPaused ? 'Resume carousel' : 'Pause carousel'" data-openpencil-carousel-autoplay="" type="button" @click="userPaused = !userPaused">{{ userPaused ? 'Play' : 'Pause' }}</button>
    <span aria-live="polite" style="height:1px;overflow:hidden;position:absolute;width:1px">{{ announcement }}</span>
    <slot />
  </div>
</template>
<style>
${CAROUSEL_STYLES}
</style>
`
}

export const CAROUSEL_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: CAROUSEL_PLUGIN_ID,
  moduleType: CAROUSEL_MODULE_TYPE,
  componentName: 'OpenPencilCarousel',
  runtimePath: 'src/__openpencil_carousel.vue',
  importPath: '../__openpencil_carousel.vue',
  buildRuntime: buildOpenPencilVueCarousel
})
