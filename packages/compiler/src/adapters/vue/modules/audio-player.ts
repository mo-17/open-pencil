import { AUDIO_PLAYER_MODULE_TYPE, AUDIO_PLAYER_PLUGIN_ID } from '@open-pencil/core/plugins'

import { VUE_MEDIA_HOST_SOURCE } from './media-host'
import type { VueModuleAdapter, VueModuleRuntimeOptions } from './types'

export function buildOpenPencilVueAudioPlayer(options?: VueModuleRuntimeOptions): string {
  const activation = options?.devMode
    ? `const authorizedSource = ref('')
const activeSource = computed(() => authorizedSource.value === props.config.src ? props.config.src : '')
watch(() => props.config.src, () => { authorizedSource.value = '' }, { flush: 'sync' })`
    : `const activeSource = computed(() => props.config.src)`
  const button = options?.devMode
    ? `<button v-if="config.src && !activeSource" data-openpencil-audio-load="" type="button" :style="{ background: config.accentColor, color: config.backgroundColor }" @click="authorizedSource = config.src">Load audio preview</button>`
    : ''
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import { computed, normalizeClass, normalizeStyle, onBeforeUnmount, ref, useAttrs, watch } from 'vue'
interface OpenPencilAudioPlayerConfig {
  src: string
  title: string
  artist: string
  controls: boolean
  autoplay: boolean
  loop: boolean
  muted: boolean
  preload: 'none' | 'metadata'
  volume: number
  playbackRate: number
  backgroundColor: string
  textColor: string
  accentColor: string
}
defineOptions({ inheritAttrs: false })
const props = defineProps<{ config: OpenPencilAudioPlayerConfig }>()
${VUE_MEDIA_HOST_SOURCE}
${activation}
const audio = ref<HTMLAudioElement | null>(null)
let capturedAudio: HTMLAudioElement | null = null
function releaseAudio() {
  if (!capturedAudio) return
  capturedAudio.pause()
  capturedAudio.removeAttribute('src')
  capturedAudio.load()
  capturedAudio = null
}
watch(activeSource, releaseAudio, { flush: 'sync' })
watch(() => [audio.value, props.config.volume, props.config.playbackRate] as const, ([element, volume, rate]) => {
  if (capturedAudio && capturedAudio !== element) releaseAudio()
  capturedAudio = element
  if (element) { element.volume = volume; element.playbackRate = rate }
}, { flush: 'post' })
onBeforeUnmount(releaseAudio)
</script>
<template><div v-bind="attrs" data-openpencil-audio-player="" role="region" :aria-label="config.title" :style="[hostStyle, { background: config.backgroundColor, color: config.textColor }]">
  <div data-audio-icon="" aria-hidden="true" :style="{ background: config.accentColor, color: config.backgroundColor }">♪</div>
  <div data-audio-info=""><strong>{{config.title}}</strong><span v-if="config.artist">{{config.artist}}</span></div>
  <audio v-if="activeSource" :key="activeSource" ref="audio" :src="activeSource" :autoplay="config.autoplay" :controls="config.controls" :loop="config.loop" :muted="config.muted" :preload="config.preload" :style="{ accentColor: config.accentColor }"/>
  <span v-else data-audio-status="">{{config.src ? 'Preview requires confirmation.' : 'Choose an audio source.'}}</span>
  ${button}<slot/>
</div></template>
<style scoped>
[data-openpencil-audio-player]{align-items:center;display:flex;gap:14px;overflow:hidden;padding:12px}
[data-audio-icon]{align-items:center;border-radius:8px;display:flex;flex:0 0 42px;font:700 20px system-ui,sans-serif;height:42px;justify-content:center}
[data-audio-info]{flex:1 1 120px;min-width:0}
[data-audio-info] strong{display:block;overflow:hidden;text-overflow:ellipsis;white-space:nowrap}
[data-audio-info] span{display:block;font:12px system-ui,sans-serif;opacity:.7}
audio{max-width:55%;min-width:180px}
[data-audio-status]{font:12px system-ui,sans-serif;opacity:.72}
[data-openpencil-audio-load]{border:0;border-radius:6px;cursor:pointer;font:600 12px system-ui,sans-serif;padding:8px 12px}
</style>`
}

export const AUDIO_PLAYER_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: AUDIO_PLAYER_PLUGIN_ID,
  moduleType: AUDIO_PLAYER_MODULE_TYPE,
  componentName: 'OpenPencilAudioPlayer',
  runtimePath: 'src/__openpencil_audio_player.vue',
  importPath: '../__openpencil_audio_player.vue',
  buildRuntime: buildOpenPencilVueAudioPlayer
})
