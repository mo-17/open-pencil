import { htmlSandboxSource } from '#compiler/adapters/html/source'

import { HTML_MODULE_TYPE, HTML_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueHTML(): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import {computed,normalizeClass,normalizeStyle,useAttrs} from 'vue'
${htmlSandboxSource(false)}
defineOptions({inheritAttrs:false})
interface OpenPencilHtmlConfig { html:string }
const props=defineProps<{config:OpenPencilHtmlConfig}>()
const attrs=useAttrs()
const sandboxDocument=computed(()=>buildSandboxDocument(props.config.html))
const hostStyle=computed(()=>{
  const inline=normalizeStyle([attrs.style])
  const position=typeof inline==='object'?inline.position:undefined
  const positioned=position!==undefined&&position!=='static'||normalizeClass(attrs.class).split(/\\s+/).some(token=>['absolute','fixed','relative','sticky'].includes(token))
  return {...(!positioned?{position:'relative' as const}:{}),...(typeof inline==='object'?inline:{})}
})
</script>
<template>
  <div v-bind="attrs" data-openpencil-html-preview="" :style="hostStyle">
    <iframe aria-label="HTML preview" title="HTML preview" referrerpolicy="no-referrer" sandbox="" :srcdoc="sandboxDocument" :tabindex="-1" :style="{border:0,height:'100%',inset:0,pointerEvents:'none',position:'absolute',width:'100%'}"/>
    <slot/>
  </div>
</template>
`
}

export const HTML_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: HTML_PLUGIN_ID,
  moduleType: HTML_MODULE_TYPE,
  componentName: 'OpenPencilHtml',
  runtimePath: 'src/__openpencil_html.vue',
  importPath: '../__openpencil_html.vue',
  buildRuntime: buildOpenPencilVueHTML
})
