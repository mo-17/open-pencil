import * as source from '#compiler/adapters/avatar/source'

import { AVATAR_MODULE_TYPE, AVATAR_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { VueModuleAdapter, VueModuleRuntimeOptions } from './types'

export function buildOpenPencilVueAvatar(options?: VueModuleRuntimeOptions): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import {computed,ref,useId} from 'vue'
${source.avatarAssetImports(options?.bundledAssetPaths)}
${source.AVATAR_CONFIG_SOURCE}
${source.AVATAR_PRESENTATION_SOURCE}
const props=defineProps<{config:OpenPencilAvatarConfig}>()
const visual=computed(()=>avatarPresentation(props.config)), clip=useId(), failed=ref<string>()
const showImage=computed(()=>!!visual.value.src && failed.value!==visual.value.src)
function imageFailed(event: Event): void {
 const image=event.currentTarget
 if(image instanceof SVGImageElement && image.getAttribute('href')===visual.value.src) failed.value=visual.value.src
}
</script>
<template><div data-openpencil-avatar="" role="img" :aria-label="config.name">
 <svg data-avatar-surface="" aria-hidden="true" focusable="false" :viewBox="'0 0 '+visual.size+' '+visual.size"
   :style="{maxWidth:visual.size+'px',maxHeight:visual.size+'px'}" preserveAspectRatio="xMidYMid meet">
  <defs><clipPath :id="clip"><rect :width="visual.size" :height="visual.size" :rx="visual.radius"/></clipPath></defs>
  <g :clip-path="'url(#'+clip+')'"><rect :width="visual.size" :height="visual.size" :rx="visual.radius" :fill="config.backgroundColor"/>
  <image v-if="showImage" :key="visual.src" data-avatar-image="" :href="visual.src" :width="visual.size" :height="visual.size"
    :preserveAspectRatio="visual.fit" :opacity="config.imageOpacity ?? 1" @error="imageFailed"/>
  <text v-else data-avatar-fallback="" :x="visual.size/2" :y="visual.size/2" text-anchor="middle" dominant-baseline="central"
    :font-size="visual.fontSize" :fill="config.textColor">{{visual.text}}</text>
  <rect v-if="config.borderWidth>0" :x="config.borderWidth/2" :y="config.borderWidth/2" :width="visual.size-config.borderWidth"
    :height="visual.size-config.borderWidth" :rx="Math.max(0,visual.radius-config.borderWidth/2)" fill="none" :stroke="config.borderColor" :stroke-width="config.borderWidth"/>
  </g></svg><slot/></div></template>
<style>${source.AVATAR_STYLE_SOURCE}</style>`
}
export const AVATAR_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: AVATAR_PLUGIN_ID,
  moduleType: AVATAR_MODULE_TYPE,
  componentName: 'OpenPencilAvatar',
  runtimePath: 'src/__openpencil_avatar.vue',
  importPath: '../__openpencil_avatar.vue',
  buildRuntime: buildOpenPencilVueAvatar
})
