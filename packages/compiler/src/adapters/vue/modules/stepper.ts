import { STEPPER_CONFIG_SOURCE, STEPPER_STYLE_SOURCE } from '#compiler/adapters/navigation/stepper'

import { STEPPER_MODULE_TYPE, STEPPER_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueStepper(): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import { ref, watch } from 'vue'
${STEPPER_CONFIG_SOURCE}
const props = defineProps<{ config: OpenPencilStepperConfig }>()
const current = ref(props.config.currentIndex)
watch([() => JSON.stringify(props.config.items), () => props.config.currentIndex], () => { current.value = props.config.currentIndex }, {flush:'sync'})
function select(index: number): void {
  if (props.config.allowStepClick && !props.config.items[index]?.disabled) current.value = index
}
function stepLabel(item: OpenPencilStepperItem, index: number): string {
  const state = stepState(item, index, current.value)
  return item.title + (state === 'error' ? ' — error' : state === 'completed' ? ' — completed' : '')
}
</script>
<template>
  <div data-openpencil-stepper="" :data-orientation="config.orientation" :aria-label="config.label"
    :style="{background:config.backgroundColor,color:config.textColor,'--op-step-background':config.backgroundColor,
      '--op-step-accent':config.accentColor,'--op-step-error':config.errorColor,
      '--op-step-muted':config.textColor+'33','--op-step-font':config.fontSize+'px'}">
    <ol><li v-for="(item,index) in config.items" :key="index" :data-state="stepState(item,index,current)"
      :data-disabled="item.disabled || undefined" :aria-current="index === current ? 'step' : undefined">
      <component :is="config.allowStepClick ? 'button' : 'div'" :type="config.allowStepClick ? 'button' : undefined"
        :disabled="config.allowStepClick ? item.disabled : undefined" :aria-label="stepLabel(item,index)" @click="select(index)">
        <span data-step-mark="" aria-hidden="true">{{ stepMark(item,index,current,config.showNumbers) }}</span>
        <span data-step-copy=""><span data-step-title="" :title="item.title">{{item.title}}</span>
        <span v-if="item.description" data-step-description="" :title="item.description">{{item.description}}</span></span>
      </component>
    </li></ol><slot />
  </div>
</template>
<style>${STEPPER_STYLE_SOURCE}</style>
`
}
export const STEPPER_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: STEPPER_PLUGIN_ID,
  moduleType: STEPPER_MODULE_TYPE,
  componentName: 'OpenPencilStepper',
  runtimePath: 'src/__openpencil_stepper.vue',
  importPath: '../__openpencil_stepper.vue',
  buildRuntime: buildOpenPencilVueStepper
})
