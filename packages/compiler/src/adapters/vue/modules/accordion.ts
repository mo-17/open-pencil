import {
  ACCORDION_CONFIG_SOURCE,
  ACCORDION_STYLE_SOURCE
} from '#compiler/adapters/accordion/source'

import { ACCORDION_MODULE_TYPE, ACCORDION_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueAccordion(): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import { computed, ref, useId, watch } from 'vue'
${ACCORDION_CONFIG_SOURCE}
const props = defineProps<{ config: OpenPencilAccordionConfig }>()
const instanceId = useId().replaceAll(':', '')
const headers = new Map<string, HTMLButtonElement>()
const openIds = ref(new Set<string>())
watch([() => props.config.allowMultiple, () => props.config.initialOpenIds.join('\\u0000'), () => props.config.items.map(item => item.id).join('\\u0000')], () => {
  const available = new Set(props.config.items.map(item => item.id))
  const requested = props.config.initialOpenIds.filter(id => available.has(id))
  openIds.value = new Set(props.config.allowMultiple ? requested : requested.slice(0, 1))
}, { immediate: true })
const hostStyle = computed(() => ({
  background: props.config.backgroundColor,
  color: props.config.textColor,
  '--openpencil-accordion-accent': props.config.accentColor,
  '--openpencil-accordion-font-size': props.config.fontSize + 'px',
  '--openpencil-accordion-divider': props.config.showDividers ? '1px solid ' + props.config.accentColor + '44' : 'none'
}))
function toggle(id: string): void {
  const next = new Set(props.config.allowMultiple ? openIds.value : [])
  if (openIds.value.has(id)) next.delete(id)
  else next.add(id)
  openIds.value = next
}
function setHeader(id: string, element: unknown): void {
  if (element instanceof HTMLButtonElement) headers.set(id, element)
  else headers.delete(id)
}
function onHeaderKeyDown(event: KeyboardEvent, index: number): void {
  const count = props.config.items.length
  const target = event.key === 'ArrowUp' ? index - 1 : event.key === 'ArrowDown' ? index + 1 : event.key === 'Home' ? 0 : event.key === 'End' ? count - 1 : null
  if (target === null || !count) return
  event.preventDefault()
  const item = props.config.items[((target % count) + count) % count]
  if (item) headers.get(item.id)?.focus()
}
</script>
<template>
  <div data-openpencil-accordion="" role="region" :aria-label="config.label" :style="hostStyle">
    <section v-for="(item, index) in config.items" :key="item.id">
      <h3><button type="button" :id="instanceId + '-header-' + item.id"
        :aria-controls="instanceId + '-panel-' + item.id" :aria-expanded="openIds.has(item.id)"
        :ref="element => setHeader(item.id, element)" @click="toggle(item.id)" @keydown="onHeaderKeyDown($event, index)">
        <span>{{ item.title }}</span><span aria-hidden="true">{{ openIds.has(item.id) ? '−' : '+' }}</span>
      </button></h3>
      <div data-accordion-panel="" :id="instanceId + '-panel-' + item.id" :aria-labelledby="instanceId + '-header-' + item.id"
        :role="!config.allowMultiple || config.items.length <= 6 ? 'region' : undefined" :hidden="!openIds.has(item.id)">{{ item.content }}</div>
    </section>
    <slot />
  </div>
</template>
<style>${ACCORDION_STYLE_SOURCE}</style>
`
}

export const ACCORDION_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: ACCORDION_PLUGIN_ID,
  moduleType: ACCORDION_MODULE_TYPE,
  componentName: 'OpenPencilAccordion',
  runtimePath: 'src/__openpencil_accordion.vue',
  importPath: '../__openpencil_accordion.vue',
  buildRuntime: buildOpenPencilVueAccordion
})
