import * as emptySource from '#compiler/adapters/empty-state/source'

import * as emptyState from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueEmptyState(): string {
  const metrics = emptySource.EMPTY_STATE_SVG_METRICS
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import {useId} from 'vue'
${emptySource.EMPTY_STATE_CONFIG_SOURCE}
defineProps<{config:OpenPencilEmptyStateConfig}>()
const id=useId(),titleId=id+'-title',descriptionId=id+'-description'
</script>
<template><div data-openpencil-empty-state="" :data-alignment="config.alignment" role="group" :aria-labelledby="titleId"
 :aria-describedby="config.description?descriptionId:undefined" :style="emptyStateStyles(config)">
 <div data-empty-body="">
 <svg v-if="config.illustration!=='none'" data-empty-illustration="" aria-hidden="true" focusable="false" viewBox="0 0 ${metrics.viewBox} ${metrics.viewBox}">
 <circle cx="32" cy="32" r="30" fill="currentColor" opacity="${metrics.illustrationOpacity}"/>
 <path :d="emptyIllustrations[config.illustration]" fill="none" stroke="currentColor" stroke-width="${metrics.illustrationStroke}"/></svg>
 <p data-empty-title="" :id="titleId">{{config.title}}</p>
 <p v-if="config.description" data-empty-description="" :id="descriptionId">{{config.description}}</p>
 </div><slot/></div></template>
<style>${emptySource.EMPTY_STATE_STYLE_SOURCE}</style>`
}
export const EMPTY_STATE_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: emptyState.EMPTY_STATE_PLUGIN_ID,
  moduleType: emptyState.EMPTY_STATE_MODULE_TYPE,
  componentName: 'OpenPencilEmptyState',
  runtimePath: 'src/__openpencil_empty_state.vue',
  importPath: '../__openpencil_empty_state.vue',
  buildRuntime: buildOpenPencilVueEmptyState
})
