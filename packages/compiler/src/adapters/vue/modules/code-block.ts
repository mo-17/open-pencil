import { CODE_BLOCK_CONTROLLER_SOURCE } from '#compiler/adapters/code-block/controller'
import * as codeBlockSource from '#compiler/adapters/code-block/source'

import * as codeBlock from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueCodeBlock(): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import {computed,onMounted,onBeforeUnmount,onUpdated,ref,useAttrs,watch} from 'vue'
${codeBlockSource.CODE_BLOCK_CONFIG_SOURCE}
${CODE_BLOCK_CONTROLLER_SOURCE}
const props=defineProps<{config:OpenPencilCodeBlockConfig}>(),attrs=useAttrs()
const host=ref<HTMLDivElement|null>(null),status=ref<CodeCopyStatus>('idle'),language=ref(typeof attrs.lang==='string'?attrs.lang:'en')
const key=computed(()=>codeBlockConfigKey(props.config)),lines=computed(()=>props.config.code.split(/\\r\\n|\\r|\\n/))
const messages=computed(()=>codeBlockMessages(language.value)),hostStyle=computed(()=>codeBlockStyle(props.config))
const controller=createCodeCopyController(()=>({key:key.value,code:props.config.code,enabled:props.config.showCopyButton,alive:host.value?.isConnected===true}),
 async(code)=>{if(!navigator.clipboard?.writeText)throw new Error('Clipboard unavailable');await navigator.clipboard.writeText(code)},
 (value)=>{status.value=value})
function updateLanguage():void {language.value=codeBlockLocale(host.value)}
function copy():void {updateLanguage();void controller.copy()}
watch(key,()=>controller.reset(),{flush:'sync'})
watch(()=>attrs.lang,()=>controller.reset(),{flush:'sync'})
onMounted(updateLanguage);onUpdated(updateLanguage);onBeforeUnmount(()=>controller.destroy())
</script>
<template>
 <div ref="host" data-openpencil-code-block="" role="region" :aria-label="config.label" :data-theme="config.theme" :data-language="config.language" :data-code-wrap="config.wrapLines" :data-code-numbers="config.showLineNumbers" :style="hostStyle">
  <div data-code-header=""><div data-code-meta=""><span data-code-title="" :title="config.label">{{config.label}}</span><span data-code-language="">{{config.language}}</span></div>
   <button v-if="config.showCopyButton" data-code-copy="" type="button" :disabled="status==='pending'" :aria-busy="status==='pending'" @click="copy">{{messages.copy}}</button>
  </div>
  <div data-code-scroll="" tabindex="0"><pre><code><span v-for="(line,index) in lines" :key="index" data-code-row=""><span v-if="config.showLineNumbers" data-code-number="" aria-hidden="true">{{index+1}}</span><span data-code-text="">{{line}}</span></span></code></pre></div>
  <p data-code-status="" aria-live="polite" role="status">{{status==='idle'?'':messages[status]}}</p>
  <slot/>
 </div>
</template>
<style>${codeBlockSource.CODE_BLOCK_STYLE_SOURCE}</style>
`
}

export const CODE_BLOCK_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: codeBlock.CODE_BLOCK_PLUGIN_ID,
  moduleType: codeBlock.CODE_BLOCK_MODULE_TYPE,
  componentName: 'OpenPencilCodeBlock',
  runtimePath: 'src/__openpencil_code_block.vue',
  importPath: '../__openpencil_code_block.vue',
  buildRuntime: buildOpenPencilVueCodeBlock
})
