import * as badgeSource from '#compiler/adapters/badge/source'

import * as badge from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueBadge(): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import {computed,normalizeClass,normalizeStyle,useAttrs} from 'vue'
${badgeSource.BADGE_CONFIG_SOURCE}
${badgeSource.BADGE_RUNTIME_SOURCE}
defineOptions({inheritAttrs:false})
const props=defineProps<{config:OpenPencilBadgeConfig}>()
const attrs=useAttrs()
const hostStyle=computed(()=>{
  const inline=normalizeStyle([attrs.style])
  const position=typeof inline==='object'?inline.position:undefined
  const positioned=position!==undefined&&position!=='static'||normalizeClass(attrs.class).split(/\\s+/).some(token=>['absolute','fixed','relative','sticky'].includes(token))
  return {...(!positioned?{position:'relative' as const}:{}),...badgeStyle(props.config)}
})
</script>
<template>
  <div v-bind="attrs" data-openpencil-badge="" :data-badge-mode="config.mode" :data-badge-placement="config.placement" :style="hostStyle">
    <span data-badge-host=""><span data-badge-host-text="">{{config.hostLabel}}</span></span>
    <span v-if="badgeVisible(config)" data-badge-value="" aria-hidden="true"><span data-badge-value-text="">{{badgeText(config)}}</span></span>
    <span v-if="badgeVisible(config)&&config.mode==='count'" data-badge-count-label="">{{config.label}}: {{config.count}}</span>
  </div>
</template>
<style>${badgeSource.BADGE_STYLE_SOURCE}</style>
`
}

export const BADGE_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: badge.BADGE_PLUGIN_ID,
  moduleType: badge.BADGE_MODULE_TYPE,
  componentName: 'OpenPencilBadge',
  runtimePath: 'src/__openpencil_badge.vue',
  importPath: '../__openpencil_badge.vue',
  buildRuntime: buildOpenPencilVueBadge
})
