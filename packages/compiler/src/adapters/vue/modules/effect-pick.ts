import { effectPickRuntimeSource } from '#compiler/adapters/effect-pick/source'

import {
  EFFECT_PICK_CATALOG,
  EFFECT_PICK_MODULE_TYPE,
  EFFECT_PICK_PLUGIN_ID
} from '@open-pencil/core/plugins'

import type { VueModuleAdapter, VueModuleRuntimeOptions } from './types'

export function buildOpenPencilVueEffectPick(options?: VueModuleRuntimeOptions): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import {onMounted,onBeforeUnmount,ref,watch,useAttrs} from 'vue'
${effectPickRuntimeSource(options?.effectPickArtifacts ?? EFFECT_PICK_CATALOG, true)}
defineOptions({inheritAttrs:false})
const props=defineProps<{config:OpenPencilEffectPickConfig}>(),attrs=useAttrs(),emit=defineEmits<{click:[event:MouseEvent]}>(),host=ref<HTMLElement|null>(null)
let controller:ReturnType<typeof mountEffectPick>|null=null
onMounted(()=>{if(host.value)controller=mountEffectPick(host.value,props.config,event=>emit('click',event))})
watch(()=>props.config,config=>controller?.setConfig(config),{deep:true})
onBeforeUnmount(()=>{controller?.destroy();controller=null})
</script>
<template><div v-bind="attrs" data-openpencil-effect-pick=""><div ref="host" style="width:100%;height:100%"/><slot/></div></template>
`
}

export const EFFECT_PICK_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: EFFECT_PICK_PLUGIN_ID,
  moduleType: EFFECT_PICK_MODULE_TYPE,
  componentName: 'OpenPencilEffectPick',
  runtimePath: 'src/__openpencil_effect_pick.vue',
  importPath: '../__openpencil_effect_pick.vue',
  buildRuntime: buildOpenPencilVueEffectPick
})
