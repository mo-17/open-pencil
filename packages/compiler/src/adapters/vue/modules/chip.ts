import { CHIP_CONFIG_SOURCE, CHIP_STYLE_SOURCE } from '#compiler/adapters/chip/source'

import { CHIP_MODULE_TYPE, CHIP_PLUGIN_ID } from '@open-pencil/core/plugins'

import type { VueModuleAdapter } from './types'

export function buildOpenPencilVueChip(): string {
  return `<!-- Auto-generated by OpenPencil compiler. Do not edit by hand. -->
<script setup lang="ts">
import {computed,nextTick,ref,watch} from 'vue'
${CHIP_CONFIG_SOURCE}
const props=defineProps<{config:OpenPencilChipConfig}>()
const key=computed(()=>chipConfigKey(props.config))
const selected=ref(props.config.selectable && props.config.initialSelected),removed=ref(false)
const host=ref<HTMLDivElement|null>(null)
watch(key,()=>{selected.value=props.config.selectable && props.config.initialSelected;removed.value=false},{flush:'sync'})
const hostStyle=computed(()=>({'--chip-font':props.config.fontSize+'px','--chip-radius':props.config.borderRadius+'px',
  '--chip-color':props.config.color,'--chip-color-soft':props.config.color+'1F','--chip-filled-text':props.config.filledTextColor}))
function remove():void {
  if(!props.config.deletable || props.config.disabled) return
  const deletedKey=key.value
  removed.value=true
  void nextTick(()=>{if(removed.value && key.value===deletedKey)host.value?.focus()})
}
function select():void {if(props.config.selectable && !props.config.disabled)selected.value=!selected.value}
function onKeyDown(event:KeyboardEvent):void {
  if((event.key==='Delete'||event.key==='Backspace') && props.config.deletable && !props.config.disabled){
    event.preventDefault();event.stopPropagation();remove()
  }
}
</script>
<template>
  <div ref="host" tabindex="-1" data-openpencil-chip="" :data-variant="config.variant" :data-selected="selected" :data-disabled="config.disabled"
    :data-removed="removed" :aria-label="removed?config.label+': '+config.removedLabel:undefined" :style="hostStyle">
    <div v-if="!removed" data-chip-body="">
      <component :is="config.selectable?'button':'span'" :type="config.selectable?'button':undefined" data-chip-main=""
        :aria-label="config.selectable?config.label:undefined" :aria-pressed="config.selectable?selected:undefined"
        :disabled="config.selectable?config.disabled:undefined" @keydown="onKeyDown" @click="select">
        <svg v-if="selected" aria-hidden="true" viewBox="0 0 16 16" focusable="false"><path :d="checkPath"/></svg>
        <span data-chip-label="" :title="config.label">{{config.label}}</span>
      </component>
      <button v-if="config.deletable" type="button" data-chip-delete="" :disabled="config.disabled"
        :aria-label="config.deleteLabel+': '+config.label" @keydown="onKeyDown" @click="remove">
        <svg aria-hidden="true" viewBox="0 0 16 16" focusable="false"><path :d="deletePath"/></svg>
      </button>
    </div>
    <span data-chip-announcement="" role="status">{{removed?config.label+': '+config.removedLabel:''}}</span>
    <slot/>
  </div>
</template>
<style>${CHIP_STYLE_SOURCE}</style>
`
}
export const CHIP_VUE_MODULE_ADAPTER: VueModuleAdapter = Object.freeze({
  pluginId: CHIP_PLUGIN_ID,
  moduleType: CHIP_MODULE_TYPE,
  componentName: 'OpenPencilChip',
  runtimePath: 'src/__openpencil_chip.vue',
  importPath: '../__openpencil_chip.vue',
  buildRuntime: buildOpenPencilVueChip
})
