import type { IRFieldValidation } from '#compiler/ir/types'

import { docStateTypeScript, scriptExpression, scriptJson, type VueEmitContext } from '../shared'

export const VUE_VALIDATION_RUNTIME_FILE = 'src/lowcode-validation.ts'
export const VUE_VALIDATION_CSS_FILE = 'src/lowcode-validation.css'
export const VUE_ASYNC_VALIDATION_ERROR = 'Remote validation is unavailable in this Vue export.'

export function buildVueValidationRuntime(): string {
  return `// Auto-generated by OpenPencil. Do not edit by hand.
export interface OpenPencilValidationRules {
  required?: boolean
  pattern?: string
  minLength?: number
  maxLength?: number
  min?: number
  max?: number
  messages?: {
    required?: string
    pattern?: string
    minLength?: string
    maxLength?: string
    min?: string
    max?: string
  }
}

export function __opValidateValue(
  value: unknown,
  rules: OpenPencilValidationRules
): string | null {
  const messages = rules.messages
  const text = value == null ? '' : String(value)
  const requiredEmpty =
    value == null ||
    value === false ||
    (Array.isArray(value) && value.length === 0) ||
    (typeof value === 'string' && value.trim() === '')
  if (rules.required && requiredEmpty) {
    return messages?.required ?? 'This field is required'
  }
  if (text === '') return null
  if (rules.minLength != null && text.length < rules.minLength) {
    return messages?.minLength ?? 'Must be at least ' + rules.minLength + ' characters'
  }
  if (rules.maxLength != null && text.length > rules.maxLength) {
    return messages?.maxLength ?? 'Must be at most ' + rules.maxLength + ' characters'
  }
  if (rules.pattern != null && !new RegExp(rules.pattern).test(text)) {
    return messages?.pattern ?? 'Invalid format'
  }
  if (rules.min != null && Number(value) < rules.min) {
    return messages?.min ?? 'Must be at least ' + rules.min
  }
  if (rules.max != null && Number(value) > rules.max) {
    return messages?.max ?? 'Must be at most ' + rules.max
  }
  return null
}
`
}

