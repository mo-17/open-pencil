export function buildVueValidationGlue(
  fields: readonly IRFieldValidation[],
  context: VueEmitContext
): string[] {
  if (fields.length === 0) return []
  const validators = fields.map((field) => buildValidator(field, context)).join('\n')
  return [
    `const __fieldErrors = __vueRef<Record<string, string | null>>({})`,
    `const __validators: Record<string, (valueOverride?: unknown) => string | null> = {`,
    validators,
    `}`,
    `function __validateFieldValue(id: string, value: unknown): string | null {`,
    `  const error = __validators[id]?.(value) ?? null`,
    `  __fieldErrors.value = { ...__fieldErrors.value, [id]: error }`,
    `  return error`,
    `}`,
    `function __validateField(id: string): string | null {`,
    `  const error = __validators[id]?.() ?? null`,
    `  __fieldErrors.value = { ...__fieldErrors.value, [id]: error }`,
    `  return error`,
    `}`,
    `function __validateFields(ids: readonly string[]): boolean {`,
    `  const next = { ...__fieldErrors.value }`,
    `  let valid = true`,
    `  for (const id of ids) {`,
    `    const error = __validators[id]?.() ?? null`,
    `    next[id] = error`,
    `    if (error !== null) valid = false`,
    `  }`,
    `  __fieldErrors.value = next`,
    `  return valid`,
    `}`
  ]
}

function buildValidator(field: IRFieldValidation, context: VueEmitContext): string {
  const stateAlias = context.identAliases.get(field.stateName) ?? field.stateName
  let stateRead = stateAlias
  if (field.stateKind === 'docState') {
    stateRead = `__getDocState<${docStateTypeScript(context.docStateTypes.get(field.stateName))}>(${scriptJson(field.stateName)})`
  } else if (context.refNames.has(stateAlias)) {
    stateRead = `${stateAlias}.value`
  }
  const lines = [
    `  ${scriptJson(field.key)}: (valueOverride?: unknown) => {`,
    `    const value = valueOverride !== undefined ? valueOverride : ${stateRead}`,
    `    let error = __opValidateValue(value, ${scriptJson(field.rules)})`
  ]
  if (field.custom) {
    lines.push(
      `    if (error === null && !(${scriptExpression(field.custom.ast, context.refNames, context.identAliases)})) error = ${scriptJson(field.custom.message)}`
    )
  }
  if (field.async) {
    lines.push(`    if (error === null) error = ${scriptJson(VUE_ASYNC_VALIDATION_ERROR)}`)
  }
  lines.push('    return error', '  },')
  return lines.join('\n')
}

export function vueValidationErrorId(key: string): string {
  let hash = 2166136261
  for (let index = 0; index < key.length; index++) {
    hash ^= key.charCodeAt(index)
    hash = Math.imul(hash, 16777619)
  }
  return `openpencil-validation-error-${(hash >>> 0).toString(36)}`
}

export function vueValidationKeyBinding(context: VueEmitContext, key: string): string {
  const existing = context.validationKeyBindings.get(key)
  if (existing) return existing
  context.expressionIndex += 1
  const binding = `__opValidationKey_${context.expressionIndex}`
  context.validationKeyBindings.set(key, binding)
  context.templateBindings.push(`const ${binding} = ${scriptJson(key)}`)
  return binding
}
