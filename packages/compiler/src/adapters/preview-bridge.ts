function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

function hasExactKeys(value: Record<string, unknown>, expected: readonly string[]): boolean {
  const keys = Object.keys(value)
  return keys.length === expected.length && keys.every((key) => expected.includes(key))
}

function readFrameContext(): PreviewFrameContext | null {
  try {
    const candidate: unknown = JSON.parse(window.name)
    if (!isRecord(candidate)) return null
    const legacyContext = hasExactKeys(candidate, [
      'protocol',
      'channel',
      'parentOrigin',
      'transport'
    ])
    const automationContext = hasExactKeys(candidate, [
      'protocol',
      'channel',
      'parentOrigin',
      'transport',
      'automation'
    ])
    if (!legacyContext && !automationContext) return null
    if (
      candidate.protocol !== CHANNEL_PROTOCOL ||
      typeof candidate.channel !== 'string' ||
      candidate.channel.length < 16 ||
      candidate.channel.length > MAX_CHANNEL_LENGTH ||
      !/^[A-Za-z0-9_-]+$/.test(candidate.channel) ||
      typeof candidate.parentOrigin !== 'string' ||
      (candidate.transport !== 'window' && candidate.transport !== 'message-port') ||
      (automationContext && typeof candidate.automation !== 'boolean')
    ) {
      return null
    }
    const parsed = new URL(candidate.parentOrigin)
    const canonicalTauriOrigin = candidate.parentOrigin === 'tauri://localhost'
    if (
      !canonicalTauriOrigin &&
      (parsed.origin !== candidate.parentOrigin || parsed.username || parsed.password)
    ) {
      return null
    }
    return {
      protocol: CHANNEL_PROTOCOL,
      channel: candidate.channel,
      parentOrigin: candidate.parentOrigin,
      transport: candidate.transport,
      automation: automationContext && candidate.automation === true
    }
  } catch {
    return null
  }
}

function allowsAutomationContext(context: PreviewFrameContext): boolean {
  if (!import.meta.env.DEV) return false
  if (!context.automation || context.transport !== 'window') return false
  if (context.parentOrigin === 'tauri://localhost') return true
  try {
    const parsed = new URL(context.parentOrigin)
    return (
      parsed.protocol === 'http:' &&
      (parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1') &&
      parsed.port !== ''
    )
  } catch {
    return false
  }
}

function validRoute(value: unknown): value is string {
  return (
    typeof value === 'string' &&
    value.length > 0 &&
    value.length <= MAX_ROUTE_LENGTH &&
    value.startsWith('/') &&
    !value.startsWith('//') &&
    !value.includes('\\\\') &&
    !/[\\u0000-\\u001f\\u007f]/.test(value)
  )
}

function validDocStateValue(value: unknown): boolean {
  const pending: unknown[] = [value]
  const seen = new Set<object>()
  let values = 0
  let bytes = 0
  while (pending.length > 0) {
    const current = pending.pop()
    values += 1
    if (values > MAX_DOC_STATE_VALUES) return false
    if (
      current === null ||
      typeof current === 'boolean' ||
      (typeof current === 'number' && Number.isFinite(current))
    ) {
      bytes += 8
      if (bytes > MAX_PORTABLE_MESSAGE_BYTES) return false
      continue
    }
    if (typeof current === 'string') {
      if (current.length > MAX_DOC_STATE_STRING_LENGTH) return false
      bytes += current.length * 2
      if (bytes > MAX_PORTABLE_MESSAGE_BYTES) return false
      continue
    }
    if (!isRecord(current) && !Array.isArray(current)) return false
    if (seen.has(current)) return false
    seen.add(current)
    if (Array.isArray(current)) {
      bytes += current.length * 8
      if (bytes > MAX_PORTABLE_MESSAGE_BYTES) return false
      pending.push(...current)
      continue
    }
    if (Object.getOwnPropertySymbols(current).length > 0) return false
    const descriptors = Object.getOwnPropertyDescriptors(current)
    for (const [key, descriptor] of Object.entries(descriptors)) {
      if (
        key.length > MAX_DOC_STATE_NAME_LENGTH ||
        !descriptor.enumerable ||
        !Object.hasOwn(descriptor, 'value')
      ) {
        return false
      }
      bytes += key.length * 2 + 8
      if (bytes > MAX_PORTABLE_MESSAGE_BYTES) return false
      pending.push(descriptor.value)
    }
  }
  return true
}

function validMotionDebugSnapshot(value: unknown): boolean {
  if (!isRecord(value)) return false
  const entries = Object.getOwnPropertyDescriptor(value, 'entries')?.value
  return (
    Array.isArray(entries) &&
    entries.length <= MAX_MOTION_DEBUG_ENTRIES &&
    validDocStateValue(value)
  )
}

function validAutomationRequestId(value: unknown): value is string {
  return (
    typeof value === 'string' &&
    value.length >= 16 &&
    value.length <= MAX_AUTOMATION_REQUEST_ID_LENGTH &&
    /^[A-Za-z0-9_-]+$/.test(value)
  )
}

function validAutomationLocator(by: unknown, locator: unknown): by is AutomationLocator {
  if (
    by !== 'testId' &&
    by !== 'buttonText' &&
    by !== 'placeholder' &&
    by !== 'body'
  ) {
    return false
  }
  if (typeof locator !== 'string') return false
  if (by === 'body') return locator === ''
  return (
    locator.length > 0 &&
    locator.length <= MAX_AUTOMATION_LOCATOR_LENGTH &&
    !/[\\u0000-\\u001f\\u007f]/.test(locator)
  )
}

function parseAutomationInbound(value: Record<string, unknown>): InboundAutomation | null {
  if (!validAutomationRequestId(value.requestId)) return null
  if (value.action === 'click') {
    if (
      !hasExactKeys(value, [
        'source',
        'channel',
        'type',
        'requestId',
        'action',
        'by',
        'locator'
      ]) ||
      (value.by !== 'testId' && value.by !== 'buttonText') ||
      !validAutomationLocator(value.by, value.locator)
    ) {
      return null
    }
    return value as unknown as InboundAutomationClick
  }
  if (value.action === 'set') {
    if (
      !hasExactKeys(value, [
        'source',
        'channel',
        'type',
        'requestId',
        'action',
        'by',
        'locator',
        'value'
      ]) ||
      (value.by !== 'testId' && value.by !== 'placeholder') ||
      !validAutomationLocator(value.by, value.locator) ||
      typeof value.value !== 'string' ||
      value.value.length > MAX_AUTOMATION_INPUT_LENGTH
    ) {
      return null
    }
    return value as unknown as InboundAutomationSet
  }
  if (value.action === 'wait') {
    if (
      !hasExactKeys(value, [
        'source',
        'channel',
        'type',
        'requestId',
        'action',
        'by',
        'locator',
        'text',
        'timeoutMs'
      ]) ||
      !validAutomationLocator(value.by, value.locator) ||
      (value.text !== null &&
        (typeof value.text !== 'string' ||
          value.text.length === 0 ||
          value.text.length > MAX_AUTOMATION_INPUT_LENGTH ||
          /[\\u0000-\\u001f\\u007f]/.test(value.text))) ||
      !Number.isSafeInteger(value.timeoutMs) ||
      (value.timeoutMs as number) < 0 ||
      (value.timeoutMs as number) > MAX_AUTOMATION_TIMEOUT_MS
    ) {
      return null
    }
    return value as unknown as InboundAutomationWait
  }
  if (value.action === 'read-safe-text') {
    if (
      !hasExactKeys(value, [
        'source',
        'channel',
        'type',
        'requestId',
        'action',
        'by',
        'locator'
      ]) ||
      !validAutomationLocator(value.by, value.locator)
    ) {
      return null
    }
    return value as unknown as InboundAutomationRead
  }
  return null
}

function parseInbound(value: unknown, channel: string): Inbound | null {
  if (!isRecord(value) || value.source !== INBOUND_SOURCE || value.channel !== channel) return null
  if (value.type === 'select' && hasExactKeys(value, ['source', 'channel', 'type', 'id'])) {
    return value.id === null ||
      (typeof value.id === 'string' && value.id.length > 0 && value.id.length <= MAX_NODE_ID_LENGTH)
      ? (value as unknown as InboundSelect)
      : null
  }
  if (value.type === 'navigate' && hasExactKeys(value, ['source', 'channel', 'type', 'route'])) {
    return validRoute(value.route) ? (value as unknown as InboundNavigate) : null
  }
  if (
    value.type === 'docState' &&
    hasExactKeys(value, ['source', 'channel', 'type', 'name', 'value']) &&
    typeof value.name === 'string' &&
    value.name.length > 0 &&
    value.name.length <= MAX_DOC_STATE_NAME_LENGTH &&
    validDocStateValue(value.value)
  ) {
    return value as unknown as InboundDocState
  }
  if (value.type === 'theme' && hasExactKeys(value, ['source', 'channel', 'type', 'theme'])) {
    return value.theme === 'light' || value.theme === 'dark'
      ? (value as unknown as InboundTheme)
      : null
  }
  if (
    value.type === 'motionDebug' &&
    hasExactKeys(value, ['source', 'channel', 'type', 'enabled']) &&
    typeof value.enabled === 'boolean'
  ) {
    return value as unknown as InboundMotionDebug
  }
  if (value.type === 'automation') return parseAutomationInbound(value)
  return null
}

