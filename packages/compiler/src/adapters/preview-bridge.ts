  function normalizedText(value: string): string {
    return value.trim().split(/\\s+/).join(' ')
  }

  function elementVisible(element: HTMLElement): boolean {
    if (element.hidden || element.closest('[hidden],[aria-hidden="true"]')) return false
    const style = getComputedStyle(element)
    if (style.display === 'none' || style.visibility === 'hidden' || style.opacity === '0') {
      return false
    }
    const rect = element.getBoundingClientRect()
    return rect.width > 0 && rect.height > 0
  }

  const AUTOMATION_NATIVE_CONTROL_SELECTOR =
    'a[href],button,input,textarea,select,option,optgroup,datalist,fieldset,legend,label,output,progress,meter,details,summary'
  const AUTOMATION_PRIVATE_TEXT_SELECTOR =
    'script,style,noscript,template,[contenteditable]:not([contenteditable="false"]),[role~="textbox" i],[data-op-sensitive]'

  function safeVisibleText(root: HTMLElement, allowButtonRoot = false): string {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
    const parts: string[] = []
    let bytes = 0
    let visited = 0
    while (walker.nextNode()) {
      visited += 1
      if (visited > MAX_AUTOMATION_SCAN_ELEMENTS) break
      const parent = walker.currentNode.parentElement
      const nativeControl = parent?.closest(AUTOMATION_NATIVE_CONTROL_SELECTOR)
      if (
        !parent ||
        parent.isContentEditable ||
        parent.closest(AUTOMATION_PRIVATE_TEXT_SELECTOR) ||
        (nativeControl !== null &&
          !(allowButtonRoot && root instanceof HTMLButtonElement && nativeControl === root)) ||
        !elementVisible(parent)
      ) {
        continue
      }
      const text = normalizedText(walker.currentNode.nodeValue ?? '')
      if (!text) continue
      const remaining = MAX_AUTOMATION_TEXT_LENGTH - bytes
      if (remaining <= 0) break
      parts.push(text.slice(0, remaining))
      bytes += Math.min(text.length, remaining)
    }
    return normalizedText(parts.join(' ')).slice(0, MAX_AUTOMATION_TEXT_LENGTH)
  }

