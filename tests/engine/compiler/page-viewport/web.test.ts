import { describe, expect, test } from 'bun:test'

import { pageViewportNodes } from '#compiler/adapters/page-viewport/project'
import { collectTree } from '#compiler/ir/collect/tree'

import { compile, withDefaults } from '@open-pencil/compiler'

import {
  pageViewportFixture,
  pageViewportGraph,
  pageViewportBandsFixture
} from '#tests/helpers/compiler/page-viewport/fixture'
import { renderPageViewport } from '#tests/helpers/compiler/page-viewport/render'
import { typeCheckCompilerFiles } from '#tests/helpers/compiler/typecheck'

describe.each(['react', 'vue'] as const)('%s page viewport', (target) => {
  test('explicit fixed keeps every generated byte identical to a legacy page', () => {
    const { graph, pageId } = pageViewportGraph()
    const options = withDefaults({ target, devMode: false, packageName: 'legacy-viewport' })
    const legacy = compile({ graph, pageIds: [pageId], options })
    graph.updateNode(pageId, { lowcodePageViewport: { version: 1, mode: 'fixed' } })
    const fixed = compile({ graph, pageIds: [pageId], options })
    expect([...fixed.files]).toEqual([...legacy.files])
    expect(fixed.warnings).toEqual(legacy.warnings)
  })

  test('empty viewport bounds warn and retain the legacy project bytes', () => {
    const { graph, pageId } = pageViewportGraph()
    for (const child of graph.getNode(pageId)?.childIds ?? []) graph.deleteNode(child)
    const options = withDefaults({ target, devMode: true, packageName: 'empty-viewport' })
    const legacy = compile({ graph, pageIds: [pageId], options })
    graph.updateNode(pageId, { lowcodePageViewport: { version: 1, mode: 'responsive' } })
    const empty = compile({ graph, pageIds: [pageId], options })
    expect([...empty.files]).toEqual([...legacy.files])
    expect(empty.warnings.some((warning) => warning.code === 'page-viewport-bounds-invalid')).toBe(
      true
    )
  })

  test('multi-page imports and cross-breakpoint effective frame layouts type-check as emitted', () => {
    const { graph, pageId } = pageViewportGraph('fit-width')
    const details = graph.addPage('Details')
    graph.updateNode(details.id, { lowcodePageViewport: { version: 1, mode: 'responsive' } })
    graph.createNode('FRAME', details.id, { width: 400, height: 600, layoutMode: 'VERTICAL' })
    const output = compile({
      graph,
      pageIds: [pageId, details.id],
      options: withDefaults({
        target,
        devMode: true,
        packageName: 'viewport-routes',
        router: target === 'react' ? 'react-router-v6' : 'vue-router-v4'
      })
    })
    expect(output.warnings).toEqual([])
    typeCheckCompilerFiles(
      new Map(
        [...output.files].filter((entry): entry is [string, string] => typeof entry[1] === 'string')
      ),
      target,
      target === 'react'
        ? { preserveSymlinks: true, extraDependencies: ['react-router', '@remix-run/router'] }
        : {}
    )
    const bands = pageViewportBandsFixture(target, true)
    expect(bands.warnings).toEqual([])
    typeCheckCompilerFiles(
      new Map(
        [...bands.files].filter((entry): entry is [string, string] => typeof entry[1] === 'string')
      ),
      target
    )
  }, 60000)

  test.each(['fit-width', 'responsive'] as const)(
    '%s emits a runnable viewport shell',
    (mode) => {
      const output = pageViewportFixture(target, mode)
      expect(output.files.has('src/lib/open-pencil-page-viewport.ts')).toBe(true)
      expect(output.warnings).toEqual([])
      typeCheckCompilerFiles(
        new Map(
          [...output.files].filter(
            (entry): entry is [string, string] => typeof entry[1] === 'string'
          )
        ),
        target
      )
      const dev = pageViewportFixture(target, mode, true)
      typeCheckCompilerFiles(
        new Map(
          [...dev.files].filter((entry): entry is [string, string] => typeof entry[1] === 'string')
        ),
        target
      )
    },
    60000
  )

  test.each(['fit-width', 'responsive'] as const)(
    '%s generated components render real page markers, state and background',
    async (mode) => {
      const html = await renderPageViewport(target, mode)
      expect(html).toContain(`data-op-page-viewport="${mode}"`)
      expect(html).toContain('data-node-id=')
      expect(html).toContain('Count 0')
      expect(html).toContain('Last action')
      expect(html).toContain('background-color:#1A334D')
      expect(html).not.toMatch(/data-op-page-viewport-host[^>]*data-node-id=/)
      if (mode === 'fit-width') {
        expect(html).toContain('width:800px;height:1200px;min-height:0')
        expect(html).toContain('left:80px;top:40px;width:0;height:0')
      } else {
        expect(html).toContain('position:relative;')
        expect(html).toContain('left:0px;')
        expect(html).toContain('top:0px;')
        expect(html).toContain('--op-page-frame-height-')
        expect(html).toContain(':auto}')
      }
    }
  )
})

test('responsive projection changes only top-level design-frame presentation and leaves authored IR intact', () => {
  const { graph, pageId, frameId } = pageViewportGraph('responsive')
  const shape = graph.createNode('RECTANGLE', pageId, { x: -100, y: 200, width: 30, height: 40 })
  const ir = collectTree(graph, pageId)
  const before = JSON.stringify(ir)
  const projected = pageViewportNodes(ir)
  expect(JSON.stringify(ir)).toBe(before)
  const frame = projected.find((node) => node.kind === 'element' && node.sourceId === frameId)
  expect(frame?.kind).toBe('element')
  if (frame?.kind !== 'element') throw new Error('Frame fixture was not collected')
  expect(frame.attrs.style).toMatchObject({
    kind: 'styleAttr',
    declarations: { position: 'relative', width: '100%' }
  })
  const originalFrame = ir.children.find(
    (node) => node.kind === 'element' && node.sourceId === frameId
  )
  if (originalFrame?.kind !== 'element') throw new Error('Original frame fixture was not collected')
  expect(frame.children).toBe(originalFrame.children)
  const shapeBefore = ir.children.find(
    (node) => node.kind === 'element' && node.sourceId === shape.id
  )
  expect(projected.find((node) => node.kind === 'element' && node.sourceId === shape.id)).toBe(
    shapeBefore
  )
})
